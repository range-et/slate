import * as fs from 'fs/promises';
import * as os from 'os';
import * as path from 'path';
import * as ts from 'typescript';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import { SlateMcpServer } from '../vscode-extension/src/mcp/slate_mcp_server';
import { credentialPairingKey } from '../vscode-extension/src/llama_transport';
import { portTsProject } from '../vscode-extension/src/port/ts_importer';
import { emptyLayout, serializeLayout, serializeNode } from '../vscode-extension/src/slate_folder';
import { startFakeLlamaServer } from './support/fake_llama_server';

const REPO_ROOT = path.resolve(__dirname, '..');

describe('Stage 1 TypeScript self-hosting gate', () => {
    let tmpDir: string;
    let server: SlateMcpServer;
    let approvedPairings: Set<string>;

    beforeEach(async () => {
        tmpDir = await fs.mkdtemp(path.join(os.tmpdir(), 'slate-stage1-selfhost-'));
        await fs.mkdir(path.join(tmpDir, 'slate', 'nodes'), { recursive: true });
        await fs.mkdir(path.join(tmpDir, 'slate', 'flows'), { recursive: true });
        approvedPairings = new Set<string>();
        server = new SlateMcpServer(tmpDir, undefined, {
            isTrusted: true,
            approvedCredentialPairings: approvedPairings,
        });
    });

    afterEach(async () => {
        await fs.rm(tmpDir, { recursive: true, force: true });
    });

    it('ports real Slate TypeScript modules, resolves AST references, and compiles back to generated .ts', async () => {
        const sourcePaths = [
            'src/harness/palette.ts',
            'src/harness/health.ts',
            'vscode-extension/src/search.ts',
        ];
        const files = new Map<string, string>();
        for (const rel of sourcePaths) {
            files.set(rel, await fs.readFile(path.join(REPO_ROOT, rel), 'utf8'));
        }

        const ported = portTsProject(files, 'typescript');
        expect(ported.nodes.size).toBeGreaterThanOrEqual(5);

        await fs.writeFile(
            path.join(tmpDir, 'slate', 'slate.json'),
            JSON.stringify({ slate: 3, name: 'slate_selfhost', language: 'typescript', compile: { outDir: 'compiled-selfhost' } }, null, 2),
            'utf8',
        );
        await fs.writeFile(path.join(tmpDir, 'slate', 'layout.json'), serializeLayout(emptyLayout()), 'utf8');

        for (const [nodeId, node] of ported.nodes.entries()) {
            const full = path.join(tmpDir, 'slate', 'nodes', `${nodeId}.json`);
            await fs.mkdir(path.dirname(full), { recursive: true });
            await fs.writeFile(full, serializeNode(node), 'utf8');
        }

        const summaryRes = await server.callTool('slate_references', {});
        expect(summaryRes.isError).toBe(false);
        const summary = JSON.parse(summaryRes.content[0].text);
        expect(summary.totalNodes).toBe(ported.nodes.size);

        // Verify a helper from src/harness/palette.ts or vscode-extension/src/search.ts has tracked references
        const scoreMatchId = Array.from(ported.nodes.keys()).find(id => id.endsWith('/scoreMatch') || id === 'scoreMatch');
        expect(scoreMatchId).toBeDefined();
        const scoreRefsRes = await server.callTool('slate_references', { nodeId: scoreMatchId });
        expect(scoreRefsRes.isError).toBe(false);
        const scoreRefs = JSON.parse(scoreRefsRes.content[0].text);
        expect(scoreRefs.language).toBe('typescript');
        expect(scoreRefs.dependencyCount).toBeGreaterThanOrEqual(1);
        expect(scoreRefs.usedBy.length).toBeGreaterThanOrEqual(1);

        const compileRes = await server.callTool('slate_compile', { dryRun: false });
        expect(compileRes.isError).toBe(false);
        const compiled = JSON.parse(compileRes.content[0].text);
        expect(compiled.ok).toBe(true);
        expect(compiled.fileCount).toBeGreaterThanOrEqual(2);
        expect(compiled.diagnostics.filter((d: any) => d.severity === 'error')).toEqual([]);

        const compiledPaletteRel = compiled.files.find((f: string) => f.includes('palette'));
        expect(compiledPaletteRel).toBeDefined();
        const compiledPaletteText = await fs.readFile(path.join(tmpDir, 'compiled-selfhost', compiledPaletteRel), 'utf8');
        expect(compiledPaletteText).toContain('// Generated by Slate');
        expect(compiledPaletteText).toContain('scoreMatch');
    });

    it('runs end-to-end Two-Tier TS MCP loop: define stubs -> OpenRouter-style batch forge with retry -> compile & execute', async () => {
        await fs.writeFile(
            path.join(tmpDir, 'slate', 'slate.json'),
            JSON.stringify({ slate: 3, name: 'stage1_loop', language: 'typescript', compile: { outDir: 'dist-ts' } }, null, 2),
            'utf8',
        );
        await fs.writeFile(path.join(tmpDir, 'slate', 'layout.json'), serializeLayout(emptyLayout()), 'utf8');

        const stubRes = await server.callTool('slate_define_stub', {
            stubs: [
                {
                    name: 'clampScore',
                    signature: 'export function clampScore(value: number, max: number): number',
                    intent: 'Clamp numeric score cleanly between 0 and max',
                    contract: 'Returns 0 when max <= 0, otherwise Math.min(max, Math.max(0, value))',
                    modulePath: 'scoring.ts',
                    extension: '.ts',
                    cases: [
                        { name: 'normal', input: { value: 42, max: 100 }, expected: 42 },
                        { name: 'above_max', input: { value: 150, max: 100 }, expected: 100 },
                        { name: 'below_zero', input: { value: -5, max: 100 }, expected: 0 },
                    ],
                },
                {
                    name: 'formatPercent',
                    signature: 'export function formatPercent(value: number, max: number): string',
                    intent: 'Format clamped score percentage using clampScore and Math.round',
                    contract: 'Returns "<pct>%" string rounded to nearest integer',
                    context: ['clampScore'],
                    modulePath: 'scoring.ts',
                    extension: '.ts',
                    cases: [
                        { name: 'capped', input: { value: 150, max: 100 }, expected: '100%' },
                        { name: 'half', input: { value: 50, max: 100 }, expected: '50%' },
                    ],
                },
                {
                    name: 'ui/ScoreBadge',
                    signature: 'export function ScoreBadge(label: string): JSX.Element',
                    intent: 'Render score badge element',
                    modulePath: 'ScoreBadge.tsx',
                    extension: '.tsx',
                },
            ],
        });
        expect(stubRes.isError).toBe(false);

        let clampAttempts = 0;
        const observedPrompts: string[] = [];
        const fakeServer = await startFakeLlamaServer(req => {
            const prompt = String((req as any).messages?.[1]?.content ?? '');
            observedPrompts.push(prompt);
            if (prompt.includes('### Target stub: clampScore')) {
                clampAttempts += 1;
                if (clampAttempts === 1) {
                    // Attempt 1 intentionally fails runtime structured cases to exercise bounded retry feedback
                    return [[
                        '### Implementation',
                        '```ts',
                        'export function clampScore(value: number, max: number): number {',
                        '    return value;',
                        '}',
                        '```',
                        '### Unit Check',
                        '```ts',
                        "test('clampScore', () => {",
                        '    expect(clampScore(42, 100)).toBe(42);',
                        '});',
                        '```',
                    ].join('\n')];
                }
                return [[
                    '### Implementation',
                    '```ts',
                    'export function clampScore(value: number, max: number): number {',
                    '    if (max <= 0) return 0;',
                    '    return Math.min(max, Math.max(0, value));',
                    '}',
                    '```',
                    '### Unit Check',
                    '```ts',
                    "test('clampScore', () => {",
                    '    expect(clampScore(150, 100)).toBe(100);',
                    '    expect(clampScore(-5, 100)).toBe(0);',
                    '});',
                    '```',
                ].join('\n')];
            }
            if (prompt.includes('### Target stub: formatPercent')) {
                return [[
                    '### Implementation',
                    '```ts',
                    'export function formatPercent(value: number, max: number): string {',
                    '    if (max <= 0) return "0%";',
                    '    const clamped = clampScore(value, max);',
                    '    return `${Math.round((clamped / max) * 100)}%`;',
                    '}',
                    '```',
                    '### Unit Check',
                    '```ts',
                    "test('formatPercent', () => {",
                    "    expect(formatPercent(50, 100)).toBe('50%');",
                    "    expect(formatPercent(150, 100)).toBe('100%');",
                    '});',
                    '```',
                ].join('\n')];
            }
            return [[
                '### Implementation',
                '```tsx',
                'export function ScoreBadge(label: string): JSX.Element {',
                '    return <span>{label}</span>;',
                '}',
                '```',
                '### Unit Check',
                '```tsx',
                "test('ScoreBadge', () => {",
                "    expect(typeof ScoreBadge).toBe('function');",
                '});',
                '```',
            ].join('\n')];
        }, { requiredAuth: 'Bearer fake-stage1-key' });
        approvedPairings.add(credentialPairingKey(fakeServer.url, 'SLATE_STAGE1_KEY'));

        const prevEnv = process.env.SLATE_STAGE1_KEY;
        process.env.SLATE_STAGE1_KEY = 'fake-stage1-key';
        try {
            // Wave 1: independent leaf nodes in parallel (clampScore + ui/ScoreBadge)
            const wave1Res = await server.callTool('slate_forge_batch', {
                nodeIds: ['clampScore', 'ui/ScoreBadge'],
                concurrency: 2,
                maxRevisions: 2,
                verify: true,
                write: true,
                endpoint: fakeServer.url,
                model: 'qwen/qwen3-coder-30b-a3b-instruct',
                apiKeyEnv: 'SLATE_STAGE1_KEY',
            });
            expect(wave1Res.isError).toBe(false);
            const wave1 = JSON.parse(wave1Res.content[0].text);
            expect(wave1.ok, JSON.stringify(wave1)).toBe(true);
            expect(wave1.forgedCount).toBe(2);
            expect(wave1.failedCount).toBe(0);

            const clampResult = wave1.results.find((r: any) => r.nodeId === 'clampScore');
            expect(clampResult.attempts).toBe(2);
            expect(clampResult.verification.state).toBe('passed');
            expect(clampResult.verification.pydanticValid).toBe(true);
            expect(clampResult.estimatedInputTokens).toBeLessThanOrEqual(600);

            // Wave 2: dependent node (formatPercent consumes newly forged clampScore)
            const wave2Res = await server.callTool('slate_forge_batch', {
                nodeIds: ['formatPercent'],
                concurrency: 1,
                maxRevisions: 2,
                verify: true,
                write: true,
                endpoint: fakeServer.url,
                model: 'qwen/qwen3-coder-30b-a3b-instruct',
                apiKeyEnv: 'SLATE_STAGE1_KEY',
            });
            expect(wave2Res.isError).toBe(false);
            const wave2 = JSON.parse(wave2Res.content[0].text);
            expect(wave2.ok).toBe(true);
            expect(wave2.forgedCount).toBe(1);
            expect(wave2.failedCount).toBe(0);

            // Confirm retry prompt included failure feedback and formatPercent included clampScore neighbor signature
            expect(observedPrompts.some(p => p.includes('### Target stub: clampScore') && p.includes('Bounded Retry Feedback'))).toBe(true);
            expect(observedPrompts.some(p => p.includes('### Target stub: formatPercent') && p.includes('Dependency: clampScore'))).toBe(true);

            // Check updated slate/nodes on disk
            const persistedClamp = JSON.parse(await fs.readFile(path.join(tmpDir, 'slate', 'nodes', 'clampScore.json'), 'utf8'));
            expect(persistedClamp.verification.state).toBe('passed');
            expect(persistedClamp.code.join('\n')).toContain('Math.min(max');

            // Compile into dist-ts and verify runtime execution of compiled TS module
            const compileRes = await server.callTool('slate_compile', { outDir: 'dist-ts' });
            expect(compileRes.isError).toBe(false);
            const compiled = JSON.parse(compileRes.content[0].text);
            expect(compiled.ok).toBe(true);
            expect(compiled.files).toContain('scoring.ts');
            expect(compiled.files).toContain('ScoreBadge.tsx');

            const scoringSource = await fs.readFile(path.join(tmpDir, 'dist-ts', 'scoring.ts'), 'utf8');
            expect(scoringSource).toContain('// Generated by Slate');
            const jsOut = ts.transpileModule(scoringSource, {
                compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS },
            }).outputText;
            const mod: { exports: Record<string, any> } = { exports: {} };
            const fn = new Function('exports', 'module', jsOut);
            fn(mod.exports, mod);
            expect(mod.exports.clampScore(150, 100)).toBe(100);
            expect(mod.exports.formatPercent(150, 100)).toBe('100%');
            expect(mod.exports.formatPercent(-5, 100)).toBe('0%');
        } finally {
            if (prevEnv === undefined) delete process.env.SLATE_STAGE1_KEY;
            else process.env.SLATE_STAGE1_KEY = prevEnv;
            await fakeServer.close();
        }
    }, 20_000);
});
