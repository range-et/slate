import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import { describe, expect, it } from 'vitest';
import {
    inspectCompiledPythonImports,
    isExtensionBuildStale,
    runBenchmarkOffload,
} from '../scripts/benchmark-offload.mjs';
import { SlateMcpServer } from '../vscode-extension/src/mcp/slate_mcp_server';
import { portPythonProject } from '../vscode-extension/src/port/python_importer';
import { parseNode, serializeConfig, serializeNode } from '../vscode-extension/src/slate_folder';
import { resolvePythonPath } from '../vscode-extension/src/verification_runner';

describe('Two-tier offload benchmark harness (scripts/benchmark-offload.mjs)', () => {
    it('executes the Scientific Calculator spec end-to-end in 1 batch / 2 waves with 0 Frontier implementation LOC', async () => {
        const scorecard = await runBenchmarkOffload({
            specPath: 'benchmarks/specs/sci_calc.json',
            provider: 'fake',
            concurrency: 2,
            maxRevisions: 2,
            slateModules: {
                SlateMcpServer,
                portPythonProject,
                parseNode,
                serializeConfig,
                serializeNode,
                resolvePythonPath,
            },
        });

        expect(
            scorecard.ok,
            JSON.stringify({
                forgedCount: scorecard.forgedCount,
                failedCount: scorecard.failedCount,
                skippedCount: scorecard.skippedCount,
                compileOk: scorecard.compileOk,
                pytestPassed: scorecard.pytestPassed,
                pytestOutput: scorecard.pytestOutput,
                results: scorecard.results,
            }, null, 2),
        ).toBe(true);
        expect(scorecard.batchesRun).toBe(1);
        expect(scorecard.waves).toBe(2);
        expect(scorecard.forgedCount).toBe(9);
        expect(scorecard.failedCount).toBe(0);
        expect(scorecard.skippedCount).toBe(0);
        expect(scorecard.frontierImplLoc).toBe(0);
        expect(scorecard.tier2ForgedCodeLoc).toBeGreaterThan(20);
        expect(scorecard.duplicateImportCount).toBe(0);
        expect(scorecard.compileOk).toBe(true);
        expect(scorecard.pytestPassed).toBe(true);
        expect(scorecard.mcpReplyEstTokens).toBeLessThan(2500);
        expect(scorecard.forgeReplyEstTokens).toBeLessThan(1500);
    }, 60_000);

    it('detects duplicate and mid-file top-level Python imports cleanly', () => {
        const clean = inspectCompiledPythonImports({
            'scientific.py': '# Generated by Slate\nimport math\n\ndef f(x):\n    return math.sqrt(x)\n',
        });
        expect(clean.duplicateImportCount).toBe(0);

        const dirty = inspectCompiledPythonImports({
            'scientific.py': '# Generated by Slate\nimport math\n\ndef f(x):\n    return math.sqrt(x)\n\nimport math\ndef g(x):\n    return math.cos(x)\n',
        });
        expect(dirty.duplicateImportCount).toBe(1);
    });

    it('detects missing and stale extension builds relative to source timestamps', () => {
        const tmpRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'slate-stale-build-'));
        try {
            const srcFile = path.join(tmpRoot, 'vscode-extension', 'src', 'batch_forge.ts');
            fs.mkdirSync(path.dirname(srcFile), { recursive: true });
            fs.writeFileSync(srcFile, 'export const v = 1;\n', 'utf8');

            // Missing outputs => stale
            expect(isExtensionBuildStale(tmpRoot)).toBe(true);

            const required = [
                path.join('mcp', 'slate_mcp_server.js'),
                path.join('port', 'python_importer.js'),
                'verification_runner.js',
                'slate_folder.js',
            ];
            const outDir = path.join(tmpRoot, 'vscode-extension', 'out');
            for (const rel of required) {
                const full = path.join(outDir, rel);
                fs.mkdirSync(path.dirname(full), { recursive: true });
                fs.writeFileSync(full, '// compiled\n', 'utf8');
            }

            // Force source newer than out => stale
            const tOld = new Date(1_700_000_000_000);
            const tNew = new Date(1_700_000_060_000);
            for (const rel of required) {
                fs.utimesSync(path.join(outDir, rel), tOld, tOld);
            }
            fs.utimesSync(srcFile, tNew, tNew);
            expect(isExtensionBuildStale(tmpRoot)).toBe(true);

            // Update out newer than source => fresh
            const tFresher = new Date(1_700_000_120_000);
            for (const rel of required) {
                fs.utimesSync(path.join(outDir, rel), tFresher, tFresher);
            }
            expect(isExtensionBuildStale(tmpRoot)).toBe(false);
        } finally {
            fs.rmSync(tmpRoot, { recursive: true, force: true });
        }
    });
});
