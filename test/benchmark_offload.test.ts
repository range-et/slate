import { describe, expect, it } from 'vitest';
import { inspectCompiledPythonImports, runBenchmarkOffload } from '../scripts/benchmark-offload.mjs';

describe('Two-tier offload benchmark harness (scripts/benchmark-offload.mjs)', () => {
    it('executes the Scientific Calculator spec end-to-end in 1 batch / 2 waves with 0 Frontier implementation LOC', async () => {
        const scorecard = await runBenchmarkOffload({
            specPath: 'benchmarks/specs/sci_calc.json',
            provider: 'fake',
            concurrency: 2,
            maxRevisions: 2,
        });

        expect(
            scorecard.ok,
            JSON.stringify({
                forgedCount: scorecard.forgedCount,
                failedCount: scorecard.failedCount,
                skippedCount: scorecard.skippedCount,
                compileOk: scorecard.compileOk,
                pytestPassed: scorecard.pytestPassed,
                pytestOutput: scorecard.pytestOutput,
                results: scorecard.results,
            }, null, 2),
        ).toBe(true);
        expect(scorecard.batchesRun).toBe(1);
        expect(scorecard.waves).toBe(2);
        expect(scorecard.forgedCount).toBe(9);
        expect(scorecard.failedCount).toBe(0);
        expect(scorecard.skippedCount).toBe(0);
        expect(scorecard.frontierImplLoc).toBe(0);
        expect(scorecard.tier2ForgedCodeLoc).toBeGreaterThan(20);
        expect(scorecard.duplicateImportCount).toBe(0);
        expect(scorecard.compileOk).toBe(true);
        expect(scorecard.pytestPassed).toBe(true);
        expect(scorecard.mcpReplyEstTokens).toBeLessThan(2500);
        expect(scorecard.forgeReplyEstTokens).toBeLessThan(1500);
    }, 60_000);

    it('detects duplicate and mid-file top-level Python imports cleanly', () => {
        const clean = inspectCompiledPythonImports({
            'scientific.py': '# Generated by Slate\nimport math\n\ndef f(x):\n    return math.sqrt(x)\n',
        });
        expect(clean.duplicateImportCount).toBe(0);

        const dirty = inspectCompiledPythonImports({
            'scientific.py': '# Generated by Slate\nimport math\n\ndef f(x):\n    return math.sqrt(x)\n\nimport math\ndef g(x):\n    return math.cos(x)\n',
        });
        expect(dirty.duplicateImportCount).toBe(1);
    });
});
