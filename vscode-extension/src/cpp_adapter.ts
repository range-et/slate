function stableId(documentPath: string, kind: ParsedUnit['kind'], qualifiedName: string): string {
    const hex = createHash('sha1').update(`slate:${documentPath}:${kind}:${qualifiedName}`).digest('hex');
    return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-5${hex.slice(13, 16)}-a${hex.slice(17, 20)}-${hex.slice(20, 32)}`;
}

function lineStarts(source: string): number[] {
    const starts = [0];
    for (let index = 0; index < source.length; index++) {
        if (source[index] === '\n') starts.push(index + 1);
    }
    return starts;
}

function positionAt(starts: number[], offset: number): SourcePosition {
    const clamped = Math.max(0, Math.min(offset, starts.length > 0 ? Number.MAX_SAFE_INTEGER : 0));
    let low = 0;
    let high = starts.length;
    while (low + 1 < high) {
        const middle = Math.floor((low + high) / 2);
        if (starts[middle] <= clamped) low = middle;
        else high = middle;
    }
    return { line: low, character: clamped - starts[low] };
}

function rangeAt(starts: number[], from: number, to: number): SourceRange {
    return { start: positionAt(starts, from), end: positionAt(starts, Math.max(from, to)) };
}

function declarationIndent(source: string, from: number): string {
    const lineStart = source.lastIndexOf('\n', from - 1) + 1;
    return source.slice(lineStart, from).match(/^[ \t]*/)?.[0] ?? '';
}

function indentBlock(value: string, indent: string): string {
    return value.split('\n').map((line, index) => index === 0 ? line : `${indent}${line}`).join('\n');
}

/**
 * Replace comments and string/character literals with spaces (preserving newlines and length)
 * so brace/parenthesis scanning and declaration matching operate on exact UTF-16 offsets.
 */
function maskCommentsAndStrings(source: string): {
    masked: string;
    unclosedOffset: number | null;
    unclosedMessage: string | null;
} {
    const chars = source.split('');
    const len = source.length;
    let i = 0;
    while (i < len) {
        const ch = source[i];
        const next = source[i + 1];

        // Line comment //
        if (ch === '/' && next === '/') {
            chars[i] = ' ';
            chars[i + 1] = ' ';
            i += 2;
            while (i < len && source[i] !== '\n') {
                if (chars[i] !== '\r') chars[i] = ' ';
                i++;
            }
            continue;
        }

        // Block comment /* ... */
        if (ch === '/' && next === '*') {
            const startOffset = i;
            chars[i] = ' ';
            chars[i + 1] = ' ';
            i += 2;
            let closed = false;
            while (i < len) {
                if (source[i] === '*' && source[i + 1] === '/') {
                    chars[i] = ' ';
                    chars[i + 1] = ' ';
                    i += 2;
                    closed = true;
                    break;
                }
                if (source[i] !== '\n' && source[i] !== '\r') chars[i] = ' ';
                i++;
            }
            if (!closed) {
                return {
                    masked: chars.join(''),
                    unclosedOffset: startOffset,
                    unclosedMessage: 'Unclosed block comment in C++ source.',
                };
            }
            continue;
        }

        // String literal "..."
        if (ch === '"') {
            const startOffset = i;
            chars[i] = ' ';
            i++;
            let closed = false;
            while (i < len) {
                if (source[i] === '\\') {
                    if (source[i] !== '\n' && source[i] !== '\r') chars[i] = ' ';
                    if (i + 1 < len && source[i + 1] !== '\n' && source[i + 1] !== '\r') {
                        chars[i + 1] = ' ';
                    }
                    i += 2;
                    continue;
                }
                if (source[i] === '"') {
                    chars[i] = ' ';
                    i++;
                    closed = true;
                    break;
                }
                if (source[i] === '\n') {
                    break;
                }
                if (source[i] !== '\r') chars[i] = ' ';
                i++;
            }
            if (!closed) {
                return {
                    masked: chars.join(''),
                    unclosedOffset: startOffset,
                    unclosedMessage: 'Unclosed string literal in C++ source.',
                };
            }
            continue;
        }

        // Character literal '...' (ignoring C++14 numeric separators like 1'000)
        if (ch === "'") {
            const prev = i > 0 ? source[i - 1] : '';
            if (/[0-9A-Za-z_]/.test(prev) && next && /[0-9A-Za-z_]/.test(next)) {
                i++;
                continue;
            }
            const startOffset = i;
            chars[i] = ' ';
            i++;
            let closed = false;
            while (i < len) {
                if (source[i] === '\\') {
                    if (source[i] !== '\n' && source[i] !== '\r') chars[i] = ' ';
                    if (i + 1 < len && source[i + 1] !== '\n' && source[i + 1] !== '\r') {
                        chars[i + 1] = ' ';
                    }
                    i += 2;
                    continue;
                }
                if (source[i] === "'") {
                    chars[i] = ' ';
                    i++;
                    closed = true;
                    break;
                }
                if (source[i] === '\n') {
                    break;
                }
                if (source[i] !== '\r') chars[i] = ' ';
                i++;
            }
            if (!closed) {
                return {
                    masked: chars.join(''),
                    unclosedOffset: startOffset,
                    unclosedMessage: 'Unclosed character literal in C++ source.',
                };
            }
            continue;
        }

        i++;
    }

    return { masked: chars.join(''), unclosedOffset: null, unclosedMessage: null };
}

/** Check balanced braces/parens/brackets on masked source. */
function checkBalancedDelimiters(masked: string): { offset: number; message: string } | null {
    const stack: Array<{ ch: string; expected: string; offset: number }> = [];
    for (let i = 0; i < masked.length; i++) {
        const ch = masked[i];
        if (ch === '{') stack.push({ ch, expected: '}', offset: i });
        else if (ch === '(') stack.push({ ch, expected: ')', offset: i });
        else if (ch === '[') stack.push({ ch, expected: ']', offset: i });
        else if (ch === '}' || ch === ')' || ch === ']') {
            const top = stack.pop();
            if (!top || top.expected !== ch) {
                return {
                    offset: i,
                    message: `Unexpected closing '${ch}' in C++ source.`,
                };
            }
        }
    }
    if (stack.length > 0) {
        const top = stack[stack.length - 1];
        return {
            offset: top.offset,
            message: `Unclosed '${top.ch}' in C++ source; expected '${top.expected}'.`,
        };
    }
    return null;
}

function findMatchingPair(masked: string, openIndex: number, openChar: string, closeChar: string): number {
    let depth = 0;
    for (let i = openIndex; i < masked.length; i++) {
        if (masked[i] === openChar) depth++;
        else if (masked[i] === closeChar) {
            depth--;
            if (depth === 0) return i;
        }
    }
    return -1;
}

function normalizeCppType(rawType: string): string {
    return rawType
        .replace(/\s+/g, ' ')
        .replace(/\s*([*&])\s*/g, '$1 ')
        .replace(/\s+([,>])/g, '$1')
        .replace(/<\s+/g, '<')
        .trim();
}

function normalizeParametersText(raw: string): string {
    const trimmed = raw.replace(/\r\n/g, '\n').replace(/\r/g, '\n').trim();
    if (!trimmed || trimmed === 'void') return '';
    return trimmed
        .split('\n')
        .map(line => line.trim())
        .filter(Boolean)
        .join(' ');
}

function splitTopLevelCsv(raw: string): string[] {
    const items: string[] = [];
    let current = '';
    let parenDepth = 0;
    let bracketDepth = 0;
    let braceDepth = 0;
    let angleDepth = 0;
    let seenEquals = false;
    let quote: '"' | "'" | null = null;

    for (let i = 0; i < raw.length; i++) {
        const ch = raw[i];
        if (quote) {
            current += ch;
            if (ch === quote && raw[i - 1] !== '\\') quote = null;
            continue;
        }
        if (ch === '"' || ch === "'") {
            quote = ch;
            current += ch;
            continue;
        }
        if (ch === '(') parenDepth++;
        else if (ch === ')') parenDepth = Math.max(0, parenDepth - 1);
        else if (ch === '[') bracketDepth++;
        else if (ch === ']') bracketDepth = Math.max(0, bracketDepth - 1);
        else if (ch === '{') braceDepth++;
        else if (ch === '}') braceDepth = Math.max(0, braceDepth - 1);
        else if (!seenEquals && ch === '<') angleDepth++;
        else if (!seenEquals && ch === '>') angleDepth = Math.max(0, angleDepth - 1);
        else if (ch === '=' && parenDepth === 0 && bracketDepth === 0 && braceDepth === 0 && angleDepth === 0) {
            seenEquals = true;
        } else if (ch === ',' && parenDepth === 0 && bracketDepth === 0 && braceDepth === 0 && angleDepth === 0) {
            if (current.trim()) items.push(current.trim());
            current = '';
            seenEquals = false;
            continue;
        }
        current += ch;
    }
    if (current.trim()) items.push(current.trim());
    return items;
}

function findTopLevelEquals(entry: string): number {
    let parenDepth = 0;
    let bracketDepth = 0;
    let braceDepth = 0;
    let angleDepth = 0;
    let quote: '"' | "'" | null = null;

    for (let i = 0; i < entry.length; i++) {
        const ch = entry[i];
        if (quote) {
            if (ch === quote && entry[i - 1] !== '\\') quote = null;
            continue;
        }
        if (ch === '"' || ch === "'") {
            quote = ch;
            continue;
        }
        if (ch === '(') parenDepth++;
        else if (ch === ')') parenDepth = Math.max(0, parenDepth - 1);
        else if (ch === '[') bracketDepth++;
        else if (ch === ']') bracketDepth = Math.max(0, bracketDepth - 1);
        else if (ch === '{') braceDepth++;
        else if (ch === '}') braceDepth = Math.max(0, braceDepth - 1);
        else if (ch === '<') angleDepth++;
        else if (ch === '>') angleDepth = Math.max(0, angleDepth - 1);
        else if (
            ch === '=' &&
            entry[i - 1] !== '!' &&
            entry[i - 1] !== '<' &&
            entry[i - 1] !== '>' &&
            entry[i - 1] !== '=' &&
            entry[i + 1] !== '=' &&
            parenDepth === 0 &&
            bracketDepth === 0 &&
            braceDepth === 0 &&
            angleDepth === 0
        ) {
            return i;
        }
    }
    return -1;
}

/**
 * Parse C++ / Arduino parameter list into structured `UnitParam[]`.
 * Handles pointers, references, `const`, templates (`std::vector<int>&`), array suffixes (`int buf[8]`),
 * variadic `...`, and default values (`int samples = 4`).
 */
export function parseCppParams(rawParams: string): UnitParam[] {
    const clean = rawParams.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/\/\/[^\n]*/g, ' ').trim();
    if (!clean || clean === 'void') return [];

    const entries = splitTopLevelCsv(clean);
    const params: UnitParam[] = [];

    for (const entry of entries) {
        if (entry === '...') {
            params.push({ name: 'args', annotation: '...', default: null, kind: 'var' });
            continue;
        }

        const eqIdx = findTopLevelEquals(entry);
        const declPart = (eqIdx >= 0 ? entry.slice(0, eqIdx) : entry).trim();
        const defaultVal = eqIdx >= 0 ? entry.slice(eqIdx + 1).trim() : null;

        // Check for array suffix e.g. `int values[4]` or `const char name[]`
        let arraySuffix = '';
        let baseDecl = declPart;
        const arrayMatch = baseDecl.match(/(\s*\[[^\]]*\])+$/);
        if (arrayMatch) {
            arraySuffix = arrayMatch[0].replace(/\s+/g, '');
            baseDecl = baseDecl.slice(0, baseDecl.length - arrayMatch[0].length).trim();
        }

        // Check for variadic pack `Args... rest`
        if (baseDecl.includes('...')) {
            const nameMatch = baseDecl.match(/([A-Za-z_][A-Za-z0-9_]*)$/);
            const name = nameMatch ? nameMatch[1] : 'args';
            const typePart = nameMatch ? baseDecl.slice(0, nameMatch.index).trim() : baseDecl;
            params.push({
                name,
                annotation: typePart ? normalizeCppType(typePart) : '...',
                default: defaultVal,
                kind: 'var',
            });
            continue;
        }

        // Extract trailing identifier
        const trailingName = baseDecl.match(/([A-Za-z_][A-Za-z0-9_]*)$/);
        if (!trailingName || trailingName.index === undefined) {
            continue;
        }

        const token = trailingName[1];
        const prefix = baseDecl.slice(0, trailingName.index).trim();

        if (!prefix) {
            // Single token: could be an untyped parameter name (e.g. `pin`)
            params.push({
                name: token,
                annotation: null,
                default: defaultVal,
                kind: 'keyword',
            });
            continue;
        }

        const annotation = normalizeCppType(`${prefix}${arraySuffix}`);
        params.push({
            name: token,
            annotation: annotation || null,
            default: defaultVal,
            kind: 'keyword',
        });
    }

    return params;
}

/**
 * Split `#include <...>` or `#include "..."` lines into structured `CppInclude` entries.
 */
export function splitCppInclude(statement: string): CppInclude[] {
    const includes: CppInclude[] = [];
    const lines = statement.replace(/\r\n?/g, '\n').split('\n');
    for (const rawLine of lines) {
        const trimmed = rawLine.trim();
        const match = trimmed.match(/^#\s*include\s*(<([^>]+)>|"([^"]+)")/);
        if (!match) continue;
        const system = Boolean(match[2]);
        const header = (match[2] ?? match[3]).trim();
        const line = system ? `#include <${header}>` : `#include "${header}"`;
        const base = header.split(/[\\/]/).pop() ?? header;
        const stem = base.replace(/\.(h|hpp|hh|hxx|ino|ipp)$/i, '');
        includes.push({
            line,
            header,
            system,
            binding: /^[A-Za-z_][A-Za-z0-9_]*$/.test(stem) ? stem : null,
        });
    }
    return includes;
}

/**
 * Extract all user/library identifier names referenced in a C++ source snippet.
 */
export function cppIdentifierNames(source: string): Set<string> {
    const withoutIncludes = source.replace(/^\s*#\s*include\s*(?:<[^>]+>|"[^"]+")/gm, '');
    const { masked } = maskCommentsAndStrings(withoutIncludes);
    const names = new Set<string>();
    const matches = masked.matchAll(/\b([A-Za-z_][A-Za-z0-9_]*)\b/g);
    for (const match of matches) {
        const ident = match[1];
        if (!CPP_KEYWORDS.has(ident)) {
            names.add(ident);
        }
    }
    return names;
}

/**
 * Extract top-level names bound by `#define`, global `const`/`constexpr`/variable declarations,
 * `typedef`/`using`, `struct`/`class`/`enum`, and functions.
 */
export function cppTopLevelBindings(source: string): Set<string> {
    const bindings = new Set<string>();
    const lines = source.replace(/\r\n?/g, '\n').split('\n');
    const nonPreprocLines: string[] = [];
    for (const rawLine of lines) {
        const trimmed = rawLine.trim();
        const defineMatch = trimmed.match(/^#\s*define\s+([A-Za-z_][A-Za-z0-9_]*)/);
        if (defineMatch) {
            bindings.add(defineMatch[1]);
        }
        if (trimmed.startsWith('#')) {
            nonPreprocLines.push('');
        } else {
            nonPreprocLines.push(rawLine);
        }
    }

    const cleanSource = nonPreprocLines.join('\n');
    const { masked } = maskCommentsAndStrings(cleanSource);
    // Find top-level statements at brace depth 0
    let depth = 0;
    let stmtStart = 0;
    for (let i = 0; i < masked.length; i++) {
        const ch = masked[i];
        if (ch === '{') {
            if (depth === 0) {
                const header = cleanSource.slice(stmtStart, i).trim();
                const structMatch = header.match(/\b(?:class|struct|enum(?:\s+class)?)\s+([A-Za-z_][A-Za-z0-9_]*)/);
                if (structMatch) {
                    bindings.add(structMatch[1]);
                } else {
                    const fnMatch = header.match(/([A-Za-z_][A-Za-z0-9_]*)\s*\([^;{}]*\)\s*(?:const\s*)?(?:noexcept\s*)?(?:override\s*)?$/);
                    if (fnMatch && !CONTROL_KEYWORDS.has(fnMatch[1])) {
                        bindings.add(fnMatch[1]);
                    }
                }
            }
            depth++;
        } else if (ch === '}') {
            depth = Math.max(0, depth - 1);
            if (depth === 0) stmtStart = i + 1;
        } else if (ch === ';' && depth === 0) {
            const stmt = cleanSource.slice(stmtStart, i).trim();
            stmtStart = i + 1;
            if (!stmt || stmt.startsWith('#')) continue;

            const usingAlias = stmt.match(/^using\s+([A-Za-z_][A-Za-z0-9_]*)\s*=/);
            if (usingAlias) {
                bindings.add(usingAlias[1]);
                continue;
            }
            const typedefMatch = stmt.match(/^typedef\s+.+\b([A-Za-z_][A-Za-z0-9_]*)\s*(?:\[[^\]]*\])?$/);
            if (typedefMatch) {
                bindings.add(typedefMatch[1]);
                continue;
            }
            // Global variable / constant e.g. `const int LED_PIN = 13` or `int counter`
            const eqIdx = findTopLevelEquals(stmt);
            const left = (eqIdx >= 0 ? stmt.slice(0, eqIdx) : stmt).trim();
            if (!left.endsWith(')')) {
                const varMatch = left.match(/\b([A-Za-z_][A-Za-z0-9_]*)\s*(?:\[[^\]]*\])*$/);
                if (varMatch && !CPP_KEYWORDS.has(varMatch[1])) {
                    const beforeVar = left.slice(0, varMatch.index).trim();
                    if (beforeVar.length > 0) {
                        bindings.add(varMatch[1]);
                    }
                }
            }
        }
    }

    return bindings;
}

function cleanReturnAnnotation(rawPrefix: string): { returnType: string | null; decorators: string[] } {
    const decorators: string[] = [];
    let cleaned = rawPrefix.trim();

    // Extract [[...]] attributes
    cleaned = cleaned.replace(/\[\[\s*([^\]]+?)\s*\]\]/g, (_full, attr: string) => {
        decorators.push(attr.trim());
        return ' ';
    });

    // Strip template<...> header from return type extraction
    cleaned = cleaned.replace(/^template\s*<[^>]*>\s*/g, '');

    // Strip leading access specifiers inside classes (`public:`, `private:`, `protected:`)
    cleaned = cleaned.replace(/^(?:public|private|protected)\s*:\s*/g, '');

    // Strip storage/function specifiers while keeping type tokens
    const tokens = cleaned.split(/\s+/).filter(Boolean);
    const kept: string[] = [];
    for (const token of tokens) {
        if (FUNCTION_MODIFIERS.has(token)) {
            if (token === 'IRAM_ATTR' || token === 'ICACHE_FLASH_ATTR' || token === 'ARDUINO_ISR_ATTR') {
                decorators.push(token);
            }
            continue;
        }
        kept.push(token);
    }

    const joined = normalizeCppType(kept.join(' '));
    return {
        returnType: joined || null,
        decorators,
    };
}

function scanDeclarationsInRange(
    source: string,
    masked: string,
    starts: number[],
    rangeFrom: number,
    rangeTo: number,
    documentPath: string,
    nodeName: string | undefined,
    nodeId: string | undefined,
    parent: ParsedUnit | null,
    units: ParsedUnit[],
    offsets: ParsedCppDetails['offsets'],
    namespaceStack: string[] = [],
    unitNamespaces: Map<string, string[]> = new Map(),
    namespaceSpans: CppNamespaceSpan[] = [],
): void {
    let pos = rangeFrom;

    while (pos < rangeTo) {
        // Skip whitespace and semicolons
        while (pos < rangeTo && /[\s;]/.test(masked[pos])) pos++;
        if (pos >= rangeTo) break;

        // Skip preprocessor directives (#include, #define, #ifdef, etc.)
        if (masked[pos] === '#') {
            while (pos < rangeTo && masked[pos] !== '\n') {
                if (masked[pos] === '\\' && pos + 1 < rangeTo) {
                    pos += 2;
                    continue;
                }
                pos++;
            }
            continue;
        }

        // Find next `{` or `;` at the current level
        let scan = pos;
        let parenDepth = 0;
        let foundBrace = -1;
        let foundSemi = -1;

        while (scan < rangeTo) {
            const ch = masked[scan];
            if (ch === '#' && parenDepth === 0 && scan === pos) {
                break;
            }
            if (ch === '(') parenDepth++;
            else if (ch === ')') parenDepth = Math.max(0, parenDepth - 1);
            else if (ch === '{' && parenDepth === 0) {
                foundBrace = scan;
                break;
            } else if (ch === ';' && parenDepth === 0) {
                foundSemi = scan;
                break;
            }
            scan++;
        }

        if (foundSemi >= 0 && (foundBrace < 0 || foundSemi < foundBrace)) {
            // A statement or forward declaration ending with `;`
            pos = foundSemi + 1;
            continue;
        }

        if (foundBrace < 0) {
            break;
        }

        const closeBrace = findMatchingPair(masked, foundBrace, '{', '}');
        if (closeBrace < 0) {
            break;
        }

        // Advance past any leading preprocessor lines inside [pos, foundBrace)
        let declStart = pos;
        while (declStart < foundBrace) {
            while (declStart < foundBrace && /\s/.test(masked[declStart])) declStart++;
            if (masked[declStart] === '#') {
                while (declStart < foundBrace && masked[declStart] !== '\n') {
                    if (masked[declStart] === '\\' && declStart + 1 < foundBrace) {
                        declStart += 2;
                        continue;
                    }
                    declStart++;
                }
            } else {
                break;
            }
        }
        while (declStart < foundBrace && /\s/.test(masked[declStart])) declStart++;

        // Strip leading access specifiers (`public:`, `private:`, `protected:`) inside class bodies
        const accessPrefix = masked.slice(declStart, foundBrace).match(/^(?:(?:public|private|protected)\s*:\s*)+/);
        if (accessPrefix) {
            declStart += accessPrefix[0].length;
        }

        const headerMasked = masked.slice(declStart, foundBrace);

        // 1. Check for `namespace ... { ... }` or `extern "C" { ... }`
        if (/^(?:inline\s+)?namespace\b/.test(headerMasked)) {
            const nsHeader = source.slice(declStart, foundBrace).replace(/\s+/g, ' ').trim();
            namespaceSpans.push({
                header: nsHeader,
                headerFrom: declStart,
                braceFrom: foundBrace,
                closeFrom: closeBrace,
            });
            namespaceStack.push(nsHeader);
            scanDeclarationsInRange(
                source,
                masked,
                starts,
                foundBrace + 1,
                closeBrace,
                documentPath,
                nodeName,
                nodeId,
                parent,
                units,
                offsets,
                namespaceStack,
                unitNamespaces,
                namespaceSpans,
            );
            namespaceStack.pop();
            pos = closeBrace + 1;
            continue;
        }
        if (/^extern\b/.test(headerMasked)) {
            scanDeclarationsInRange(
                source,
                masked,
                starts,
                foundBrace + 1,
                closeBrace,
                documentPath,
                nodeName,
                nodeId,
                parent,
                units,
                offsets,
                namespaceStack,
                unitNamespaces,
                namespaceSpans,
            );
            pos = closeBrace + 1;
            continue;
        }

        // 2. Check for `class` or `struct` definition
        const classMatch = headerMasked.match(
            /^(?:template\s*<[^>]*>\s*)?(class|struct)\s+([A-Za-z_][A-Za-z0-9_]*)\b/,
        );
        if (classMatch && !headerMasked.includes('(')) {
            const classKeyword = classMatch[1];
            const name = classMatch[2];
            const relNameStart = headerMasked.indexOf(name, classMatch[0].length - name.length);
            const nameFrom = declStart + relNameStart;
            const nameTo = nameFrom + name.length;

            let declTo = closeBrace + 1;
            while (declTo < rangeTo && /[ \t]/.test(masked[declTo])) declTo++;
            if (declTo < rangeTo && masked[declTo] === ';') declTo++;

            const kind: ParsedUnit['kind'] = parent ? 'nested_class' : 'class';
            const qualifiedName = parent ? `${parent.qualifiedName}.${name}` : name;
            const isNode = !parent && nodeName !== undefined && name === nodeName;
            const id = isNode ? nodeId! : stableId(documentPath, kind, qualifiedName);

            const unit: ParsedUnit = {
                id,
                identity: isNode ? 'durable' : 'provisional',
                kind,
                name,
                qualifiedName,
                parentId: parent?.id ?? null,
                ranges: {
                    name: rangeAt(starts, nameFrom, nameTo),
                    declaration: rangeAt(starts, declStart, declTo),
                },
                annotation: null,
                decorators: [],
                signature: `${classKeyword} ${name}`,
            };
            units.push(unit);
            offsets.set(id, { code: { from: declStart, to: declTo } });
            if (namespaceStack.length > 0 && !parent) {
                unitNamespaces.set(id, [...namespaceStack]);
            }

            scanDeclarationsInRange(
                source,
                masked,
                starts,
                foundBrace + 1,
                closeBrace,
                documentPath,
                nodeName,
                nodeId,
                unit,
                units,
                offsets,
                namespaceStack,
                unitNamespaces,
                namespaceSpans,
            );

            pos = declTo;
            continue;
        }

        // 3. Check for Function or Method definition: `<returnType> <name>(<params>) [qualifiers] { ... }`
        const openParen = headerMasked.indexOf('(');
        if (openParen >= 0) {
            const closeParenAbs = findMatchingPair(masked, declStart + openParen, '(', ')');
            if (closeParenAbs > declStart + openParen && closeParenAbs < foundBrace) {
                const beforeParen = source.slice(declStart, declStart + openParen);
                const afterParen = source.slice(closeParenAbs + 1, foundBrace).trim();

                // Extract function name (supports `foo` or `ClassName::foo` or `~ClassName`)
                const nameMatch = beforeParen.match(/(?:([A-Za-z_][A-Za-z0-9_]*)\s*::\s*)?(~?[A-Za-z_][A-Za-z0-9_]*)\s*$/);
                if (nameMatch && nameMatch.index !== undefined) {
                    const scopePrefix = nameMatch[1] ?? null;
                    const fnName = nameMatch[2];
                    if (!CONTROL_KEYWORDS.has(fnName)) {
                        const rawReturnPrefix = beforeParen.slice(0, nameMatch.index);
                        const { returnType: prefixReturn, decorators } = cleanReturnAnnotation(rawReturnPrefix);

                        // Check trailing return type `-> Type`
                        let returnAnnotation = prefixReturn;
                        const trailingReturnMatch = afterParen.match(/^->\s*([^{:;]+)$/);
                        if (trailingReturnMatch && (!returnAnnotation || returnAnnotation === 'auto')) {
                            returnAnnotation = normalizeCppType(trailingReturnMatch[1]);
                        }

                        const fnNameOffsetInMatch = nameMatch[0].lastIndexOf(fnName);
                        const nameFrom = declStart + nameMatch.index + fnNameOffsetInMatch;
                        const nameTo = nameFrom + fnName.length;
                        const declTo = closeBrace + 1;

                        const rawParams = source.slice(declStart + openParen + 1, closeParenAbs);
                        const parameters = normalizeParametersText(rawParams);
                        const structured = parseCppParams(rawParams);

                        const kind: ParsedUnit['kind'] = parent && (parent.kind === 'class' || parent.kind === 'nested_class')
                            ? 'method'
                            : scopePrefix
                                ? 'method'
                                : parent
                                    ? 'nested_function'
                                    : 'function';
                        const qualifiedName = parent
                            ? `${parent.qualifiedName}.${fnName}`
                            : scopePrefix
                                ? `${scopePrefix}.${fnName}`
                                : fnName;
                        const isNode = !parent && nodeName !== undefined && fnName === nodeName;
                        let id = isNode ? nodeId! : stableId(documentPath, kind, qualifiedName);
                        if (!isNode && offsets.has(id)) {
                            const paramSig = structured.map(p => (p.annotation ?? '').replace(/\s+/g, '')).join(',');
                            const overloaded = stableId(documentPath, kind, `${qualifiedName}(${paramSig})`);
                            id = overloaded;
                            if (offsets.has(id)) {
                                let n = 2;
                                while (offsets.has(`${overloaded}#${n}`)) n++;
                                id = `${overloaded}#${n}`;
                            }
                        }

                        const signature = `${returnAnnotation ? `${returnAnnotation} ` : ''}${fnName}(${parameters})`;

                        const unit: ParsedUnit = {
                            id,
                            identity: isNode ? 'durable' : 'provisional',
                            kind,
                            name: fnName,
                            qualifiedName,
                            parentId: parent?.id ?? null,
                            ranges: {
                                name: rangeAt(starts, nameFrom, nameTo),
                                declaration: rangeAt(starts, declStart, declTo),
                            },
                            annotation: null,
                            decorators,
                            async: false,
                            parameters,
                            params: structured,
                            returnAnnotation,
                            signature,
                        };
                        units.push(unit);
                        offsets.set(id, { code: { from: declStart, to: declTo } });
                        if (namespaceStack.length > 0 && !parent) {
                            unitNamespaces.set(id, [...namespaceStack]);
                        }
                        pos = declTo;
                        continue;
                    }
                }
            }
        }

        pos = closeBrace + 1;
    }
}

export function parseCppDetailed(source: string, documentPath = '<memory>', nodeId?: string): ParsedCppDetails {
    const starts = lineStarts(source);
    const { masked, unclosedOffset, unclosedMessage } = maskCommentsAndStrings(source);
    if (unclosedOffset !== null && unclosedMessage !== null) {
        return {
            path: documentPath,
            sourceHash: sourceHash(source),
            valid: false,
            units: [],
            diagnostics: [{
                code: 'cpp-syntax',
                message: unclosedMessage,
                range: rangeAt(starts, unclosedOffset, unclosedOffset + 1),
            }],
            offsets: new Map(),
            unitNamespaces: new Map(),
            namespaceSpans: [],
        };
    }

    const delimiterError = checkBalancedDelimiters(masked);
    if (delimiterError) {
        return {
            path: documentPath,
            sourceHash: sourceHash(source),
            valid: false,
            units: [],
            diagnostics: [{
                code: 'cpp-syntax',
                message: delimiterError.message,
                range: rangeAt(starts, delimiterError.offset, delimiterError.offset + 1),
            }],
            offsets: new Map(),
            unitNamespaces: new Map(),
            namespaceSpans: [],
        };
    }

    // Check for trailing garbage or statement without `;` or `{}` when non-preprocessor tokens exist
    const nonPreproc = masked
        .split('\n')
        .filter(line => !line.trim().startsWith('#'))
        .join('\n')
        .trim();
    if (nonPreproc.length > 0 && !/[;{}]/.test(nonPreproc)) {
        const firstTokenOffset = Math.max(0, masked.search(/\S/));
        return {
            path: documentPath,
            sourceHash: sourceHash(source),
            valid: false,
            units: [],
            diagnostics: [{
                code: 'cpp-syntax',
                message: 'Incomplete C++ declaration or statement (missing body or semicolon).',
                range: rangeAt(starts, firstTokenOffset, firstTokenOffset + 1),
            }],
            offsets: new Map(),
            unitNamespaces: new Map(),
            namespaceSpans: [],
        };
    }

    const nodeName = nodeId?.split('/').pop();
    const units: ParsedUnit[] = [];
    const offsets: ParsedCppDetails['offsets'] = new Map();
    const unitNamespaces = new Map<string, string[]>();
    const namespaceSpans: CppNamespaceSpan[] = [];

    scanDeclarationsInRange(
        source,
        masked,
        starts,
        0,
        source.length,
        documentPath,
        nodeName,
        nodeId,
        null,
        units,
        offsets,
        [],
        unitNamespaces,
        namespaceSpans,
    );

    return {
        path: documentPath,
        sourceHash: sourceHash(source),
        valid: true,
        units,
        diagnostics: [],
        offsets,
        unitNamespaces,
        namespaceSpans,
    };
}

/**
 * Parse a C++ (`.cpp`, `.cc`, `.h`, `.hpp`) or Arduino (`.ino`) source file into `ParseModuleResult`.
 */
export function parseCppModule(source: string, documentPath = '<memory>', nodeId?: string): ParseModuleResult {
    const { offsets: _offsets, unitNamespaces: _ns, namespaceSpans: _spans, ...result } = parseCppDetailed(source, documentPath, nodeId);
    return result;
}

function requireString(params: Record<string, unknown>, key: string): string {
    if (typeof params[key] !== 'string') throw new CppAdapterError(`${key} must be a string`);
    return params[key] as string;
}

function requireFresh(source: string, expectedHash: unknown): void {
    if (expectedHash === undefined) return;
    const actual = sourceHash(source);
    if (expectedHash !== actual) {
        throw new CppAdapterError(`stale source: expected ${String(expectedHash)}, current ${actual}`);
    }
}

/**
 * Replace a function or method unit in a C++ / Arduino document while verifying hash freshness and signature preservation.
 */
export function replaceCppUnit(params: Record<string, unknown>): SourceProposal {
    const source = requireString(params, 'source');
    const documentPath = typeof params.path === 'string' ? params.path : '<memory>';
    requireFresh(source, params.expectedHash);
    const nodeId = typeof params.nodeId === 'string' ? params.nodeId : undefined;
    const parsed = parseCppDetailed(source, documentPath, nodeId);
    if (!parsed.valid) {
        throw new CppAdapterError('source is not valid C++');
    }

    const unitId = requireString(params, 'unitId');
    const matches = parsed.units.filter(u => u.id === unitId || u.name === unitId);
    const exactMatches = parsed.units.filter(u => u.id === unitId);
    const resolved = exactMatches.length === 1 ? exactMatches : matches;
    if (resolved.length !== 1) {
        throw new CppAdapterError(`unit id ${JSON.stringify(unitId)} resolved to ${resolved.length} declarations; expected exactly one`);
    }
    const unit = resolved[0];
    if (!['function', 'method'].includes(unit.kind)) {
        throw new CppAdapterError('only functions and methods can be replaced');
    }
    if (unit.annotation?.locked === true) {
        throw new CppAdapterError('unit is locked');
    }

    const replacement = requireString(params, 'replacement').trim();
    const candidate = parseCppDetailed(`${replacement}\n`, '<replacement>');
    if (!candidate.valid || candidate.units.length !== 1 || candidate.units[0].parentId !== null) {
        throw new CppAdapterError('replacement must contain exactly one valid C++ function');
    }
    const candUnit = candidate.units[0];
    if (
        candUnit.name !== unit.name ||
        candUnit.signature !== unit.signature ||
        candUnit.decorators.length !== unit.decorators.length
    ) {
        throw new CppAdapterError('replacement must preserve the function name, signature, and attributes');
    }

    const target = parsed.offsets.get(unit.id)!.code;
    const indent = declarationIndent(source, target.from);
    const newText = indentBlock(replacement, indent);
    const starts = lineStarts(source);
    const proposedSource = source.slice(0, target.from) + newText + source.slice(target.to);
    const proposedParsed = parseCppModule(proposedSource, documentPath, nodeId);
    if (!proposedParsed.valid) {
        throw new CppAdapterError('proposed edit produces invalid C++');
    }

    return {
        baseSourceHash: sourceHash(source),
        proposedSourceHash: sourceHash(proposedSource),
        edits: [{ range: rangeAt(starts, target.from, target.to), newText }],
        proposedSource,
        parsed: proposedParsed,
    };
}

function defaultCppReturnExpression(returnType: string): string {
    const clean = returnType.replace(/\bconst\b/g, '').trim();
    if (!clean || clean === 'void') return '';
    if (clean.endsWith('*')) return 'nullptr';
    if (clean === 'bool') return 'false';
    if (clean === 'float') return '0.0f';
    if (clean === 'double' || clean === 'long double') return '0.0';
    if (clean === 'char') return "'\\0'";
    if (clean === 'String') return 'String("")';
    if (clean === 'std::string' || clean === 'string') return '""';
    if (/^(?:u?int(?:8|16|32|64)_t|size_t|ssize_t|short|int|long|unsigned|signed|byte|word)\b/.test(clean)) {
        return '0';
    }
    return `${clean}{}`;
}

/**
 * Create a valid typed C++ / Arduino stub function or struct/class definition.
 * Accepts either `(name, params, returnType, kind)` or a full C++ signature string as the first argument.
 */
export function createCppStub(
    nameOrSignature: string,
    params?: UnitParam[] | Array<{ name: string; annotation?: string | null; default?: string | null }> | string,
    returnType?: string | null,
    kind: 'function' | 'method' | 'class' | 'struct' = 'function',
): string {
    const trimmed = nameOrSignature.trim().replace(/;\s*$/, '');

    // If a full signature string was passed e.g. `int readSensor(int pin, int samples = 4)`
    if (params === undefined && returnType === undefined && trimmed.includes('(') && trimmed.endsWith(')')) {
        const probe = `${trimmed} {\n}\n`;
        const parsed = parseCppModule(probe, '<stub>');
        const unit = parsed.units[0];
        if (!parsed.valid || !unit) {
            throw new CppAdapterError(`Invalid C++ signature: ${nameOrSignature}`);
        }
        const ret = unit.returnAnnotation ?? 'void';
        const retExpr = defaultCppReturnExpression(ret);
        const bodyLines = [`    // TODO: implement ${unit.name}`];
        if (retExpr) bodyLines.push(`    return ${retExpr};`);
        return `${unit.signature} {\n${bodyLines.join('\n')}\n}`;
    }

    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(trimmed)) {
        throw new CppAdapterError(`Invalid C++ identifier: ${nameOrSignature}`);
    }

    if (kind === 'class' || kind === 'struct') {
        return `${kind} ${trimmed} {\n};`;
    }

    let paramText = '';
    if (typeof params === 'string') {
        paramText = normalizeParametersText(params);
    } else if (Array.isArray(params)) {
        paramText = params
            .map(p => {
                const typeStr = (p.annotation ?? 'int').trim() || 'int';
                const defStr = p.default !== undefined && p.default !== null ? ` = ${p.default}` : '';
                return `${typeStr} ${p.name}${defStr}`;
            })
            .join(', ');
    }

    const ret = (returnType ?? 'void').trim() || 'void';
    const retExpr = defaultCppReturnExpression(ret);
    const bodyLines = [`    // TODO: implement ${trimmed}`];
    if (retExpr) bodyLines.push(`    return ${retExpr};`);
    return `${ret} ${trimmed}(${paramText}) {\n${bodyLines.join('\n')}\n}`;
}

/**
 * Create a new C++/Arduino `SlateNode` from a typed C++ function signature.
 */
export function cppNodeFromSignature(
    signature: string,
    intent = '',
    language: 'cpp' | 'arduino' = 'cpp',
): SlateNode {
    const stub = createCppStub(signature);
    const parsed = parseCppModule(`${stub}\n`, '<new node>');
    const unit = parsed.valid && parsed.units.length === 1 ? parsed.units[0] : null;
    if (!unit) {
        throw new SlateFormatError('enter one C++ function signature, e.g. int readSensor(int pin, int samples = 4)');
    }
    return {
        name: unit.name,
        language,
        intent: intent.trim(),
        contract: '',
        context: [],
        examples: [],
        describedBy: 'human',
        locked: false,
        imports: language === 'arduino' ? ['#include <Arduino.h>'] : [],
        uses: [],
        code: codeLines(stub),
        extra: language === 'arduino' ? { arduinoSketch: true } : {},
    };
}

/**
 * Validate C++ / Arduino node code against JPL-60 rules (`<= 60` lines, explicit parameter & return types,
 * single definition rule, and optional contract check).
 *
 * Supports both:
 * - `checkCppNodeCode(code: string, expectedName?: string, options?: CppCheckOptions)`
 * - `checkCppNodeCode(node: SlateNode, nodeId?: string, code?: string, options?: CppCheckOptions)`
 */
export function checkCppNodeCode(
    codeOrNode: string | SlateNode,
    expectedNameOrNodeId?: string,
    optionsOrCode?: CppCheckOptions | string,
    maybeOptions?: CppCheckOptions,
): Jpl60CheckResult {
    let rawCode: string;
    let expectedName: string | undefined;
    let nodeKind: SlateNode['kind'] | undefined;
    let contractText: string | undefined;
    let options: CppCheckOptions | undefined;

    if (typeof codeOrNode === 'string') {
        rawCode = codeOrNode;
        expectedName = expectedNameOrNodeId?.split('/').pop();
        options = typeof optionsOrCode === 'object' ? optionsOrCode : maybeOptions;
        contractText = options?.contract;
    } else {
        nodeKind = codeOrNode.kind;
        expectedName = codeOrNode.name || expectedNameOrNodeId?.split('/').pop();
        rawCode = typeof optionsOrCode === 'string' ? optionsOrCode : codeOrNode.code.join('\n');
        options = typeof optionsOrCode === 'object' ? optionsOrCode : maybeOptions;
        contractText = options?.contract ?? codeOrNode.contract;
    }

    const lines = codeLines(rawCode).flatMap(line => line.split(/\r?\n/));
    const executable = lines.filter(l => {
        const t = l.trim();
        return t.length > 0 && !t.startsWith('//') && !t.startsWith('/*') && !t.startsWith('*');
    }).length;
    const diagnostics: Array<{ code: string; message: string }> = [];

    const source = `${lines.join('\n')}\n`;
    const parsed = parseCppModule(source, '<node>', expectedName);

    if (!parsed.valid) {
        diagnostics.push({
            code: 'cpp-syntax',
            message: parsed.diagnostics[0]?.message ?? 'Code is not valid C++.',
        });
        if (options?.throwOnError) {
            throw new SlateFormatError(diagnostics[0].message);
        }
        return {
            valid: false,
            lineCount: lines.length,
            executableLines: executable,
            diagnostics,
        };
    }

    if (nodeKind === 'prelude' || nodeKind === 'epilogue') {
        return {
            valid: true,
            lineCount: lines.length,
            executableLines: executable,
            diagnostics: [],
        };
    }

    if (lines.length > 60) {
        diagnostics.push({
            code: 'jpl60-line-count',
            message: `Node "${expectedName ?? '<anonymous>'}" exceeds JPL-60 limit: ${lines.length} lines (>60). Split or refactor into stubs and a flow composition.`,
        });
    }

    const topLevel = parsed.units.filter(u => u.parentId === null);
    if (topLevel.length === 0) {
        diagnostics.push({
            code: 'node-definition-missing',
            message: `Code must define a C++ function or struct/class${expectedName ? ` named "${expectedName}"` : ''}.`,
        });
    } else if (topLevel.length > 1) {
        diagnostics.push({
            code: 'node-extra-statements',
            message: 'Code must contain exactly one top-level C++ definition; put #include directives in "imports" and other definitions in their own nodes.',
        });
    } else {
        const def = topLevel[0];
        if (expectedName && def.name !== expectedName) {
            diagnostics.push({
                code: 'node-name-mismatch',
                message: `Definition name "${def.name}" does not match expected node name "${expectedName}".`,
            });
        }
        if (def.kind === 'function' || def.kind === 'method') {
            if (!def.returnAnnotation || !def.returnAnnotation.trim()) {
                diagnostics.push({
                    code: 'jpl60-return-annotation',
                    message: `Function "${def.name}" is missing an explicit C++ return type (e.g. void, int, float).`,
                });
            }
            for (const param of def.params ?? []) {
                if (!param.annotation || !param.annotation.trim()) {
                    diagnostics.push({
                        code: 'jpl60-param-annotation',
                        message: `Parameter "${param.name}" in "${def.name}" is missing an explicit C++ type annotation.`,
                    });
                }
            }
        }
    }

    if (options?.requireContract && (!contractText || !contractText.trim())) {
        diagnostics.push({
            code: 'jpl60-contract-missing',
            message: `Node "${expectedName ?? '<anonymous>'}" is missing contract documentation.`,
        });
    }

    const result: Jpl60CheckResult = {
        valid: diagnostics.length === 0,
        lineCount: lines.length,
        executableLines: executable,
        diagnostics,
    };

    if ((options?.enforceJpl60 || options?.throwOnError) && !result.valid) {
        throw new SlateFormatError(result.diagnostics[0].message);
    }

    return result;
}

export const checkCppJpl60 = checkCppNodeCode;

export class CppAdapter {
    async parseModule(source: string, documentPath = '<memory>', nodeId?: string): Promise<ParseModuleResult> {
        return parseCppModule(source, documentPath, nodeId);
    }

    async replaceUnit(params: Record<string, unknown>): Promise<SourceProposal> {
        return replaceCppUnit(params);
    }

    createStub(
        name: string,
        params?: UnitParam[] | string,
        returnType?: string | null,
        kind?: 'function' | 'method' | 'class' | 'struct',
    ): string {
        return createCppStub(name, params, returnType, kind);
    }

    checkNodeCode(code: string | SlateNode, expectedName?: string, options?: CppCheckOptions): Jpl60CheckResult {
        return checkCppNodeCode(code, expectedName, options);
    }

    formatGeneratedHeader(path?: string): string {
        return formatCppGeneratedHeader(path);
    }

    isGeneratedFile(content: string): boolean {
        return isCppGeneratedFile(content);
    }

    dispose(): void {}
}
