function stableId(documentPath: string, kind: UnitKind, qualifiedName: string): string {
    const hex = createHash('sha1').update(`slate:${documentPath}:${kind}:${qualifiedName}`).digest('hex');
    return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-5${hex.slice(13, 16)}-a${hex.slice(17, 20)}-${hex.slice(20, 32)}`;
}

function lineStarts(source: string): number[] {
    const starts = [0];
    for (let index = 0; index < source.length; index++) {
        if (source[index] === '\n') starts.push(index + 1);
    }
    return starts;
}

function positionAt(starts: number[], offset: number): SourcePosition {
    const clamped = Math.max(0, offset);
    let low = 0;
    let high = starts.length;
    while (low + 1 < high) {
        const middle = Math.floor((low + high) / 2);
        if (starts[middle] <= clamped) low = middle;
        else high = middle;
    }
    return { line: low, character: clamped - starts[low] };
}

function rangeAt(starts: number[], from: number, to: number): SourceRange {
    return { start: positionAt(starts, from), end: positionAt(starts, Math.max(from, to)) };
}

function meaningfulEnd(source: string, to: number): number {
    while (to > 0 && (source[to - 1] === '\n' || source[to - 1] === '\r')) to--;
    return to;
}

function declarationIndent(source: string, from: number): string {
    const lineStart = source.lastIndexOf('\n', from - 1) + 1;
    return source.slice(lineStart, from).match(/^[ \t]*/)?.[0] ?? '';
}

function normalizeParameters(raw: string): string {
    const normalized = raw.replace(/\r\n/g, '\n').replace(/\r/g, '\n');
    const lines = normalized.split('\n');
    if (lines.length === 1) return normalized.trim();
    if (lines[0].trim() === '') lines.shift();
    const closedOnOwnLine = lines.length > 0 && lines[lines.length - 1].trim() === '';
    if (closedOnOwnLine) lines.pop();
    const indents = lines.filter(line => line.trim()).map(line => line.match(/^[ \t]*/)?.[0].length ?? 0);
    const common = indents.length ? Math.min(...indents) : 0;
    const value = lines.map(line => line.slice(common)).join('\n');
    return closedOnOwnLine ? `${value}\n` : value;
}

/** Tokenize C# source while tracking comments and detecting lexical/bracket syntax errors. */
function lexCSharp(source: string): CSharpLexResult {
    const tokens: CSharpToken[] = [];
    const comments: Array<{ text: string; from: number; to: number }> = [];
    const len = source.length;
    let i = 0;

    while (i < len) {
        const ch = source[i];

        // Whitespace
        if (ch === ' ' || ch === '\t' || ch === '\r' || ch === '\n') {
            i++;
            continue;
        }

        // Single-line comment
        if (ch === '/' && source[i + 1] === '/') {
            const start = i;
            i += 2;
            while (i < len && source[i] !== '\n') i++;
            comments.push({ text: source.slice(start, i), from: start, to: i });
            continue;
        }

        // Multi-line comment
        if (ch === '/' && source[i + 1] === '*') {
            const start = i;
            i += 2;
            while (i < len && !(source[i] === '*' && source[i + 1] === '/')) i++;
            if (i >= len) {
                return {
                    tokens,
                    comments,
                    error: { message: 'Unterminated multi-line comment in C# source.', from: start, to: len },
                };
            }
            i += 2;
            comments.push({ text: source.slice(start, i), from: start, to: i });
            continue;
        }

        // Preprocessor directive (#region, #nullable, #if, etc.)
        if (ch === '#') {
            while (i < len && source[i] !== '\n') i++;
            continue;
        }

        // Verbatim or interpolated string literals: @"...", $"...", $@"...", @$"..."
        if (
            (ch === '@' && source[i + 1] === '"') ||
            (ch === '$' && source[i + 1] === '"') ||
            (ch === '$' && source[i + 1] === '@' && source[i + 2] === '"') ||
            (ch === '@' && source[i + 1] === '$' && source[i + 2] === '"')
        ) {
            const start = i;
            const isVerbatim = ch === '@' || source[i + 1] === '@';
            i += (source[i + 1] === '@' || source[i + 1] === '$') ? 3 : 2;
            let closed = false;
            while (i < len) {
                if (isVerbatim) {
                    if (source[i] === '"') {
                        if (source[i + 1] === '"') {
                            i += 2;
                            continue;
                        }
                        i++;
                        closed = true;
                        break;
                    }
                    i++;
                } else {
                    if (source[i] === '\\') {
                        i += 2;
                        continue;
                    }
                    if (source[i] === '"') {
                        i++;
                        closed = true;
                        break;
                    }
                    if (source[i] === '\n') break;
                    i++;
                }
            }
            if (!closed) {
                return {
                    tokens,
                    comments,
                    error: { message: 'Unterminated string literal in C# source.', from: start, to: i },
                };
            }
            tokens.push({ kind: 'string', text: source.slice(start, i), from: start, to: i });
            continue;
        }

        // Standard string literal "..." or raw string """..."""
        if (ch === '"') {
            const start = i;
            if (source[i + 1] === '"' && source[i + 2] === '"') {
                i += 3;
                let closed = false;
                while (i < len) {
                    if (source[i] === '"' && source[i + 1] === '"' && source[i + 2] === '"') {
                        i += 3;
                        closed = true;
                        break;
                    }
                    i++;
                }
                if (!closed) {
                    return {
                        tokens,
                        comments,
                        error: { message: 'Unterminated raw string literal in C# source.', from: start, to: i },
                    };
                }
                tokens.push({ kind: 'string', text: source.slice(start, i), from: start, to: i });
                continue;
            }
            i++;
            let closed = false;
            while (i < len) {
                if (source[i] === '\\') {
                    i += 2;
                    continue;
                }
                if (source[i] === '"') {
                    i++;
                    closed = true;
                    break;
                }
                if (source[i] === '\n') break;
                i++;
            }
            if (!closed) {
                return {
                    tokens,
                    comments,
                    error: { message: 'Unterminated string literal in C# source.', from: start, to: i },
                };
            }
            tokens.push({ kind: 'string', text: source.slice(start, i), from: start, to: i });
            continue;
        }

        // Character literal '...'
        if (ch === "'") {
            const start = i;
            i++;
            let closed = false;
            while (i < len) {
                if (source[i] === '\\') {
                    i += 2;
                    continue;
                }
                if (source[i] === "'") {
                    i++;
                    closed = true;
                    break;
                }
                if (source[i] === '\n') break;
                i++;
            }
            if (!closed) {
                return {
                    tokens,
                    comments,
                    error: { message: 'Unterminated character literal in C# source.', from: start, to: i },
                };
            }
            tokens.push({ kind: 'string', text: source.slice(start, i), from: start, to: i });
            continue;
        }

        // Identifier (or @ident verbatim identifier)
        if (
            (ch >= 'a' && ch <= 'z') ||
            (ch >= 'A' && ch <= 'Z') ||
            ch === '_' ||
            (ch === '@' && i + 1 < len && /[A-Za-z_]/.test(source[i + 1]))
        ) {
            const start = i;
            if (ch === '@') i++;
            while (i < len && /[A-Za-z0-9_]/.test(source[i])) i++;
            tokens.push({ kind: 'ident', text: source.slice(start, i), from: start, to: i });
            continue;
        }

        // Number literal
        if (ch >= '0' && ch <= '9') {
            const start = i;
            while (i < len && /[0-9a-fA-FxXbB._eE+-]/.test(source[i])) {
                if ((source[i] === '+' || source[i] === '-') && !/[eE]/.test(source[i - 1])) break;
                i++;
            }
            while (i < len && /[fFdDmMuUlL]/.test(source[i])) i++;
            tokens.push({ kind: 'number', text: source.slice(start, i), from: start, to: i });
            continue;
        }

        // Multi-character operators / punctuation
        const two = source.slice(i, i + 2);
        if (['=>', '::', '?.', '??', '==', '!=', '<=', '>=', '&&', '||', '++', '--', '+=', '-=', '*=', '/='].includes(two)) {
            tokens.push({ kind: 'punct', text: two, from: i, to: i + 2 });
            i += 2;
            continue;
        }

        tokens.push({ kind: 'punct', text: ch, from: i, to: i + 1 });
        i++;
    }

    // Validate balanced {}, (), []
    const stack: Array<{ open: string; close: string; token: CSharpToken }> = [];
    const pairs: Record<string, string> = { '{': '}', '(': ')', '[': ']' };
    const closers = new Set(['}', ')', ']']);

    for (const tok of tokens) {
        if (tok.kind !== 'punct') continue;
        if (pairs[tok.text]) {
            stack.push({ open: tok.text, close: pairs[tok.text], token: tok });
        } else if (closers.has(tok.text)) {
            const top = stack.pop();
            if (!top || top.close !== tok.text) {
                return {
                    tokens,
                    comments,
                    error: {
                        message: `Unexpected '${tok.text}' in C# source.`,
                        from: tok.from,
                        to: tok.to,
                    },
                };
            }
        }
    }
    if (stack.length > 0) {
        const unclosed = stack[stack.length - 1];
        return {
            tokens,
            comments,
            error: {
                message: `Unclosed '${unclosed.open}' in C# source.`,
                from: unclosed.token.from,
                to: unclosed.token.to,
            },
        };
    }

    return { tokens, comments, error: null };
}

/** Split one or more C# `using` directives into structured `CSharpUsing` entries. */
export function splitCSharpUsing(statement: string): CSharpUsing[] {
    const lexed = lexCSharp(statement);
    if (lexed.error) return [];
    const tokens = lexed.tokens;
    const results: CSharpUsing[] = [];
    let i = 0;

    while (i < tokens.length) {
        let isGlobal = false;
        if (tokens[i]?.kind === 'ident' && tokens[i].text === 'global' && tokens[i + 1]?.text === 'using') {
            isGlobal = true;
            i++;
        }
        if (tokens[i]?.kind !== 'ident' || tokens[i].text !== 'using') {
            i++;
            continue;
        }
        i++; // consume 'using'

        // Ignore `using (...)` or `using var ...` disposal statements
        if (!tokens[i] || tokens[i].text === '(' || tokens[i].text === 'var') {
            while (i < tokens.length && tokens[i].text !== ';') i++;
            i++;
            continue;
        }

        let isStatic = false;
        if (tokens[i].kind === 'ident' && tokens[i].text === 'static') {
            isStatic = true;
            i++;
        }

        let alias: string | null = null;
        if (tokens[i]?.kind === 'ident' && tokens[i + 1]?.text === '=') {
            alias = tokens[i].text;
            i += 2;
        }

        const startTok = tokens[i];
        if (!startTok) break;
        const targetParts: string[] = [];
        while (i < tokens.length && tokens[i].text !== ';') {
            // If this looks like a local `using Type varName = ...;` disposal declaration, abort
            if (tokens[i].text === '=' && alias === null) {
                targetParts.length = 0;
                while (i < tokens.length && tokens[i].text !== ';') i++;
                break;
            }
            targetParts.push(tokens[i].text);
            i++;
        }
        if (tokens[i]?.text === ';') i++;

        if (targetParts.length === 0) continue;
        // Reconstruct normalized namespace/type string without spaces around `.`, `<`, `>`, `,`
        const ns = targetParts
            .join('')
            .replace(/,/g, ', ');

        const prefix = `${isGlobal ? 'global ' : ''}using ${isStatic ? 'static ' : ''}${alias ? `${alias} = ` : ''}`;
        results.push({
            line: `${prefix}${ns};`,
            namespace: ns,
            alias,
            isStatic,
            isGlobal,
        });
    }

    return results;
}

/** Split a C# parameter list string at top-level commas (respecting `<...>`, `(...)`, `[...]`, `{...}`, and strings). */
function splitCSharpParamEntries(raw: string): string[] {
    const entries: string[] = [];
    let current = '';
    let angleDepth = 0;
    let parenDepth = 0;
    let bracketDepth = 0;
    let braceDepth = 0;
    let inString: '"' | "'" | null = null;

    for (let i = 0; i < raw.length; i++) {
        const ch = raw[i];
        if (inString) {
            current += ch;
            if (ch === inString && raw[i - 1] !== '\\') inString = null;
            continue;
        }
        if (ch === '"' || ch === "'") {
            inString = ch;
            current += ch;
            continue;
        }
        if (ch === '<') angleDepth++;
        else if (ch === '>') angleDepth = Math.max(0, angleDepth - 1);
        else if (ch === '(') parenDepth++;
        else if (ch === ')') parenDepth = Math.max(0, parenDepth - 1);
        else if (ch === '[') bracketDepth++;
        else if (ch === ']') bracketDepth = Math.max(0, bracketDepth - 1);
        else if (ch === '{') braceDepth++;
        else if (ch === '}') braceDepth = Math.max(0, braceDepth - 1);
        else if (
            ch === ',' &&
            angleDepth === 0 &&
            parenDepth === 0 &&
            bracketDepth === 0 &&
            braceDepth === 0
        ) {
            if (current.trim()) entries.push(current.trim());
            current = '';
            continue;
        }
        current += ch;
    }
    if (current.trim()) entries.push(current.trim());
    return entries;
}

/** Find top-level `=` in a single parameter entry (outside `<...>`, `(...)`, `[...]`, `{...}`, strings). */
function findTopLevelEquals(entry: string): number {
    let angleDepth = 0;
    let parenDepth = 0;
    let bracketDepth = 0;
    let braceDepth = 0;
    let inString: '"' | "'" | null = null;

    for (let i = 0; i < entry.length; i++) {
        const ch = entry[i];
        if (inString) {
            if (ch === inString && entry[i - 1] !== '\\') inString = null;
            continue;
        }
        if (ch === '"' || ch === "'") {
            inString = ch;
            continue;
        }
        if (ch === '<') angleDepth++;
        else if (ch === '>') angleDepth = Math.max(0, angleDepth - 1);
        else if (ch === '(') parenDepth++;
        else if (ch === ')') parenDepth = Math.max(0, parenDepth - 1);
        else if (ch === '[') bracketDepth++;
        else if (ch === ']') bracketDepth = Math.max(0, bracketDepth - 1);
        else if (ch === '{') braceDepth++;
        else if (ch === '}') braceDepth = Math.max(0, braceDepth - 1);
        else if (
            ch === '=' &&
            entry[i - 1] !== '!' &&
            entry[i - 1] !== '<' &&
            entry[i - 1] !== '>' &&
            entry[i + 1] !== '=' &&
            entry[i + 1] !== '>' &&
            angleDepth === 0 &&
            parenDepth === 0 &&
            bracketDepth === 0 &&
            braceDepth === 0
        ) {
            return i;
        }
    }
    return -1;
}

/** Strip leading `[Attr]` blocks from a parameter entry. */
function stripLeadingAttributes(text: string): string {
    let s = text.trim();
    while (s.startsWith('[')) {
        let depth = 0;
        let idx = 0;
        for (; idx < s.length; idx++) {
            if (s[idx] === '[') depth++;
            else if (s[idx] === ']') {
                depth--;
                if (depth === 0) {
                    idx++;
                    break;
                }
            }
        }
        s = s.slice(idx).trim();
    }
    return s;
}

/** Parse C# parameter list text into structured `UnitParam[]`. */
export function parseCSharpParams(rawParams: string): UnitParam[] {
    const entries = splitCSharpParamEntries(rawParams);
    const params: UnitParam[] = [];

    for (const rawEntry of entries) {
        const stripped = stripLeadingAttributes(rawEntry);
        if (!stripped) continue;

        const eqIdx = findTopLevelEquals(stripped);
        const leftPart = (eqIdx >= 0 ? stripped.slice(0, eqIdx) : stripped).trim();
        const defaultVal = eqIdx >= 0 ? stripped.slice(eqIdx + 1).trim() || null : null;

        const lexed = lexCSharp(leftPart);
        const toks = lexed.tokens;
        if (toks.length === 0) continue;

        let isParams = false;
        let tokIdx = 0;
        while (tokIdx < toks.length && toks[tokIdx].kind === 'ident' && PARAM_MODIFIERS.has(toks[tokIdx].text)) {
            if (toks[tokIdx].text === 'params') isParams = true;
            tokIdx++;
        }

        const remaining = toks.slice(tokIdx);
        if (remaining.length === 0) continue;

        const lastTok = remaining[remaining.length - 1];
        if (lastTok.kind !== 'ident') continue;

        const paramName = lastTok.text.replace(/^@/, '');
        if (remaining.length === 1) {
            // Parameter has a name but no C# type annotation
            params.push({
                name: paramName,
                annotation: null,
                default: defaultVal,
                kind: isParams ? 'var' : 'positional',
            });
            continue;
        }

        const typeStart = remaining[0].from;
        const typeEnd = remaining[remaining.length - 2].to;
        const rawType = leftPart.slice(typeStart, typeEnd).trim();
        params.push({
            name: paramName,
            annotation: rawType || null,
            default: defaultVal,
            kind: isParams ? 'var' : 'positional',
        });
    }

    return params;
}

function findMatchingClose(tokens: CSharpToken[], openIndex: number, openChar: string, closeChar: string): number {
    let depth = 0;
    for (let i = openIndex; i < tokens.length; i++) {
        if (tokens[i].kind !== 'punct') continue;
        if (tokens[i].text === openChar) depth++;
        else if (tokens[i].text === closeChar) {
            depth--;
            if (depth === 0) return i;
        }
    }
    return -1;
}

function findMatchingAngleClose(tokens: CSharpToken[], openIndex: number): number {
    let depth = 0;
    for (let i = openIndex; i < tokens.length; i++) {
        if (tokens[i].kind === 'punct') {
            if (tokens[i].text === '<') depth++;
            else if (tokens[i].text === '>') {
                depth--;
                if (depth === 0) return i;
            } else if (tokens[i].text === ';' || tokens[i].text === '{' || tokens[i].text === '}') {
                return -1;
            }
        }
    }
    return -1;
}

export function parseCSharpDetailed(
    source: string,
    documentPath = '<memory>',
    nodeId?: string,
): CSharpParseDetails {
    const starts = lineStarts(source);
    const hash = sourceHash(source);
    const lexed = lexCSharp(source);

    if (lexed.error) {
        return {
            path: documentPath,
            sourceHash: hash,
            valid: false,
            units: [],
            diagnostics: [
                {
                    code: 'csharp-syntax',
                    message: lexed.error.message,
                    range: rangeAt(starts, lexed.error.from, lexed.error.to),
                },
            ],
            namespace: null,
            usings: [],
            offsets: new Map(),
            unitDetails: new Map(),
        };
    }

    const tokens = lexed.tokens;
    const nodeName = nodeId?.split('/').pop();
    const usings: CSharpUsing[] = [];
    const detailsList: ParsedUnitDetail[] = [];
    let fileNamespace: string | null = null;
    type SyntaxErr = { message: string; from: number; to: number };
    let syntaxError: SyntaxErr | null = null as SyntaxErr | null;

    const parseAttributeDecorators = (
        startIdx: number,
        limitIdx: number,
    ): { decorators: string[]; nextIdx: number; wrapperFrom: number | null } => {
        const decorators: string[] = [];
        let idx = startIdx;
        let wrapperFrom: number | null = null;
        while (idx < limitIdx && tokens[idx].kind === 'punct' && tokens[idx].text === '[') {
            wrapperFrom ??= tokens[idx].from;
            const closeIdx = findMatchingClose(tokens, idx, '[', ']');
            if (closeIdx < 0 || closeIdx >= limitIdx) break;
            const inner = source.slice(tokens[idx].from + 1, tokens[closeIdx].to - 1).trim();
            if (inner) decorators.push(inner);
            idx = closeIdx + 1;
        }
        return { decorators, nextIdx: idx, wrapperFrom };
    };

    const parseDeclarations = (
        fromIdx: number,
        toIdx: number,
        parent: ParsedUnit | null,
        currentNamespace: string | null,
        currentClassName: string | null,
        currentClassModifiers: string | null,
        currentClassDeclaration: string | null = null,
    ): void => {
        let i = fromIdx;
        while (i < toIdx && !syntaxError) {
            const tok = tokens[i];
            if (tok.kind === 'punct' && tok.text === ';') {
                i++;
                continue;
            }

            // Collect any leading `[Attribute]` blocks
            const attrRes = parseAttributeDecorators(i, toIdx);
            const wrapperFrom = attrRes.wrapperFrom;
            i = attrRes.nextIdx;
            if (i >= toIdx) break;

            // `using` directive at file or namespace scope
            if (
                parent === null &&
                ((tokens[i].kind === 'ident' && tokens[i].text === 'using') ||
                    (tokens[i].kind === 'ident' && tokens[i].text === 'global' && tokens[i + 1]?.text === 'using'))
            ) {
                const startOffset = tokens[i].from;
                let semiIdx = i;
                while (semiIdx < toIdx && tokens[semiIdx].text !== ';' && tokens[semiIdx].text !== '{') semiIdx++;
                if (semiIdx >= toIdx || tokens[semiIdx].text !== ';') {
                    syntaxError = {
                        message: 'Expected ";" after C# using directive.',
                        from: startOffset,
                        to: tokens[Math.min(semiIdx, toIdx - 1)].to,
                    };
                    return;
                }
                const stmtText = source.slice(startOffset, tokens[semiIdx].to);
                usings.push(...splitCSharpUsing(stmtText));
                i = semiIdx + 1;
                continue;
            }

            // `namespace` declaration (block-scoped or file-scoped)
            if (parent === null && tokens[i].kind === 'ident' && tokens[i].text === 'namespace') {
                const nsStart = tokens[i].from;
                i++;
                const nsParts: string[] = [];
                while (
                    i < toIdx &&
                    (tokens[i].kind === 'ident' || tokens[i].text === '.' || tokens[i].text === '::')
                ) {
                    nsParts.push(tokens[i].text);
                    i++;
                }
                if (nsParts.length === 0) {
                    syntaxError = {
                        message: 'Expected namespace name after "namespace".',
                        from: nsStart,
                        to: tokens[Math.min(i, toIdx - 1)].to,
                    };
                    return;
                }
                const nsName = nsParts.join('');
                const fullNs = currentNamespace ? `${currentNamespace}.${nsName}` : nsName;
                fileNamespace ??= fullNs;

                if (tokens[i]?.text === ';') {
                    // File-scoped namespace
                    currentNamespace = fullNs;
                    i++;
                    continue;
                }
                if (tokens[i]?.text === '{') {
                    const closeBrace = findMatchingClose(tokens, i, '{', '}');
                    if (closeBrace < 0) {
                        syntaxError = {
                            message: `Unclosed namespace "${fullNs}" block.`,
                            from: tokens[i].from,
                            to: tokens[toIdx - 1].to,
                        };
                        return;
                    }
                    parseDeclarations(i + 1, closeBrace, null, fullNs, null, null, null);
                    i = closeBrace + 1;
                    continue;
                }
                syntaxError = {
                    message: `Expected "{" or ";" after namespace "${fullNs}".`,
                    from: nsStart,
                    to: tokens[Math.min(i, toIdx - 1)].to,
                };
                return;
            }

            // Collect declaration modifiers (`public`, `static`, `async`, etc.)
            const modStartIdx = i;
            const modifiers: string[] = [];
            while (i < toIdx && tokens[i].kind === 'ident' && MODIFIER_KEYWORDS.has(tokens[i].text)) {
                modifiers.push(tokens[i].text);
                i++;
            }

            if (i >= toIdx) {
                syntaxError = {
                    message: 'Unexpected end of C# declaration after modifiers.',
                    from: tokens[modStartIdx].from,
                    to: tokens[toIdx - 1].to,
                };
                return;
            }

            // Check for `class`, `struct`, `interface`, `record`
            if (tokens[i].kind === 'ident' && TYPE_DECLARATION_KEYWORDS.has(tokens[i].text)) {
                const declKeyword = tokens[i].text;
                i++;
                // Handle `record class` or `record struct`
                if (
                    declKeyword === 'record' &&
                    tokens[i]?.kind === 'ident' &&
                    (tokens[i].text === 'class' || tokens[i].text === 'struct')
                ) {
                    i++;
                }
                const nameTok = tokens[i];
                if (!nameTok || nameTok.kind !== 'ident') {
                    syntaxError = {
                        message: `Expected identifier after "${declKeyword}".`,
                        from: tokens[modStartIdx].from,
                        to: tokens[Math.min(i, toIdx - 1)].to,
                    };
                    return;
                }
                const typeName = nameTok.text.replace(/^@/, '');
                i++;

                // Skip generic parameters, primary constructors, base types, `where` clauses until `{` or `;`
                while (i < toIdx && tokens[i].text !== '{' && tokens[i].text !== ';') {
                    if (tokens[i].text === '(') {
                        const closeP = findMatchingClose(tokens, i, '(', ')');
                        if (closeP < 0) break;
                        i = closeP + 1;
                    } else {
                        i++;
                    }
                }
                if (i >= toIdx) {
                    syntaxError = {
                        message: `Expected "{" or ";" in declaration of "${typeName}".`,
                        from: nameTok.from,
                        to: tokens[toIdx - 1].to,
                    };
                    return;
                }

                const endTokIdx = tokens[i].text === '{' ? findMatchingClose(tokens, i, '{', '}') : i;
                if (endTokIdx < 0) {
                    syntaxError = {
                        message: `Unclosed body in type "${typeName}".`,
                        from: nameTok.from,
                        to: tokens[toIdx - 1].to,
                    };
                    return;
                }

                const codeFrom = tokens[modStartIdx].from;
                const declFrom = wrapperFrom ?? codeFrom;
                const declTo = meaningfulEnd(source, tokens[endTokIdx].to);
                const kind: UnitKind = parent ? 'nested_class' : 'class';
                const qualifiedName = parent ? `${parent.qualifiedName}.${typeName}` : typeName;
                const isDurableNode = !parent && nodeName !== undefined && typeName === nodeName;
                const unitId = isDurableNode ? nodeId! : stableId(documentPath, kind, qualifiedName);

                const classUnit: ParsedUnit = {
                    id: unitId,
                    identity: isDurableNode ? 'durable' : 'provisional',
                    kind,
                    name: typeName,
                    qualifiedName,
                    parentId: parent?.id ?? null,
                    ranges: {
                        name: rangeAt(starts, nameTok.from, nameTok.to),
                        declaration: rangeAt(starts, declFrom, declTo),
                    },
                    annotation: null,
                    decorators: attrRes.decorators,
                };
                const classMods = modifiers.length > 0 ? modifiers.join(' ') : 'public static';
                const rawDeclHeader = source.slice(declFrom, tokens[i].from).replace(/\r\n?/g, '\n');
                const classDecl = rawDeclHeader
                    .split('\n')
                    .map(l => l.trim())
                    .filter(Boolean)
                    .join('\n') || `${classMods} ${declKeyword} ${typeName}`;
                detailsList.push({
                    unit: classUnit,
                    wrapperFrom: declFrom,
                    codeFrom,
                    codeTo: declTo,
                    namespace: currentNamespace,
                    className: typeName,
                    classModifiers: classMods,
                    classDeclaration: classDecl,
                });

                if (tokens[i].text === '{') {
                    parseDeclarations(
                        i + 1,
                        endTokIdx,
                        classUnit,
                        currentNamespace,
                        typeName,
                        classMods,
                        classDecl,
                    );
                }
                i = endTokIdx + 1;
                continue;
            }

            // Check for `enum` or `delegate`
            if (tokens[i].kind === 'ident' && (tokens[i].text === 'enum' || tokens[i].text === 'delegate')) {
                while (i < toIdx && tokens[i].text !== '{' && tokens[i].text !== ';') i++;
                if (i < toIdx && tokens[i].text === '{') {
                    const closeB = findMatchingClose(tokens, i, '{', '}');
                    i = closeB >= 0 ? closeB + 1 : toIdx;
                } else {
                    i++;
                }
                continue;
            }

            // Otherwise, inside a class or at top-level: could be a method, constructor, property, or field/statement.
            // Find the next `(` at the current level (before `{`, `;`, `=`) to check if it's a method or constructor.
            let scanIdx = i;
            let parenOpenIdx = -1;
            while (scanIdx < toIdx) {
                const st = tokens[scanIdx];
                if (st.kind === 'punct') {
                    if (st.text === '(') {
                        // Make sure this `(` isn't a tuple return type like `public static (int a, int b) Split(...)`
                        if (scanIdx === i && tokens[scanIdx].text === '(') {
                            const closeTuple = findMatchingClose(tokens, scanIdx, '(', ')');
                            if (closeTuple > scanIdx && tokens[closeTuple + 1]?.kind === 'ident') {
                                scanIdx = closeTuple + 1;
                                continue;
                            }
                        }
                        parenOpenIdx = scanIdx;
                        break;
                    }
                    if (st.text === '<') {
                        const closeAngle = findMatchingAngleClose(tokens, scanIdx);
                        if (closeAngle > scanIdx) {
                            scanIdx = closeAngle + 1;
                            continue;
                        }
                    }
                    if (st.text === ';' || st.text === '{' || st.text === '=' || st.text === '=>') {
                        break;
                    }
                }
                scanIdx++;
            }

            if (parenOpenIdx > i) {
                // Determine method name token (possibly preceded by `<TypeParams>` right before `(`)
                let nameTokIdx = parenOpenIdx - 1;
                if (tokens[nameTokIdx]?.text === '>') {
                    // Walk back to matching `<`
                    let depth = 0;
                    for (let k = nameTokIdx; k >= i; k--) {
                        if (tokens[k].text === '>') depth++;
                        else if (tokens[k].text === '<') {
                            depth--;
                            if (depth === 0) {
                                nameTokIdx = k - 1;
                                break;
                            }
                        }
                    }
                }

                const methodNameTok = tokens[nameTokIdx];
                if (!methodNameTok || methodNameTok.kind !== 'ident') {
                    syntaxError = {
                        message: 'Invalid C# method declaration.',
                        from: tokens[modStartIdx].from,
                        to: tokens[parenOpenIdx].to,
                    };
                    return;
                }

                const methodName = methodNameTok.text.replace(/^@/, '');
                // Check if this is a constructor (`public ClassName(...)`)
                const isConstructor = nameTokIdx === i && parent !== null && methodName === parent.name;

                // Extract return annotation (tokens from `i` up to `nameTokIdx - 1`)
                let returnAnnotation: string | null = null;
                if (nameTokIdx > i) {
                    returnAnnotation = source.slice(tokens[i].from, tokens[nameTokIdx - 1].to).trim();
                }

                // If at top-level with no modifiers and no return type (e.g. `Foo(1);` or `if (...)`), check for invalid statement
                if (
                    nameTokIdx === i &&
                    modifiers.length === 0 &&
                    !isConstructor
                ) {
                    syntaxError = {
                        message: `Method "${methodName}" is missing a C# return type or modifiers.`,
                        from: tokens[modStartIdx].from,
                        to: tokens[parenOpenIdx].to,
                    };
                    return;
                }

                const parenCloseIdx = findMatchingClose(tokens, parenOpenIdx, '(', ')');
                if (parenCloseIdx < 0) {
                    syntaxError = {
                        message: `Unclosed parameter list in "${methodName}".`,
                        from: tokens[parenOpenIdx].from,
                        to: tokens[toIdx - 1].to,
                    };
                    return;
                }

                // Advance past optional `: base(...)` / `: this(...)` or `where T : ...`
                let bodyStartIdx = parenCloseIdx + 1;
                while (
                    bodyStartIdx < toIdx &&
                    tokens[bodyStartIdx].text !== '{' &&
                    tokens[bodyStartIdx].text !== '=>' &&
                    tokens[bodyStartIdx].text !== ';'
                ) {
                    if (tokens[bodyStartIdx].text === '(') {
                        const closeC = findMatchingClose(tokens, bodyStartIdx, '(', ')');
                        bodyStartIdx = closeC >= 0 ? closeC + 1 : bodyStartIdx + 1;
                    } else {
                        bodyStartIdx++;
                    }
                }

                if (bodyStartIdx >= toIdx) {
                    syntaxError = {
                        message: `Expected method body "{ ... }" or "=> ...;" for "${methodName}".`,
                        from: methodNameTok.from,
                        to: tokens[toIdx - 1].to,
                    };
                    return;
                }

                let endMethodIdx = bodyStartIdx;
                if (tokens[bodyStartIdx].text === '{') {
                    endMethodIdx = findMatchingClose(tokens, bodyStartIdx, '{', '}');
                    if (endMethodIdx < 0) {
                        syntaxError = {
                            message: `Unclosed method body for "${methodName}".`,
                            from: tokens[bodyStartIdx].from,
                            to: tokens[toIdx - 1].to,
                        };
                        return;
                    }
                } else if (tokens[bodyStartIdx].text === '=>') {
                    let semi = bodyStartIdx + 1;
                    while (semi < toIdx && tokens[semi].text !== ';') {
                        if (tokens[semi].text === '{') {
                            const closeB = findMatchingClose(tokens, semi, '{', '}');
                            semi = closeB >= 0 ? closeB + 1 : semi + 1;
                        } else {
                            semi++;
                        }
                    }
                    if (semi >= toIdx) {
                        syntaxError = {
                            message: `Expected ";" at end of expression-bodied method "${methodName}".`,
                            from: tokens[bodyStartIdx].from,
                            to: tokens[toIdx - 1].to,
                        };
                        return;
                    }
                    endMethodIdx = semi;
                } else if (tokens[bodyStartIdx].text === ';') {
                    endMethodIdx = bodyStartIdx;
                }

                if (isConstructor) {
                    i = endMethodIdx + 1;
                    continue;
                }

                const rawParams = source.slice(tokens[parenOpenIdx].from + 1, tokens[parenCloseIdx].to - 1);
                const parameters = normalizeParameters(rawParams);
                const structuredParams = parseCSharpParams(rawParams);
                const asynchronous = modifiers.includes('async');

                const codeFrom = tokens[modStartIdx].from;
                const declFrom = wrapperFrom ?? codeFrom;
                const declTo = meaningfulEnd(source, tokens[endMethodIdx].to);
                const kind: UnitKind = parent ? 'method' : 'function';
                const qualifiedName = parent ? `${parent.qualifiedName}.${methodName}` : methodName;
                const isDurable = !parent && nodeName !== undefined && methodName === nodeName;
                const unitId = isDurable ? nodeId! : stableId(documentPath, kind, qualifiedName);

                const methodUnit: ParsedUnit = {
                    id: unitId,
                    identity: isDurable ? 'durable' : 'provisional',
                    kind,
                    name: methodName,
                    qualifiedName,
                    parentId: parent?.id ?? null,
                    ranges: {
                        name: rangeAt(starts, methodNameTok.from, methodNameTok.to),
                        declaration: rangeAt(starts, declFrom, declTo),
                    },
                    annotation: null,
                    decorators: attrRes.decorators,
                    async: asynchronous,
                    parameters,
                    params: structuredParams,
                    returnAnnotation,
                    signature: `${asynchronous ? 'async ' : ''}${returnAnnotation ?? 'void'} ${methodName}(${parameters})`,
                };

                detailsList.push({
                    unit: methodUnit,
                    wrapperFrom: declFrom,
                    codeFrom,
                    codeTo: declTo,
                    namespace: currentNamespace,
                    className: currentClassName,
                    classModifiers: currentClassModifiers,
                    classDeclaration: currentClassDeclaration,
                });

                i = endMethodIdx + 1;
                continue;
            }

            // Field, constant, or property inside a class/struct
            if (parent !== null) {
                while (i < toIdx && tokens[i].text !== ';' && tokens[i].text !== '{') i++;
                if (i < toIdx && tokens[i].text === '{') {
                    const closeProp = findMatchingClose(tokens, i, '{', '}');
                    i = closeProp >= 0 ? closeProp + 1 : toIdx;
                    // Optional property initializer `= ...;`
                    if (tokens[i]?.text === '=') {
                        while (i < toIdx && tokens[i].text !== ';') i++;
                        if (tokens[i]?.text === ';') i++;
                    }
                } else if (i < toIdx && tokens[i].text === ';') {
                    i++;
                }
                continue;
            }

            // Top-level field/const declaration or invalid syntax
            if (modifiers.length > 0 || (tokens[i]?.kind === 'ident' && tokens[i + 1]?.kind === 'ident')) {
                let semi = i;
                while (semi < toIdx && tokens[semi].text !== ';' && tokens[semi].text !== '{') semi++;
                if (semi < toIdx && tokens[semi].text === ';') {
                    i = semi + 1;
                    continue;
                }
            }

            syntaxError = {
                message: `C# syntax could not be parsed at "${tokens[i].text}".`,
                from: tokens[modStartIdx].from,
                to: tokens[Math.min(i + 1, toIdx - 1)].to,
            };
            return;
        }
    };

    parseDeclarations(0, tokens.length, null, null, null, null, null);

    if (syntaxError) {
        return {
            path: documentPath,
            sourceHash: hash,
            valid: false,
            units: [],
            diagnostics: [
                {
                    code: 'csharp-syntax',
                    message: syntaxError.message,
                    range: rangeAt(starts, syntaxError.from, syntaxError.to),
                },
            ],
            namespace: fileNamespace,
            usings,
            offsets: new Map(),
            unitDetails: new Map(),
        };
    }

    // If `nodeId` was provided and no top-level unit matched `nodeName` (e.g., a class wraps the target method),
    // promote the matching method to durable `nodeId`.
    if (
        nodeId &&
        nodeName &&
        !detailsList.some(d => d.unit.identity === 'durable')
    ) {
        const methodMatches = detailsList.filter(d => d.unit.kind === 'method' && d.unit.name === nodeName);
        if (methodMatches.length > 0) {
            for (const m of methodMatches) {
                m.unit.id = nodeId;
                m.unit.identity = 'durable';
            }
        }
    }

    // Disambiguate provisional overload IDs so offsets and unitDetails never collide across same-named methods.
    const idGroups = new Map<string, ParsedUnitDetail[]>();
    for (const item of detailsList) {
        const group = idGroups.get(item.unit.id) ?? [];
        group.push(item);
        idGroups.set(item.unit.id, group);
    }
    const assignedIds = new Set<string>();
    for (const item of detailsList) {
        const group = idGroups.get(item.unit.id)!;
        if (group.length > 1 && item.unit.identity !== 'durable') {
            const paramSig = (item.unit.params ?? []).map(p => (p.annotation ?? '').replace(/\s+/g, '')).join(',');
            let candidate = stableId(documentPath, item.unit.kind, `${item.unit.qualifiedName}(${paramSig})`);
            if (assignedIds.has(candidate)) {
                let n = 2;
                while (assignedIds.has(`${candidate}#${n}`)) n++;
                candidate = `${candidate}#${n}`;
            }
            item.unit.id = candidate;
        }
        assignedIds.add(item.unit.id);
    }

    const units: ParsedUnit[] = [];
    const offsets: CSharpParseDetails['offsets'] = new Map();
    const unitDetails: CSharpParseDetails['unitDetails'] = new Map();

    for (const item of detailsList) {
        units.push(item.unit);
        offsets.set(item.unit.id, {
            wrapper: { from: item.wrapperFrom, to: item.codeTo },
            code: { from: item.codeFrom, to: item.codeTo },
        });
        unitDetails.set(item.unit.id, {
            namespace: item.namespace,
            className: item.className,
            classModifiers: item.classModifiers,
            classDeclaration: item.classDeclaration,
        });
    }

    return {
        path: documentPath,
        sourceHash: hash,
        valid: true,
        units,
        diagnostics: [],
        namespace: fileNamespace,
        usings,
        offsets,
        unitDetails,
    };
}

/** Parse a C# source file or method snippet into a `ParseModuleResult`. */
export function parseCSharpModule(
    source: string,
    documentPath = '<memory>',
    nodeId?: string,
): ParseModuleResult {
    const {
        namespace: _ns,
        usings: _usings,
        offsets: _offsets,
        unitDetails: _details,
        ...result
    } = parseCSharpDetailed(source, documentPath, nodeId);
    return result;
}

/** Every non-keyword identifier referenced or declared in C# source. */
export function csharpIdentifierNames(source: string): Set<string> {
    const names = new Set<string>();
    const lexed = lexCSharp(source);
    for (const tok of lexed.tokens) {
        if (tok.kind === 'ident') {
            const clean = tok.text.replace(/^@/, '');
            if (!CSHARP_KEYWORDS.has(clean)) {
                names.add(clean);
            }
        }
    }
    return names;
}

/** Names bound by top-level or class-level declarations in a C# source string. */
export function csharpTopLevelBindings(source: string): Set<string> {
    const names = new Set<string>();
    const detailed = parseCSharpDetailed(source);
    for (const unit of detailed.units) {
        names.add(unit.name);
    }
    // Also detect `const` or `static readonly` field bindings in prelude/class snippets
    const fieldRegex = /\b(?:const|static\s+readonly|static)\s+[A-Za-z0-9_<>,?\[\]\s]+\s+([A-Za-z_][A-Za-z0-9_]*)\s*=/g;
    for (const match of source.matchAll(fieldRegex)) {
        names.add(match[1]);
    }
    return names;
}

function indentBlock(value: string, indent: string): string {
    return value
        .split('\n')
        .map((line, index) => (index === 0 ? line : line.trim() ? `${indent}${line}` : line))
        .join('\n');
}

export interface ReplaceCSharpUnitParams {
    source: string;
    path?: string;
    nodeId?: string;
    expectedHash?: string;
    unitId: string;
    replacement: string;
}

/** Replace a C# method or function unit in `source` while verifying hash, syntax, and signature preservation. */
export function replaceCSharpUnit(params: ReplaceCSharpUnitParams | Record<string, unknown>): SourceProposal {
    if (typeof params.source !== 'string') throw new AdapterError('source must be a string');
    if (typeof params.unitId !== 'string') throw new AdapterError('unitId must be a string');
    if (typeof params.replacement !== 'string') throw new AdapterError('replacement must be a string');

    const source = params.source;
    const documentPath = typeof params.path === 'string' ? params.path : '<memory>';
    const nodeId = typeof params.nodeId === 'string' ? params.nodeId : undefined;
    const unitId = params.unitId;

    if (params.expectedHash !== undefined) {
        const actual = sourceHash(source);
        if (params.expectedHash !== actual) {
            throw new AdapterError(`stale source: expected ${String(params.expectedHash)}, current ${actual}`);
        }
    }

    const parsed = parseCSharpDetailed(source, documentPath, nodeId);
    if (!parsed.valid) {
        throw new AdapterError('cannot replace unit in invalid C# source');
    }

    let matches = parsed.units.filter(u => u.id === unitId);
    if (matches.length === 0) {
        matches = parsed.units.filter(u => u.qualifiedName === unitId || u.name === unitId);
    }
    if (matches.length !== 1) {
        throw new AdapterError(
            `unit id ${JSON.stringify(unitId)} resolved to ${matches.length} declarations; expected exactly one`,
        );
    }
    const unit = matches[0];
    if (unit.kind !== 'function' && unit.kind !== 'method') {
        throw new AdapterError('only functions and methods can be replaced');
    }
    if (unit.annotation?.locked === true) {
        throw new AdapterError('unit is locked');
    }

    const replacement = params.replacement.trim();
    const candidate = parseCSharpDetailed(`${replacement}\n`, '<replacement>');
    const candidateMethods = candidate.units.filter(u => u.kind === 'function' || u.kind === 'method');
    if (!candidate.valid || candidate.units.length !== 1 || candidateMethods.length !== 1) {
        throw new AdapterError('replacement must contain exactly one valid C# method');
    }

    const candUnit = candidateMethods[0];
    if (
        candUnit.name !== unit.name ||
        candUnit.returnAnnotation !== unit.returnAnnotation ||
        (candUnit.params?.length ?? 0) !== (unit.params?.length ?? 0) ||
        (candUnit.params ?? []).some((p, idx) => {
            const orig = unit.params![idx];
            return p.name !== orig.name || p.annotation !== orig.annotation || p.default !== orig.default;
        })
    ) {
        throw new AdapterError('replacement must preserve the C# method name, return type, and parameters');
    }

    const offsetEntry = parsed.offsets.get(unit.id)!;
    const target = replacement.startsWith('[') ? offsetEntry.wrapper : offsetEntry.code;
    const indent = declarationIndent(source, target.from);
    const newText = indentBlock(replacement, indent);
    const proposedSource = source.slice(0, target.from) + newText + source.slice(target.to);
    const reParsed = parseCSharpModule(proposedSource, documentPath, nodeId);
    if (!reParsed.valid) {
        throw new AdapterError('proposed edit produces invalid C#');
    }

    const starts = lineStarts(source);
    return {
        baseSourceHash: sourceHash(source),
        proposedSourceHash: sourceHash(proposedSource),
        edits: [{ range: rangeAt(starts, target.from, target.to), newText }],
        proposedSource,
        parsed: reParsed,
    };
}

export interface CSharpStubParamInput {
    name: string;
    annotation?: string | null;
    type?: string | null;
    default?: string | null;
    kind?: UnitParam['kind'];
}

export interface CreateCSharpStubOptions {
    visibility?: 'public' | 'internal' | 'private' | 'protected';
    isStatic?: boolean;
    async?: boolean;
    message?: string;
    intent?: string;
}

/**
 * Create a typed C# method stub throwing `new NotImplementedException(...)`.
 * Accepts either:
 * - `createCSharpStub('public static int Clamp(int x, int low = 0, int high = 10)', 'Clamp value')`
 * - `createCSharpStub('Clamp', [{ name: 'x', annotation: 'int' }, ...], 'int', options)`
 * - `createCSharpStub('Clamp', 'int x, int low = 0', 'int', options)`
 */
export function createCSharpStub(
    nameOrSignature: string,
    paramsOrMessage?: ReadonlyArray<CSharpStubParamInput> | string,
    returnType?: string | null,
    options?: CreateCSharpStubOptions | string,
): string {
    const trimmed = nameOrSignature.trim();

    // Full signature string passed as first argument, e.g. `public static int Clamp(int x, int low = 0)`
    if (trimmed.includes('(') && trimmed.includes(')')) {
        const header = trimmed.replace(/\s*(\{[\s\S]*\}|;)\s*$/, '').trim();
        const hasVisibility = /\b(public|private|protected|internal)\b/.test(header);
        const fullHeader = hasVisibility ? header : `public static ${header}`;
        const parsed = parseCSharpModule(`${fullHeader}\n{\n}\n`, '<stub>');
        const methodUnit = parsed.units.find(u => u.kind === 'function' || u.kind === 'method');
        const methodName = methodUnit?.name ?? 'Method';
        const customMessage = typeof paramsOrMessage === 'string' && paramsOrMessage.trim()
            ? paramsOrMessage.trim()
            : `${methodName} is not implemented.`;
        return [
            fullHeader,
            '{',
            `    throw new NotImplementedException(${JSON.stringify(customMessage)});`,
            '}',
        ].join('\n');
    }

    const opts: CreateCSharpStubOptions = typeof options === 'object' && options !== null
        ? options
        : typeof options === 'string'
            ? { message: options }
            : {};

    const visibility = opts.visibility ?? 'public';
    const isStatic = opts.isStatic !== false;
    const isAsync = opts.async === true;
    const ret = returnType && returnType.trim() ? returnType.trim() : 'void';

    let paramListText = '';
    if (typeof paramsOrMessage === 'string') {
        paramListText = paramsOrMessage.trim();
    } else if (Array.isArray(paramsOrMessage)) {
        paramListText = paramsOrMessage
            .map(p => {
                const typeAnn = (p.annotation ?? p.type ?? 'object').trim() || 'object';
                const prefix = p.kind === 'var' && !typeAnn.startsWith('params ') ? 'params ' : '';
                const def = p.default !== undefined && p.default !== null ? ` = ${p.default}` : '';
                return `${prefix}${typeAnn} ${p.name}${def}`;
            })
            .join(', ');
    }

    const msg = opts.message ?? opts.intent ?? `${trimmed} is not implemented.`;
    const staticPart = isStatic ? 'static ' : '';
    const asyncPart = isAsync ? 'async ' : '';

    return [
        `${visibility} ${staticPart}${asyncPart}${ret} ${trimmed}(${paramListText})`,
        '{',
        `    throw new NotImplementedException(${JSON.stringify(msg)});`,
        '}',
    ].join('\n');
}

export interface CheckCSharpNodeOptions {
    enforceJpl60?: boolean;
    requireContract?: boolean;
    contract?: string;
}

/**
 * Validate C# node code against JPL-60 (`<=60` lines) and explicit C# parameter and return types.
 * Supports calling with `(code, expectedName?, options?)` or `(node, nodeId?, code?, options?)`.
 */
export function checkCSharpNodeCode(
    input: string | string[] | SlateNode,
    arg2?: string | CheckCSharpNodeOptions,
    arg3?: string | CheckCSharpNodeOptions,
    arg4?: CheckCSharpNodeOptions,
): Jpl60CheckResult {
    let rawLines: string[];
    let expectedName: string | undefined;
    let contractText = '';
    let nodeKind: string | undefined;
    let options: CheckCSharpNodeOptions = {};

    if (typeof input === 'string') {
        rawLines = input.replace(/\r\n?/g, '\n').split('\n');
        while (rawLines.length > 0 && rawLines[rawLines.length - 1].trim() === '') rawLines.pop();
        if (typeof arg2 === 'string') {
            expectedName = arg2.split('/').pop();
            if (typeof arg3 === 'object' && arg3 !== null) options = arg3;
        } else if (typeof arg2 === 'object' && arg2 !== null) {
            options = arg2;
        }
    } else if (Array.isArray(input)) {
        rawLines = input.flatMap(l => l.replace(/\r\n?/g, '\n').split('\n'));
        while (rawLines.length > 0 && rawLines[rawLines.length - 1].trim() === '') rawLines.pop();
        if (typeof arg2 === 'string') {
            expectedName = arg2.split('/').pop();
            if (typeof arg3 === 'object' && arg3 !== null) options = arg3;
        } else if (typeof arg2 === 'object' && arg2 !== null) {
            options = arg2;
        }
    } else {
        // SlateNode
        const node = input;
        expectedName = node.name;
        contractText = node.contract ?? '';
        nodeKind = node.kind;
        let codeOverride: string | undefined;
        if (typeof arg2 === 'string' && typeof arg3 === 'string') {
            codeOverride = arg3;
            if (arg4) options = arg4;
        } else if (typeof arg2 === 'string') {
            if (arg2.includes('(') || arg2.includes('{') || arg2.includes('\n')) {
                codeOverride = arg2;
            }
            if (typeof arg3 === 'object' && arg3 !== null) options = arg3;
        } else if (typeof arg2 === 'object' && arg2 !== null) {
            options = arg2;
        }
        const sourceLines = codeOverride !== undefined ? codeOverride.replace(/\r\n?/g, '\n').split('\n') : [...node.code];
        rawLines = sourceLines.flatMap(l => l.replace(/\r\n?/g, '\n').split('\n'));
        while (rawLines.length > 0 && rawLines[rawLines.length - 1].trim() === '') rawLines.pop();
    }

    if (options.contract !== undefined) {
        contractText = options.contract;
    }

    const lineCount = rawLines.length;
    const executableLines = rawLines.filter(l => {
        const t = l.trim();
        return t.length > 0 && !t.startsWith('//') && !t.startsWith('/*') && !t.startsWith('*');
    }).length;

    if (nodeKind === 'prelude' || nodeKind === 'epilogue') {
        return { valid: true, lineCount, executableLines, diagnostics: [] };
    }

    const diagnostics: Array<{ code: string; message: string }> = [];
    const labelName = expectedName ?? 'method';

    if (lineCount > 60) {
        diagnostics.push({
            code: 'jpl60-line-count',
            message: `Node "${labelName}" exceeds JPL-60 limit: ${lineCount} lines (>60). Split or refactor into stubs and a flow composition.`,
        });
    }

    const source = `${rawLines.join('\n')}\n`;
    const parsed = parseCSharpDetailed(source, '<csharp-node>', expectedName);
    if (!parsed.valid) {
        for (const diag of parsed.diagnostics) {
            diagnostics.push({ code: diag.code, message: diag.message });
        }
    } else {
        const methodUnits = parsed.units.filter(u => u.kind === 'function' || u.kind === 'method');
        const targetUnit =
            (expectedName ? methodUnits.find(u => u.name === expectedName) : undefined) ??
            methodUnits[0] ??
            (expectedName ? parsed.units.find(u => u.name === expectedName) : parsed.units[0]);

        if (!targetUnit) {
            diagnostics.push({
                code: 'node-definition-missing',
                message: `C# code must define a method or class${expectedName ? ` named "${expectedName}"` : ''}.`,
            });
        } else {
            if (expectedName && targetUnit.name !== expectedName) {
                diagnostics.push({
                    code: 'node-name-mismatch',
                    message: `C# declaration name "${targetUnit.name}" does not match expected node name "${expectedName}".`,
                });
            }
            if (targetUnit.kind === 'function' || targetUnit.kind === 'method') {
                for (const param of targetUnit.params ?? []) {
                    if (
                        !param.annotation ||
                        !param.annotation.trim() ||
                        param.annotation.trim() === 'var' ||
                        param.annotation.trim() === 'dynamic'
                    ) {
                        diagnostics.push({
                            code: 'jpl60-param-annotation',
                            message: `Parameter "${param.name}" in "${targetUnit.name}" is missing an explicit C# type annotation.`,
                        });
                    }
                }
                if (
                    !targetUnit.returnAnnotation ||
                    !targetUnit.returnAnnotation.trim() ||
                    targetUnit.returnAnnotation.trim() === 'var' ||
                    targetUnit.returnAnnotation.trim() === 'dynamic'
                ) {
                    diagnostics.push({
                        code: 'jpl60-return-annotation',
                        message: `Method "${targetUnit.name}" is missing an explicit C# return type annotation.`,
                    });
                }
            }
        }
    }

    if (options.requireContract && !contractText.trim()) {
        diagnostics.push({
            code: 'jpl60-contract-missing',
            message: `Node "${labelName}" is missing contract documentation.`,
        });
    }

    const result: Jpl60CheckResult = {
        valid: diagnostics.length === 0,
        lineCount,
        executableLines,
        diagnostics,
    };

    if (options.enforceJpl60 && !result.valid) {
        throw new AdapterError(result.diagnostics[0].message);
    }

    return result;
}

export class CSharpAdapter {
    readonly language = 'csharp' as const;

    async parseModule(source: string, documentPath = '<memory>', nodeId?: string): Promise<ParseModuleResult> {
        return parseCSharpModule(source, documentPath, nodeId);
    }

    async replaceUnit(params: Record<string, unknown>): Promise<SourceProposal> {
        return replaceCSharpUnit(params);
    }

    createStub(
        name: string,
        params?: ReadonlyArray<CSharpStubParamInput> | string,
        returnType?: string | null,
        options?: CreateCSharpStubOptions | string,
    ): string {
        return createCSharpStub(name, params, returnType, options);
    }

    checkNodeCode(
        input: string | string[] | SlateNode,
        expectedName?: string | CheckCSharpNodeOptions,
        options?: CheckCSharpNodeOptions,
    ): Jpl60CheckResult {
        return checkCSharpNodeCode(input, expectedName, options);
    }

    dispose(): void {}
}
