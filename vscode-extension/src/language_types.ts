export const GENERATED_SLASH_HEADER = '// Generated by Slate — do not edit by hand.';
export const GENERATED_SLASH_PREFIX = '// Generated by Slate';
export const GENERATED_HASH_HEADER = '# Generated by Slate — do not edit by hand.';
export const GENERATED_HASH_PREFIX = '# Generated by Slate';
export const GENERATED_MD_HEADER = '<!-- Generated by Slate Prose Mode -->';
export const GENERATED_TEX_HEADER = '% Generated by Slate Prose Mode';
export const RESERVED_OUTPUT_ROOTS = new Set(['slate', '.slate', '.git', '.vscode']);

/**
 * Normalize a language identifier or file extension alias into a canonical Slate language.
 * Throws an Error when the language is unknown.
 */
export function normalizeLanguage(lang: string): CanonicalLanguage {
    const cleaned = lang.trim().toLowerCase().replace(/^\./, '');
    const match = LANGUAGE_ALIASES[cleaned];
    if (!match) {
        throw new Error(`Unsupported language "${lang}". Expected one of: python, typescript, javascript, csharp, cpp, arduino, prose.`);
    }
    return match;
}

/**
 * Try normalizing a language or file extension without throwing.
 */
export function tryNormalizeLanguage(lang: string | undefined | null): CanonicalLanguage | null {
    if (!lang || typeof lang !== 'string') return null;
    try {
        return normalizeLanguage(lang);
    } catch {
        return null;
    }
}

/**
 * Infer canonical language from a file path's extension.
 */
export function inferLanguageFromPath(filePath: string): CanonicalLanguage | null {
    const normalized = filePath.replace(/\\/g, '/').trim();
    const dot = normalized.lastIndexOf('.');
    if (dot < 0 || dot === normalized.length - 1) return null;
    const ext = normalized.slice(dot + 1).toLowerCase();
    return LANGUAGE_ALIASES[ext] ?? null;
}

/**
 * Format the standard generated file header for a given language or file path.
 */
export function formatGeneratedHeaderForLanguage(langOrPath: string, sourceHint?: string): string {
    const lang = inferLanguageFromPath(langOrPath) ?? tryNormalizeLanguage(langOrPath) ?? 'typescript';
    if (lang === 'python') {
        return sourceHint
            ? `${GENERATED_HASH_PREFIX} from ${sourceHint}; edit the node files, not this file.`
            : GENERATED_HASH_HEADER;
    }
    if (lang === 'prose') {
        if (langOrPath.toLowerCase().endsWith('.tex')) return GENERATED_TEX_HEADER;
        return GENERATED_MD_HEADER;
    }
    return sourceHint
        ? `${GENERATED_SLASH_HEADER} (${sourceHint})`
        : GENERATED_SLASH_HEADER;
}

/**
 * Check whether a file's content carries a Slate generated marker header.
 */
export function isSlateGeneratedContent(content: string): boolean {
    const trimmed = content.replace(/^\uFEFF/, '').trimStart();
    return (
        trimmed.startsWith(GENERATED_SLASH_PREFIX) ||
        trimmed.startsWith(GENERATED_HASH_PREFIX) ||
        trimmed.startsWith('<!-- Generated by Slate') ||
        trimmed.startsWith('% Generated by Slate')
    );
}

/**
 * Normalize a relative compiler output file path using POSIX rules.
 * Returns null if the path is empty, absolute, contains a drive letter or null byte,
 * or traverses outside the output root via `..`.
 */
export function normalizeCompileOutputPath(rawPath: string): string | null {
    if (typeof rawPath !== 'string' || rawPath.includes('\0')) return null;
    const slashNormalized = rawPath.trim().replace(/\\/g, '/');
    if (!slashNormalized || slashNormalized.startsWith('/') || /^[A-Za-z]:/.test(slashNormalized)) {
        return null;
    }
    const stack: string[] = [];
    for (const seg of slashNormalized.split('/')) {
        if (!seg || seg === '.') continue;
        if (seg === '..') {
            if (stack.length === 0) return null;
            stack.pop();
        } else {
            stack.push(seg);
        }
    }
    return stack.length > 0 ? stack.join('/') : null;
}

/**
 * Normalize an `existingFiles` lookup map or record using POSIX compile output path rules.
 */
export function normalizeExistingFiles(
    existingFiles?: ReadonlyMap<string, string> | Record<string, string>,
): Map<string, string> {
    if (!existingFiles) return new Map();
    const entries = existingFiles instanceof Map ? [...existingFiles.entries()] : Object.entries(existingFiles);
    const out = new Map<string, string>();
    for (const [key, value] of entries) {
        const norm = normalizeCompileOutputPath(key);
        if (norm) out.set(norm, value);
    }
    return out;
}
