// Compile slate/ nodes into Python modules. Each node folder becomes one module
// (`a/b/` → `a/b.py`, or `a/b/__init__.py` when it also has subfolders);
// root-level nodes go into a module named after the project. Cross-module node
// references become absolute imports rooted at the output directory, so the
// output directory is the import root (like a ported project's original root).

export const GENERATED_HEADER = '# Generated by Slate';

export interface CompileDiagnostic {
    severity: 'error' | 'warning';
    message: string;
}

export interface CompileResult {
    /** Python files keyed by path relative to the output directory. */
    files: Map<string, string>;
    diagnostics: CompileDiagnostic[];
}

const folderOf = (nodeId: string) => nodeId.includes('/') ? nodeId.slice(0, nodeId.lastIndexOf('/')) : '';

export function projectModuleName(projectName: string): string {
    const name = projectName.toLowerCase().replace(/[^a-z0-9_]/g, '_');
    return /^[0-9]/.test(name) ? `_${name}` : name || 'project';
}

function blockOrder(node: SlateNode): number {
    return node.kind === 'prelude' ? 0 : node.kind === 'epilogue' ? 2 : 1;
}

/** Merge `from M import x` lines per module (first-seen order); keep other lines once. */
function mergeImports(lines: string[]): string[] {
    const merged: Array<{ module: string | null; line: string; names: string[] }> = [];
    for (const line of lines) {
        const match = line.match(/^from (\S+) import (.+)$/);
        if (!match || match[2] === '*') {
            if (!merged.some(entry => entry.line === line)) merged.push({ module: null, line, names: [] });
            continue;
        }
        const entry = merged.find(item => item.module === match[1]);
        if (!entry) merged.push({ module: match[1], line, names: [match[2]] });
        else if (!entry.names.includes(match[2])) entry.names.push(match[2]);
    }
    return merged.map(entry => entry.module ? `from ${entry.module} import ${entry.names.join(', ')}` : entry.line);
}

function comment(label: string, text: string): string[] {
    return text.trim() ? text.trim().split('\n').map((line, index) => `# ${index === 0 ? `${label}: ` : '  '}${line}`) : [];
}

/** `lib:<path>:<name>` → `from <module> import <name>` (the library root must be importable). */
export function libraryImport(target: string): string | null {
    const match = target.match(/^lib:(.+\.py):([A-Za-z_][A-Za-z0-9_]*)$/);
    if (!match) return null;
    const module = match[1].slice(0, -'.py'.length).replace(/\/__init__$/, '').replace(/\//g, '.');
    return `from ${module} import ${match[2]}`;
}

/** Signature of a definition node from its code, or null. */
export function nodeSignature(node: SlateNode): CallableSignature | null {
    if (node.kind) return null;
    const units = parseModule(`${node.code.join('\n')}\n`, '<signature>').units;
    const unit = units.find(item => item.parentId === null && item.name === node.name);
    return unit ? unitSignature(unit, units) : null;
}

const variable = (instanceId: string) => `v_${instanceId.replace(/[^A-Za-z0-9_]/g, '_')}`;

export function flowTarget(flowId: string, projectName: string): { module: string; functionName: string } {
    const rootMod = projectModuleName(projectName);
    if (flowId === MAIN_FLOW || flowId === 'main') {
        return { module: rootMod, functionName: 'main' };
    }
    const folder = folderOf(flowId);
    const fnName = flowId.includes('/') ? flowId.slice(flowId.lastIndexOf('/') + 1) : flowId;
    const module = folder ? folder.replace(/\//g, '.') : rootMod;
    return { module, functionName: fnName };
}

/**
 * Generate one Python function for a flow: instances in dependency order, each
 * assigned to a variable; unwired inputs use their defaults; outputs are
 * returned (a tuple when there are several). Returns a node for the compiler.
 */
export function flowToNode(
    flowId: string,
    flow: SlateFlow,
    resolve: (target: string) => { signature: CallableSignature; imports: string[] } | null,
    diagnostics: CompileDiagnostic[],
    options?: { trace?: boolean },
): SlateNode | null {
    const label = `flows/${flowId}`;
    const errors: string[] = [];
    const resolveAny = (target: string) =>
        resolve(target) ?? (target.startsWith('flow:') ? resolve(target.slice('flow:'.length)) : null);
    const signatureToFlow = (sig: CallableSignature): SlateFlow => ({
        name: sig.name,
        inputs: sig.params
            .filter(p => p.kind === 'positional' || p.kind === 'keyword')
            .map(p => ({ name: p.name, annotation: p.annotation })),
        outputs: sig.outputs ?? [{ name: 'out', annotation: sig.returns }],
        instances: [],
        wires: [],
        extra: {},
    });
    const flowLookup = (childFlowId: string): SlateFlow | undefined => {
        const res = resolveAny(childFlowId);
        return res ? signatureToFlow(res.signature) : undefined;
    };

    const signatures = new Map<string, CallableSignature | null>();
    for (const instance of flow.instances) {
        if (instance.kind === 'value') { signatures.set(instance.id, null); continue; }
        if (instance.kind === 'viewer') {
            signatures.set(instance.id, { name: 'viewer', params: [{ name: 'in', annotation: null, default: null, kind: 'positional' }], returns: null });
            continue;
        }
        const resolved = resolveAny(instance.node!);
        if (!resolved) errors.push(`instance ${instance.id} calls ${instance.node}, which does not exist`);
        signatures.set(instance.id, resolved?.signature ?? null);
    }

    const regionsById = new Map<string, FlowRegion>();
    const regionPortMap = new Map<string, RegionPorts>();
    for (const region of flow.regions ?? []) {
        regionsById.set(region.id, region);
        if (region.kind === 'branch') {
            const thenRes = resolveAny(region.thenFlow);
            if (!thenRes) errors.push(`region ${region.id} calls ${region.thenFlow}, which does not exist`);
            if (region.elseFlow && !resolveAny(region.elseFlow)) {
                errors.push(`region ${region.id} calls ${region.elseFlow}, which does not exist`);
            }
        } else {
            if (!resolveAny(region.bodyFlow)) {
                errors.push(`region ${region.id} calls ${region.bodyFlow}, which does not exist`);
            }
        }
        try {
            regionPortMap.set(region.id, regionPorts(region, flowLookup));
        } catch {
            // Child flow resolution error already recorded above
        }
    }

    const names = new Map<string, string>();
    for (const instance of flow.instances) {
        const name = variable(instance.id);
        if (names.has(name) || flow.inputs.some(input => input.name === name)) errors.push(`instance ${instance.id} needs a distinct variable name (${name})`);
        names.set(name, instance.id);
    }
    for (const region of flow.regions ?? []) {
        const name = variable(region.id);
        if (names.has(name) || flow.inputs.some(input => input.name === name)) errors.push(`region ${region.id} needs a distinct variable name (${name})`);
        names.set(name, region.id);
    }

    const outputsOf = (id: string) => {
        if (regionsById.has(id)) {
            return regionPortMap.get(id)?.outputs ?? [];
        }
        const signature = signatures.get(id);
        return signature ? outputPorts(signature) : [{ id: 'out', name: 'out', annotation: null }];
    };

    const usedNames = new Set([
        ...flow.inputs.map(input => input.name),
        ...[...signatures.values()].flatMap(signature => signature ? [signature.name] : []),
        ...flow.instances.flatMap(instance => [variable(instance.id), ...outputsOf(instance.id)
            .map(port => variable(instance.id) + '_' + port.name)]),
        ...(flow.regions ?? []).flatMap(region => {
            const targets = region.kind === 'branch' ? [region.thenFlow, region.elseFlow] : [region.bodyFlow];
            return targets.flatMap(target => target ? [resolveAny(target)?.signature.name ?? target] : []);
        }),
    ]);
    const allocate = (preferred: string) => {
        let name = preferred;
        for (let n = 2; usedNames.has(name); n++) name = preferred + '_' + n;
        usedNames.add(name);
        return name;
    };
    const regionVariables = new Map([...regionPortMap].map(([id, ports]) =>
        [id, new Map(ports.outputs.map(port =>
            [port.name, allocate(ports.outputs.length === 1 ? variable(id) : variable(id) + '_' + port.name)]))]));

    const incoming = new Map<string, string>();
    for (const wire of flow.wires) {
        const from = parseEndpoint(wire.from);
        const to = parseEndpoint(wire.to);
        const fromRegionPorts = from.instance !== null ? regionPortMap.get(from.instance) : undefined;
        const fromOk = from.instance === null
            ? from.port.startsWith('input:') && flow.inputs.some(input => `input:${input.name}` === from.port)
            : fromRegionPorts
                ? fromRegionPorts.outputs.some(port => port.id === from.port) ||
                  (fromRegionPorts.outputs.length === 1 && (from.port === 'out' || from.port === `out:${fromRegionPorts.outputs[0].name}`))
                : signatures.has(from.instance) && outputsOf(from.instance).some(port => port.id === from.port);
        const isViewerTo = flow.instances.find(i => i.id === to.instance)?.kind === 'viewer';
        const toRegionPorts = to.instance !== null ? regionPortMap.get(to.instance) : undefined;
        const toOk = to.instance === null
            ? to.port.startsWith('output:') && flow.outputs.some(output => `output:${output.name}` === to.port)
            : toRegionPorts
                ? toRegionPorts.inputs.some(port => port.id === to.port)
                : signatures.has(to.instance) && (
                    (signatures.get(to.instance)?.params ?? []).some(param => `in:${param.name}` === to.port) ||
                    (isViewerTo && (to.port === 'in' || to.port === 'in:in'))
                );
        if (!fromOk || !toOk) errors.push(`wire ${wire.from} → ${wire.to} has an unknown endpoint`);
        else if (incoming.has(wire.to)) errors.push(`${wire.to} has more than one wire`);
        else incoming.set(wire.to, wire.from);
    }
    const expression = (endpoint: string) => {
        const { instance, port } = parseEndpoint(endpoint);
        if (instance === null) return port.slice('input:'.length);
        const rPorts = regionPortMap.get(instance);
        if (rPorts) {
            const name = rPorts.outputs.length === 1 ? rPorts.outputs[0].name : port.slice('out:'.length);
            return regionVariables.get(instance)?.get(name) ?? 'None';
        }
        return port === 'out' ? variable(instance) : `${variable(instance)}_${port.slice('out:'.length)}`;
    };

    // Kahn's algorithm in instance and region order; leftovers form a cycle.
    const order: string[] = [];
    const pending = new Set([
        ...flow.instances.map(instance => instance.id),
        ...(flow.regions ?? []).map(region => region.id),
    ]);
    while (pending.size) {
        const ready = [...pending].find(id => [...incoming].every(([to, from]) =>
            parseEndpoint(to).instance !== id || parseEndpoint(from).instance === null || !pending.has(parseEndpoint(from).instance!)));
        if (!ready) { errors.push(`instances ${[...pending].join(', ')} form a cycle`); break; }
        order.push(ready);
        pending.delete(ready);
    }

    const body: string[] = [];
    for (const id of order) {
        const region = regionsById.get(id);
        if (region) {
            const rPorts = regionPortMap.get(id);
            if (!rPorts) continue;
            const slug = id.replace(/[^A-Za-z0-9_]/g, '_');
            const output = (name: string) => regionVariables.get(id)!.get(name)!;
            const traceError = options?.trace ? allocate('_slate_err') : '';

            if (region.kind === 'branch') {
                const thenSig = resolveAny(region.thenFlow)?.signature;
                const elseSig = region.elseFlow ? resolveAny(region.elseFlow)?.signature : undefined;
                if (!thenSig || (region.elseFlow && !elseSig)) continue;
                if (elseSig && !branchOutputsMatch(signatureToFlow(thenSig), signatureToFlow(elseSig))) {
                    errors.push(`${id} branches must expose compatible outputs by name`);
                    continue;
                }

                const condPort = region.conditionPort ?? 'condition';
                const condSource = incoming.get(`${id}.in:${condPort}`);
                if (!condSource) errors.push(`${id}.in:${condPort} is not wired and has no default`);
                const condExpr = condSource ? expression(condSource) : 'False';
                const wiredInputs: Array<{ portName: string; expr: string }> = [];
                if (condSource) wiredInputs.push({ portName: condPort, expr: condExpr });

                const buildBranchCall = (sig: CallableSignature) => {
                    const args: string[] = [];
                    let skippedPos = false;
                    for (const param of sig.params) {
                        if (param.kind === 'var' || param.kind === 'kwvar') continue;
                        const src = incoming.get(`${id}.in:${param.name}`);
                        if (!src) {
                            if (param.default === null) errors.push(`${id}.in:${param.name} is not wired and has no default`);
                            if (param.kind === 'positional') skippedPos = true;
                            continue;
                        }
                        const expr = expression(src);
                        if (!wiredInputs.some(w => w.portName === param.name)) {
                            wiredInputs.push({ portName: param.name, expr });
                        }
                        if (param.kind === 'positional') {
                            if (skippedPos) errors.push(`${id}.in:${param.name} is positional-only after an unwired one`);
                            args.push(expr);
                        } else {
                            args.push(`${param.name}=${expr}`);
                        }
                    }
                    return `${sig.name}(${args.join(', ')})`;
                };

                const thenCall = buildBranchCall(thenSig);
                const elseCall = elseSig ? buildBranchCall(elseSig) : null;
                const outVars = rPorts.outputs.map(port => output(port.name));
                const lhs = outVars.join(', ');
                const elseLhs = elseSig ? signatureToFlow(elseSig).outputs.map(port => output(port.name)).join(', ') : '';
                const defaultRhs = outVars.length <= 1 ? 'None' : outVars.map(() => 'None').join(', ');

                if (options?.trace) {
                    body.push(`    with _slate_trace.scope("${id}"):`);
                    body.push(`        try:`);
                    for (const input of wiredInputs) {
                        body.push(`            _slate_trace.trace_input("${id}", "in:${input.portName}", ${input.expr})`);
                    }
                    body.push(`            if ${condExpr}:`);
                    body.push(`                with _slate_trace.scope("then"):`);
                    body.push(`                    ${lhs ? `${lhs} = ${thenCall}` : thenCall}`);
                    body.push(`            else:`);
                    if (elseCall) {
                        body.push(`                with _slate_trace.scope("else"):`);
                        body.push(`                    ${elseLhs ? `${elseLhs} = ${elseCall}` : elseCall}`);
                    } else {
                        body.push(`                ${lhs ? `${lhs} = ${defaultRhs}` : 'pass'}`);
                    }
                    for (let i = 0; i < rPorts.outputs.length; i++) {
                        body.push(`            _slate_trace.trace_output("${id}", "${rPorts.outputs[i].id}", ${outVars[i]})`);
                    }
                    body.push(`        except Exception as ${traceError}:`);
                    body.push(`            _slate_trace.trace_error("${id}", f"{type(${traceError}).__name__}: {${traceError}}")`);
                    body.push(`            raise`);
                } else {
                    body.push(`    if ${condExpr}:`);
                    body.push(`        ${lhs ? `${lhs} = ${thenCall}` : thenCall}`);
                    body.push(`    else:`);
                    if (elseCall) {
                        body.push(`        ${elseLhs ? `${elseLhs} = ${elseCall}` : elseCall}`);
                    } else {
                        body.push(`        ${lhs ? `${lhs} = ${defaultRhs}` : 'pass'}`);
                    }
                }
                continue;
            }

            if (region.kind === 'foreach') {
                const bodySig = resolveAny(region.bodyFlow)?.signature;
                if (!bodySig) continue;

                const itemVar = allocate('_item');
                const indexVar = allocate('_idx');
                const collPort = region.collectionPort ?? 'items';
                const itemPort = region.itemPort ?? 'item';
                const indexPort = region.indexPort ?? 'index';
                const collSource = incoming.get(`${id}.in:${collPort}`);
                if (!collSource) errors.push(`${id}.in:${collPort} is not wired and has no default`);
                const collExpr = collSource ? expression(collSource) : '[]';
                const wiredInputs: Array<{ portName: string; expr: string }> = [];
                if (collSource) wiredInputs.push({ portName: collPort, expr: collExpr });

                const bodyArgs: string[] = [];
                let skippedPos = false;
                for (const param of bodySig.params) {
                    if (param.kind === 'var' || param.kind === 'kwvar') continue;
                    let argExpr: string | null = null;
                    if (param.name === itemPort) {
                        argExpr = itemVar;
                    } else if (param.name === indexPort) {
                        argExpr = indexVar;
                    } else {
                        const src = incoming.get(`${id}.in:${param.name}`);
                        if (!src) {
                            if (param.default === null) errors.push(`${id}.in:${param.name} is not wired and has no default`);
                            if (param.kind === 'positional') skippedPos = true;
                            continue;
                        }
                        argExpr = expression(src);
                        wiredInputs.push({ portName: param.name, expr: argExpr });
                    }
                    if (param.kind === 'positional') {
                        if (skippedPos) errors.push(`${id}.in:${param.name} is positional-only after an unwired one`);
                        bodyArgs.push(argExpr);
                    } else {
                        bodyArgs.push(`${param.name}=${argExpr}`);
                    }
                }
                const bodyCall = `${bodySig.name}(${bodyArgs.join(', ')})`;
                const outVars = rPorts.outputs.map(port => output(port.name));

                const itemVars = rPorts.outputs.map(port => allocate(outVars.length === 1 ? `_item_${slug}` : `_item_${slug}_${port.name}`));
                if (options?.trace) {
                    body.push(`    with _slate_trace.scope("${id}"):`);
                    body.push(`        try:`);
                    for (const input of wiredInputs) {
                        body.push(`            _slate_trace.trace_input("${id}", "in:${input.portName}", ${input.expr})`);
                    }
                    for (const ov of outVars) {
                        body.push(`            ${ov} = []`);
                    }
                    body.push(`            for ${indexVar}, ${itemVar} in enumerate(${collExpr}):`);
                    if (region.maxIterations !== undefined) {
                        body.push(`                if ${indexVar} >= ${region.maxIterations}:`);
                        body.push(`                    break`);
                    }
                    body.push(`                with _slate_trace.scope(f"iter:{${indexVar}}"):`);
                    body.push(`                    _slate_trace.trace_input("${id}", "in:${itemPort}", ${itemVar})`);
                    if (outVars.length === 0) {
                        body.push(`                    ${bodyCall}`);
                    } else if (outVars.length === 1) {
                        body.push(`                    ${itemVars[0]} = ${bodyCall}`);
                        body.push(`                    ${outVars[0]}.append(${itemVars[0]})`);
                    } else {
                        body.push(`                    ${itemVars.join(', ')} = ${bodyCall}`);
                        for (let i = 0; i < outVars.length; i++) {
                            body.push(`                    ${outVars[i]}.append(${itemVars[i]})`);
                        }
                    }
                    for (let i = 0; i < rPorts.outputs.length; i++) {
                        body.push(`            _slate_trace.trace_output("${id}", "${rPorts.outputs[i].id}", ${outVars[i]})`);
                    }
                    body.push(`        except Exception as ${traceError}:`);
                    body.push(`            _slate_trace.trace_error("${id}", f"{type(${traceError}).__name__}: {${traceError}}")`);
                    body.push(`            raise`);
                } else {
                    for (const ov of outVars) {
                        body.push(`    ${ov} = []`);
                    }
                    body.push(`    for ${indexVar}, ${itemVar} in enumerate(${collExpr}):`);
                    if (region.maxIterations !== undefined) {
                        body.push(`        if ${indexVar} >= ${region.maxIterations}:`);
                        body.push(`            break`);
                    }
                    if (outVars.length === 0) {
                        body.push(`        ${bodyCall}`);
                    } else if (outVars.length === 1) {
                        body.push(`        ${itemVars[0]} = ${bodyCall}`);
                        body.push(`        ${outVars[0]}.append(${itemVars[0]})`);
                    } else {
                        body.push(`        ${itemVars.join(', ')} = ${bodyCall}`);
                        for (let i = 0; i < outVars.length; i++) {
                            body.push(`        ${outVars[i]}.append(${itemVars[i]})`);
                        }
                    }
                }
                continue;
            }

            if (region.kind === 'repeat') {
                const bodySig = resolveAny(region.bodyFlow)?.signature;
                const bodyFlow = flowLookup(region.bodyFlow);
                if (!bodySig || !bodyFlow) continue;

                const inputNames = new Set(bodyFlow.inputs.map(p => p.name));
                const stateNames = new Set(repeatStatePortNames(region, bodyFlow));
                const stateOutputs = bodyFlow.outputs.filter(p => stateNames.has(p.name));

                if ([...stateNames].some(name => !inputNames.has(name) || !stateOutputs.some(port => port.name === name))) {
                    errors.push(`${id} state ports must be declared as both inputs and outputs`);
                    continue;
                }
                if (region.conditionPort && !bodyFlow.outputs.some(port => port.name === region.conditionPort)) {
                    errors.push(`${id} condition port must be a body output`);
                    continue;
                }
                const iterationVar = allocate('_iter');
                const conditionVar = allocate(`_cond_${slug}`);
                const stateVarFor = output;

                const wiredInputs: Array<{ portName: string; expr: string }> = [];
                const initLines: string[] = [];
                for (const sName of stateNames) {
                    const src = incoming.get(`${id}.in:${sName}`);
                    if (!src) errors.push(`${id}.in:${sName} is not wired and has no default`);
                    const expr = src ? expression(src) : 'None';
                    if (src) wiredInputs.push({ portName: sName, expr });
                    initLines.push(`${stateVarFor(sName)} = ${expr}`);
                }

                const bodyArgs: string[] = [];
                let skippedPos = false;
                for (const param of bodySig.params) {
                    if (param.kind === 'var' || param.kind === 'kwvar') continue;
                    let argExpr: string | null = null;
                    if (stateNames.has(param.name)) {
                        argExpr = stateVarFor(param.name);
                    } else {
                        const src = incoming.get(`${id}.in:${param.name}`);
                        if (!src) {
                            if (param.default === null) errors.push(`${id}.in:${param.name} is not wired and has no default`);
                            if (param.kind === 'positional') skippedPos = true;
                            continue;
                        }
                        argExpr = expression(src);
                        wiredInputs.push({ portName: param.name, expr: argExpr });
                    }
                    if (param.kind === 'positional') {
                        if (skippedPos) errors.push(`${id}.in:${param.name} is positional-only after an unwired one`);
                        bodyArgs.push(argExpr);
                    } else {
                        bodyArgs.push(`${param.name}=${argExpr}`);
                    }
                }

                const bodyCall = `${bodySig.name}(${bodyArgs.join(', ')})`;
                const bodyOutputs = bodyFlow.outputs;
                let callLine: string;
                if (bodyOutputs.length === 0) {
                    callLine = bodyCall;
                } else if (bodyOutputs.length === 1) {
                    const outName = bodyOutputs[0].name;
                    const targetVar = stateNames.has(outName) ? stateVarFor(outName) : conditionVar;
                    callLine = `${targetVar} = ${bodyCall}`;
                } else {
                    const unpackVars = bodyOutputs.map(p => {
                        if (stateNames.has(p.name)) return stateVarFor(p.name);
                        if (region.conditionPort === p.name) return conditionVar;
                        return allocate(`_unused_${slug}_${p.name}`);
                    });
                    callLine = `${unpackVars.join(', ')} = ${bodyCall}`;
                }

                const condCheckVar = region.conditionPort
                    ? (stateNames.has(region.conditionPort) ? stateVarFor(region.conditionPort) : conditionVar)
                    : null;

                if (options?.trace) {
                    body.push(`    with _slate_trace.scope("${id}"):`);
                    body.push(`        try:`);
                    for (const input of wiredInputs) {
                        body.push(`            _slate_trace.trace_input("${id}", "in:${input.portName}", ${input.expr})`);
                    }
                    for (const line of initLines) {
                        body.push(`            ${line}`);
                    }
                    body.push(`            for ${iterationVar} in range(${region.maxIterations}):`);
                    body.push(`                with _slate_trace.scope(f"iter:{${iterationVar}}"):`);
                    body.push(`                    ${callLine}`);
                    for (const port of rPorts.outputs) {
                        body.push(`                    _slate_trace.trace_output("${id}", "${port.id}", ${stateVarFor(port.name)})`);
                    }
                    if (condCheckVar) {
                        body.push(`                if not ${condCheckVar}:`);
                        body.push(`                    break`);
                    }
                    for (const port of rPorts.outputs) {
                        const outVar = stateVarFor(port.name);
                        body.push(`            _slate_trace.trace_output("${id}", "${port.id}", ${outVar})`);
                    }
                    body.push(`        except Exception as ${traceError}:`);
                    body.push(`            _slate_trace.trace_error("${id}", f"{type(${traceError}).__name__}: {${traceError}}")`);
                    body.push(`            raise`);
                } else {
                    for (const line of initLines) {
                        body.push(`    ${line}`);
                    }
                    body.push(`    for ${iterationVar} in range(${region.maxIterations}):`);
                    body.push(`        ${callLine}`);
                    if (condCheckVar) {
                        body.push(`        if not ${condCheckVar}:`);
                        body.push(`            break`);
                    }
                }
                continue;
            }
        }

        const instance = flow.instances.find(item => item.id === id)!;
        if (instance.kind === 'value') {
            const pyVal = compileValueToPython(instance.value);
            if (options?.trace) {
                body.push(`    with _slate_trace.scope("${id}"):`);
                body.push(`        ${variable(id)} = ${pyVal}`);
                body.push(`        _slate_trace.trace_output("${id}", "out", ${variable(id)})`);
            } else {
                body.push(`    ${variable(id)} = ${pyVal}`);
            }
            continue;
        }
        if (instance.kind === 'viewer') {
            const source = incoming.get(`${id}.in`) ?? incoming.get(`${id}.in:in`);
            const sourceExpr = source ? expression(source) : 'None';
            if (options?.trace) {
                body.push(`    with _slate_trace.scope("${id}"):`);
                body.push(`        _slate_trace.trace_input("${id}", "in", ${sourceExpr})`);
            }
            continue;
        }
        const signature = signatures.get(id);
        if (!signature) continue;
        const args: string[] = [];
        let skippedPositional = false;
        const wiredInputs: Array<{ paramName: string; expr: string }> = [];
        for (const param of signature.params) {
            if (param.kind === 'var' || param.kind === 'kwvar') continue;
            const source = incoming.get(`${id}.in:${param.name}`);
            if (!source) {
                if (param.default === null) errors.push(`${id}.in:${param.name} is not wired and has no default`);
                if (param.kind === 'positional') skippedPositional = true;
                continue;
            }
            const expr = expression(source);
            wiredInputs.push({ paramName: param.name, expr });
            if (param.kind === 'positional') {
                if (skippedPositional) errors.push(`${id}.in:${param.name} is positional-only after an unwired one`);
                args.push(expr);
            } else args.push(`${param.name}=${expr}`);
        }
        const call = `${signature.name}(${args.join(', ')})`;
        const outputs = outputPorts(signature);

        if (options?.trace) {
            body.push(`    with _slate_trace.scope("${id}"):`);
            body.push(`        try:`);
            for (const input of wiredInputs) {
                body.push(`            _slate_trace.trace_input("${id}", "in:${input.paramName}", ${input.expr})`);
            }
            if (signature.outputs && signature.outputs.length === 0) {
                body.push(`            ${call}`);
                body.push(`            _slate_trace.trace_output("${id}", "out", None)`);
            } else if (signature.outputs && signature.outputs.length > 1) {
                body.push(`            ${outputs.map(port => expression(`${id}.${port.id}`)).join(', ')} = ${call}`);
                for (const port of outputs) {
                    body.push(`            _slate_trace.trace_output("${id}", "${port.id}", ${expression(`${id}.${port.id}`)})`);
                }
            } else {
                body.push(`            ${variable(id)} = ${call}`);
                body.push(`            _slate_trace.trace_output("${id}", "out", ${variable(id)})`);
            }
            body.push(`        except Exception as _slate_err:`);
            body.push(`            _slate_trace.trace_error("${id}", f"{type(_slate_err).__name__}: {_slate_err}")`);
            body.push(`            raise`);
        } else {
            if (signature.outputs && signature.outputs.length === 0) body.push(`    ${call}`);
            else if (signature.outputs && signature.outputs.length > 1) {
                body.push(`    ${outputs.map(port => expression(`${id}.${port.id}`)).join(', ')} = ${call}`);
            } else body.push(`    ${variable(id)} = ${call}`);
        }
    }
    for (const input of flow.inputs) {
        if (!flow.wires.some(wire => wire.from === `input:${input.name}`)) {
            diagnostics.push({ severity: 'warning', message: `${label}: input ${input.name} is unused.` });
        }
    }
    const results = flow.outputs.map(output => {
        const source = incoming.get(`output:${output.name}`);
        if (!source) errors.push(`output ${output.name} is not wired`);
        return source ? expression(source) : 'None';
    });
    if (options?.trace) {
        for (let i = 0; i < flow.outputs.length; i++) {
            const output = flow.outputs[i];
            const source = incoming.get(`output:${output.name}`);
            if (source) {
                body.push(`    _slate_trace.trace_flow_output("${output.name}", ${results[i]})`);
            }
        }
    }
    if (results.length === 1) body.push(`    return ${results[0]}`);
    else if (results.length > 1) body.push(`    return (${results.join(', ')})`);
    if (body.length === 0) body.push('    pass');

    if (errors.length) {
        for (const message of errors) diagnostics.push({ severity: 'error', message: `${label}: ${message}.` });
        return null;
    }
    const parameters = flow.inputs.map(input => input.annotation ? `${input.name}: ${input.annotation}` : input.name).join(', ');
    const annotations = flow.outputs.map(output => output.annotation);
    const returns = flow.outputs.length === 0 ? ' -> None'
        : annotations.every(Boolean) ? ` -> ${annotations.length === 1 ? annotations[0] : `tuple[${annotations.join(', ')}]`}` : '';
    const code = [`def ${flow.name}(${parameters})${returns}:`, ...body];
    const used = identifierNames(code.join('\n'));
    const regionTargets = (flow.regions ?? []).flatMap(r => {
        if (r.kind === 'branch') return r.elseFlow ? [r.thenFlow, r.elseFlow] : [r.thenFlow];
        return [r.bodyFlow];
    }).map(t => t.startsWith('flow:') ? t.slice('flow:'.length) : t);
    const instanceTargets = flow.instances.filter(instance => instance.node).map(instance => instance.node!);
    const targets = [...new Set([...instanceTargets, ...regionTargets])];
    const imports = [...new Set(targets.flatMap(target => resolveAny(target)?.imports ?? []))]
        .filter(line => splitImport(line).some(item => item.binding !== null && used.has(item.binding)));
    const typingNames = ['Any', 'Dict', 'List', 'Optional', 'Set', 'Tuple', 'Union'].filter(
        name => used.has(name) && !imports.some(line => splitImport(line).some(item => item.binding === name)),
    );
    if (typingNames.length > 0) {
        imports.push(`from typing import ${typingNames.join(', ')}`);
    }
    if (options?.trace) {
        imports.push('import _slate_trace');
    }
    return {
        name: flow.name, intent: '', contract: '', context: [], examples: [], locked: true,
        order: 1e9, imports, uses: targets.sort(), code, extra: { flow: true },
    };
}

export function compilePython(
    sourceNodes: ReadonlyMap<string, SlateNode>,
    config: SlateConfig,
    flows: ReadonlyMap<string, SlateFlow> = new Map(),
    library: ReadonlyMap<string, CallableSignature> = new Map(),
    options?: { checkJpl60?: boolean; trace?: boolean },
): CompileResult {
    const diagnostics: CompileDiagnostic[] = [];
    const error = (message: string) => diagnostics.push({ severity: 'error', message });
    const nodes = new Map(sourceNodes);
    const resolve = (target: string) => {
        const clean = target.startsWith('flow:') ? target.slice('flow:'.length) : target;
        const node = sourceNodes.get(clean);
        const flow = node ? undefined : flows.get(clean);
        if (flow) return { signature: flowSignature(flow), imports: [] };
        const signature = node ? nodeSignature(node) : library.get(target) ?? library.get(clean) ?? null;
        return signature ? { signature, imports: node?.imports ?? [] } : null;
    };
    for (const [flowId, flow] of [...flows].sort(([left], [right]) => left.localeCompare(right))) {
        if (flowId === MAIN_FLOW && flow.instances.length === 0 && (!flow.regions || flow.regions.length === 0)) continue;
        if (sourceNodes.has(flowId)) { error(`flows/${flowId} has the same id as a node.`); continue; }
        const node = flowToNode(flowId, flow, resolve, diagnostics, options);
        if (node) nodes.set(flowId, node);
    }
    const valid = new Map<string, SlateNode>();
    for (const [nodeId, node] of nodes) {
        const language = node.language ?? config.language;
        if (language !== 'python') error(`${nodeId}: no compiler for language "${language}".`);
        else if (!parseModule(`${node.code.join('\n')}\n`, nodeId).valid) error(`${nodeId}: code is not valid Python.`);
        else valid.set(nodeId, node);
    }

    if (options?.checkJpl60) {
        for (const [nodeId, node] of valid) {
            if (node.kind) continue;
            const jpl = checkJpl60(node);
            for (const diag of jpl.diagnostics) {
                diagnostics.push({ severity: 'warning', message: `${nodeId}: ${diag.message}` });
            }
        }
    }

    const folders = [...new Set([...valid.keys()].map(folderOf))].sort();
    const rootModule = projectModuleName(config.name);
    if (folders.includes('') && folders.includes(rootModule)) error(`Folder ${rootModule}/ collides with the module for root-level nodes (${rootModule}.py).`);
    const hasChildren = (folder: string) => folders.some(other => other !== folder && other.startsWith(`${folder}/`));
    const moduleName = (folder: string) => folder ? folder.replace(/\//g, '.') : rootModule;
    const modulePath = (folder: string) => !folder ? `${rootModule}.py`
        : hasChildren(folder) ? `${folder}/__init__.py` : `${folder}.py`;

    const preludeNames = new Map<string, Set<string>>();
    const definitions = new Map<string, string[]>();
    for (const [nodeId, node] of valid) {
        if (node.kind === 'prelude') preludeNames.set(nodeId, topLevelBindings(node.code.join('\n')));
        else if (!node.kind) definitions.set(node.name, [...(definitions.get(node.name) ?? []), nodeId]);
    }

    const files = new Map<string, string>();
    const moduleEdges = new Map<string, Set<string>>();
    for (const folder of folders) {
        const members = [...valid].filter(([nodeId]) => folderOf(nodeId) === folder).sort(([leftId, left], [rightId, right]) =>
            blockOrder(left) - blockOrder(right)
            || (left.order ?? Number.MAX_SAFE_INTEGER) - (right.order ?? Number.MAX_SAFE_INTEGER)
            || leftId.localeCompare(rightId));
        const localNames = new Set<string>();
        for (const [nodeId, node] of members) {
            if (node.kind === 'prelude') preludeNames.get(nodeId)!.forEach(name => localNames.add(name));
            else if (!node.kind) localNames.add(node.name);
        }

        const external: string[] = [];
        const crossModule: string[] = [];
        const origins = new Map<string, string>();
        const bind = (name: string, origin: string, nodeId: string) => {
            const previous = origins.get(name);
            if (previous && previous !== origin) error(`${modulePath(folder)}: name collision on "${name}" (${previous} vs ${origin}, in ${nodeId}).`);
            else origins.set(name, origin);
        };
        for (const [nodeId, node] of members) if (!node.kind) bind(node.name, `node ${nodeId}`, nodeId);

        for (const [nodeId, node] of members) {
            const names = identifierNames(node.code.join('\n'));
            const own = new Set<string>();
            for (const line of node.imports) {
                const parsed = splitImport(line);
                if (!parsed.length) error(`${nodeId}: "${line}" is not an import.`);
                for (const item of parsed) {
                    external.push(item.line);
                    if (!item.binding) continue;
                    own.add(item.binding);
                    // `import a.b` and `import a.c` both bind `a` compatibly.
                    bind(item.binding, item.name === null && !item.line.includes(' as ') ? `"import ${item.binding}…"` : `"${item.line}"`, nodeId);
                }
            }
            const importFrom = (target: string, name: string) => {
                const line = `from ${moduleName(folderOf(target))} import ${name}`;
                crossModule.push(line);
                own.add(name);
                bind(name, `"${line}"`, nodeId);
                moduleEdges.set(folder, (moduleEdges.get(folder) ?? new Set()).add(folderOf(target)));
            };
            for (const target of node.uses) {
                const external = libraryImport(target);
                if (external) {
                    if (!library.has(target)) error(`${nodeId} uses ${target}, which is not in the library.`);
                    const item = splitImport(external)[0];
                    if (names.has(item.binding!)) { crossModule.push(external); own.add(item.binding!); bind(item.binding!, `"${external}"`, nodeId); }
                    continue;
                }
                const used = valid.get(target);
                if (!used) {
                    error(`${nodeId} uses ${target}, which ${nodes.has(target) ? 'did not compile' : 'does not exist'}.`);
                    continue;
                }
                if (folderOf(target) === folder) continue;
                if (used.kind === 'prelude') [...preludeNames.get(target)!].filter(name => names.has(name)).forEach(name => importFrom(target, name));
                else if (!used.kind && names.has(used.name)) importFrom(target, used.name);
            }
            // Bare names not resolved by the folder, imports, or `uses`: a unique node elsewhere.
            for (const name of names) {
                if (name === node.name || own.has(name) || localNames.has(name)) continue;
                const candidates = (definitions.get(name) ?? []).filter(candidate => folderOf(candidate) !== folder);
                if (candidates.length === 1) importFrom(candidates[0], name);
                else if (candidates.length > 1) error(`${nodeId}: "${name}" matches ${candidates.join(', ')}; add the intended one to "uses".`);
            }
        }

        const future = external.filter(line => line.startsWith('from __future__ '));
        const sections = [
            [`${GENERATED_HEADER} from slate/nodes/${folder}${folder ? '/' : ''}; edit the node files, not this file.`],
            mergeImports(future),
            [...mergeImports(external.filter(line => !future.includes(line))), ...mergeImports(crossModule)],
        ].filter(section => section.length).map(section => section.join('\n'));
        const blocks = members.map(([nodeId, node]) => [
            `# slate: ${node.extra?.flow ? 'flows' : 'nodes'}/${nodeId}`,
            ...comment('intent', node.intent),
            ...comment('contract', node.contract),
            ...node.code,
        ].join('\n'));
        files.set(modulePath(folder), `${[sections.join('\n\n'), ...blocks].join('\n\n\n')}\n`);
    }

    for (const folder of folders) {
        const parts = folder.split('/');
        for (let depth = 1; depth < parts.length; depth++) {
            const packagePath = `${parts.slice(0, depth).join('/')}/__init__.py`;
            if (!files.has(packagePath)) files.set(packagePath, `${GENERATED_HEADER}; package marker.\n`);
        }
    }

    const visiting: string[] = [];
    const done = new Set<string>();
    const reported = new Set<string>();
    const visit = (folder: string) => {
        if (done.has(folder)) return;
        const at = visiting.indexOf(folder);
        if (at >= 0) {
            const cycle = [...visiting.slice(at), folder].map(modulePath).join(' → ');
            if (!reported.has(cycle)) diagnostics.push({ severity: 'warning', message: `Import cycle: ${cycle}.` });
            reported.add(cycle);
            return;
        }
        visiting.push(folder);
        for (const next of [...(moduleEdges.get(folder) ?? [])].sort()) visit(next);
        visiting.pop();
        done.add(folder);
    };
    folders.forEach(visit);

    if (options?.trace) {
        files.set('_slate_trace.py', SLATE_TRACE_PY);
    }

    return { files: new Map([...files].sort(([left], [right]) => left.localeCompare(right))), diagnostics };
}
