import { identifierNames, parseModule, splitImport, topLevelBindings } from '../python_adapter';
import type { SlateConfig, SlateNode } from '../slate_folder';

// Compile slate/ nodes into Python modules. Each node folder becomes one module
// (`a/b/` → `a/b.py`, or `a/b/__init__.py` when it also has subfolders);
// root-level nodes go into a module named after the project. Cross-module node
// references become absolute imports rooted at the output directory, so the
// output directory is the import root (like a ported project's original root).

export const GENERATED_HEADER = '# Generated by Slate';

export interface CompileDiagnostic {
    severity: 'error' | 'warning';
    message: string;
}

export interface CompileResult {
    /** Python files keyed by path relative to the output directory. */
    files: Map<string, string>;
    diagnostics: CompileDiagnostic[];
}

const folderOf = (nodeId: string) => nodeId.includes('/') ? nodeId.slice(0, nodeId.lastIndexOf('/')) : '';

export function projectModuleName(projectName: string): string {
    const name = projectName.toLowerCase().replace(/[^a-z0-9_]/g, '_');
    return /^[0-9]/.test(name) ? `_${name}` : name || 'project';
}

function blockOrder(node: SlateNode): number {
    return node.kind === 'prelude' ? 0 : node.kind === 'epilogue' ? 2 : 1;
}

/** Merge `from M import x` lines per module (first-seen order); keep other lines once. */
function mergeImports(lines: string[]): string[] {
    const merged: Array<{ module: string | null; line: string; names: string[] }> = [];
    for (const line of lines) {
        const match = line.match(/^from (\S+) import (.+)$/);
        if (!match || match[2] === '*') {
            if (!merged.some(entry => entry.line === line)) merged.push({ module: null, line, names: [] });
            continue;
        }
        const entry = merged.find(item => item.module === match[1]);
        if (!entry) merged.push({ module: match[1], line, names: [match[2]] });
        else if (!entry.names.includes(match[2])) entry.names.push(match[2]);
    }
    return merged.map(entry => entry.module ? `from ${entry.module} import ${entry.names.join(', ')}` : entry.line);
}

function comment(label: string, text: string): string[] {
    return text.trim() ? text.trim().split('\n').map((line, index) => `# ${index === 0 ? `${label}: ` : '  '}${line}`) : [];
}

export function compilePython(nodes: ReadonlyMap<string, SlateNode>, config: SlateConfig): CompileResult {
    const diagnostics: CompileDiagnostic[] = [];
    const error = (message: string) => diagnostics.push({ severity: 'error', message });
    const valid = new Map<string, SlateNode>();
    for (const [nodeId, node] of nodes) {
        const language = node.language ?? config.language;
        if (language !== 'python') error(`${nodeId}: no compiler for language "${language}".`);
        else if (!parseModule(`${node.code.join('\n')}\n`, nodeId).valid) error(`${nodeId}: code is not valid Python.`);
        else valid.set(nodeId, node);
    }

    const folders = [...new Set([...valid.keys()].map(folderOf))].sort();
    const rootModule = projectModuleName(config.name);
    if (folders.includes('') && folders.includes(rootModule)) error(`Folder ${rootModule}/ collides with the module for root-level nodes (${rootModule}.py).`);
    const hasChildren = (folder: string) => folders.some(other => other !== folder && other.startsWith(`${folder}/`));
    const moduleName = (folder: string) => folder ? folder.replace(/\//g, '.') : rootModule;
    const modulePath = (folder: string) => !folder ? `${rootModule}.py`
        : hasChildren(folder) ? `${folder}/__init__.py` : `${folder}.py`;

    const preludeNames = new Map<string, Set<string>>();
    const definitions = new Map<string, string[]>();
    for (const [nodeId, node] of valid) {
        if (node.kind === 'prelude') preludeNames.set(nodeId, topLevelBindings(node.code.join('\n')));
        else if (!node.kind) definitions.set(node.name, [...(definitions.get(node.name) ?? []), nodeId]);
    }

    const files = new Map<string, string>();
    const moduleEdges = new Map<string, Set<string>>();
    for (const folder of folders) {
        const members = [...valid].filter(([nodeId]) => folderOf(nodeId) === folder).sort(([leftId, left], [rightId, right]) =>
            blockOrder(left) - blockOrder(right)
            || (left.order ?? Number.MAX_SAFE_INTEGER) - (right.order ?? Number.MAX_SAFE_INTEGER)
            || leftId.localeCompare(rightId));
        const localNames = new Set<string>();
        for (const [nodeId, node] of members) {
            if (node.kind === 'prelude') preludeNames.get(nodeId)!.forEach(name => localNames.add(name));
            else if (!node.kind) localNames.add(node.name);
        }

        const external: string[] = [];
        const crossModule: string[] = [];
        const origins = new Map<string, string>();
        const bind = (name: string, origin: string, nodeId: string) => {
            const previous = origins.get(name);
            if (previous && previous !== origin) error(`${modulePath(folder)}: name collision on "${name}" (${previous} vs ${origin}, in ${nodeId}).`);
            else origins.set(name, origin);
        };
        for (const [nodeId, node] of members) if (!node.kind) bind(node.name, `node ${nodeId}`, nodeId);

        for (const [nodeId, node] of members) {
            const names = identifierNames(node.code.join('\n'));
            const own = new Set<string>();
            for (const line of node.imports) {
                const parsed = splitImport(line);
                if (!parsed.length) error(`${nodeId}: "${line}" is not an import.`);
                for (const item of parsed) {
                    external.push(item.line);
                    if (!item.binding) continue;
                    own.add(item.binding);
                    // `import a.b` and `import a.c` both bind `a` compatibly.
                    bind(item.binding, item.name === null && !item.line.includes(' as ') ? `"import ${item.binding}…"` : `"${item.line}"`, nodeId);
                }
            }
            const importFrom = (target: string, name: string) => {
                const line = `from ${moduleName(folderOf(target))} import ${name}`;
                crossModule.push(line);
                own.add(name);
                bind(name, `"${line}"`, nodeId);
                moduleEdges.set(folder, (moduleEdges.get(folder) ?? new Set()).add(folderOf(target)));
            };
            for (const target of node.uses) {
                const used = valid.get(target);
                if (!used) {
                    error(`${nodeId} uses ${target}, which ${nodes.has(target) ? 'did not compile' : 'does not exist'}.`);
                    continue;
                }
                if (folderOf(target) === folder) continue;
                if (used.kind === 'prelude') [...preludeNames.get(target)!].filter(name => names.has(name)).forEach(name => importFrom(target, name));
                else if (!used.kind && names.has(used.name)) importFrom(target, used.name);
            }
            // Bare names not resolved by the folder, imports, or `uses`: a unique node elsewhere.
            for (const name of names) {
                if (name === node.name || own.has(name) || localNames.has(name)) continue;
                const candidates = (definitions.get(name) ?? []).filter(candidate => folderOf(candidate) !== folder);
                if (candidates.length === 1) importFrom(candidates[0], name);
                else if (candidates.length > 1) error(`${nodeId}: "${name}" matches ${candidates.join(', ')}; add the intended one to "uses".`);
            }
        }

        const future = external.filter(line => line.startsWith('from __future__ '));
        const sections = [
            [`${GENERATED_HEADER} from slate/nodes/${folder}${folder ? '/' : ''}; edit the node files, not this file.`],
            mergeImports(future),
            [...mergeImports(external.filter(line => !future.includes(line))), ...mergeImports(crossModule)],
        ].filter(section => section.length).map(section => section.join('\n'));
        const blocks = members.map(([nodeId, node]) => [
            `# slate: nodes/${nodeId}`,
            ...comment('intent', node.intent),
            ...comment('contract', node.contract),
            ...node.code,
        ].join('\n'));
        files.set(modulePath(folder), `${[sections.join('\n\n'), ...blocks].join('\n\n\n')}\n`);
    }

    for (const folder of folders) {
        const parts = folder.split('/');
        for (let depth = 1; depth < parts.length; depth++) {
            const packagePath = `${parts.slice(0, depth).join('/')}/__init__.py`;
            if (!files.has(packagePath)) files.set(packagePath, `${GENERATED_HEADER}; package marker.\n`);
        }
    }

    const visiting: string[] = [];
    const done = new Set<string>();
    const reported = new Set<string>();
    const visit = (folder: string) => {
        if (done.has(folder)) return;
        const at = visiting.indexOf(folder);
        if (at >= 0) {
            const cycle = [...visiting.slice(at), folder].map(modulePath).join(' → ');
            if (!reported.has(cycle)) diagnostics.push({ severity: 'warning', message: `Import cycle: ${cycle}.` });
            reported.add(cycle);
            return;
        }
        visiting.push(folder);
        for (const next of [...(moduleEdges.get(folder) ?? [])].sort()) visit(next);
        visiting.pop();
        done.add(folder);
    };
    folders.forEach(visit);

    return { files: new Map([...files].sort(([left], [right]) => left.localeCompare(right))), diagnostics };
}
