export interface ProseCitationEntry {
    key: string;
    author: string;
    year: string;
    title: string;
    venue?: string;
    url?: string;
    doi?: string;
}

export interface ProseCompileResult {
    /** Compiled files (`<name>.md` and `<name>.tex`) keyed by relative path. */
    files: Map<string, string>;
    /** Structured diagnostics compatible with CompileResult. */
    diagnostics: CompileDiagnostic[];
    /** Detailed prose diagnostics (budgets, citations, rubric, wires). */
    proseDiagnostics: ProseDiagnostic[];
    /** Assembled raw text per compiled flow or document before format-specific rendering. */
    assembledFlows: Map<string, string>;
    /** Ordered citation keys referenced in the compiled output. */
    referencedCitations: string[];
}

export function proseDocumentSlug(name: string): string {
    const clean = name
        .trim()
        .toLowerCase()
        .replace(/[^a-z0-9_-]/g, '_')
        .replace(/^_+|_+$/g, '');
    return clean || 'document';
}

/**
 * Parse a `ProseCitationEntry` from a citation `SlateNode` or a raw JSON/text string.
 */
export function parseCitationNode(node: SlateNode, fallbackKey?: string): ProseCitationEntry | null {
    const extra = node.extra ?? {};
    const citationObj = (extra.citation && typeof extra.citation === 'object' && !Array.isArray(extra.citation))
        ? (extra.citation as Record<string, unknown>)
        : extra;

    const bodyText = (node.code ?? []).join('\n').trim();

    // Check if bodyText or a return value is JSON describing a citation
    const parsedNode = parseProseNode(node);
    const candidateJson = parsedNode.bodyText || bodyText;
    if (candidateJson.startsWith('{') && candidateJson.endsWith('}')) {
        try {
            const j = JSON.parse(candidateJson) as Record<string, unknown>;
            const key = normalizeCitationKey(String(j.key ?? citationObj.key ?? fallbackKey ?? node.name));
            return {
                key,
                author: String(j.author ?? citationObj.author ?? 'Unknown Author'),
                year: String(j.year ?? citationObj.year ?? 'n.d.'),
                title: String(j.title ?? citationObj.title ?? (node.intent || key)),
                venue: typeof (j.venue ?? citationObj.venue) === 'string' ? String(j.venue ?? citationObj.venue) : undefined,
                url: typeof (j.url ?? citationObj.url) === 'string' ? String(j.url ?? citationObj.url) : undefined,
                doi: typeof (j.doi ?? citationObj.doi) === 'string' ? String(j.doi ?? citationObj.doi) : undefined,
            };
        } catch {
            // Fall through
        }
    }

    const isCitationKind =
        parsedNode.kind === 'citation' ||
        parsedNode.signature.returns === 'citation' ||
        typeof citationObj.author === 'string' ||
        typeof citationObj.citationKey === 'string';

    if (!isCitationKind && !fallbackKey) return null;

    // Parse key: value lines from bodyText if present
    const kvMap = new Map<string, string>();
    for (const line of parsedNode.templateLines) {
        const m = line.match(/^\s*([A-Za-z_]+)\s*[:=]\s*(.+?)\s*$/);
        if (m) {
            kvMap.set(m[1].toLowerCase(), m[2].replace(/^["']|["']$/g, ''));
        }
    }

    const rawKey = String(
        citationObj.key ??
        citationObj.citationKey ??
        kvMap.get('key') ??
        fallbackKey ??
        node.name,
    );
    const key = normalizeCitationKey(rawKey);
    const author = String(citationObj.author ?? kvMap.get('author') ?? 'Unknown Author');
    const year = String(citationObj.year ?? kvMap.get('year') ?? '2024');
    const title = String(
        citationObj.title ??
        kvMap.get('title') ??
        (node.intent ? node.intent : parsedNode.bodyText || key),
    );
    const venue = (citationObj.venue ?? kvMap.get('venue') ?? kvMap.get('journal')) as string | undefined;
    const doi = (citationObj.doi ?? kvMap.get('doi')) as string | undefined;
    const url = (citationObj.url ?? kvMap.get('url')) as string | undefined;

    return {
        key,
        author,
        year,
        title,
        ...(venue ? { venue: String(venue) } : {}),
        ...(doi ? { doi: String(doi) } : {}),
        ...(url ? { url: String(url) } : {}),
    };
}

function coerceProseValue(val: unknown): string {
    if (val === undefined || val === null) return '';
    if (typeof val === 'string') {
        const trimmed = val.trim();
        if ((trimmed.startsWith('"') && trimmed.endsWith('"')) || (trimmed.startsWith("'") && trimmed.endsWith("'"))) {
            try {
                if (trimmed.startsWith('"')) return JSON.parse(trimmed);
            } catch {
                return trimmed.slice(1, -1);
            }
            return trimmed.slice(1, -1);
        }
        return val;
    }
    if (Array.isArray(val)) {
        return val.map(coerceProseValue).join('\n\n');
    }
    if (typeof val === 'object') {
        const rec = val as Record<string, unknown>;
        if (typeof rec.text === 'string') return rec.text;
        if (typeof rec.key === 'string') return `[@${normalizeCitationKey(rec.key)}]`;
        return JSON.stringify(val);
    }
    return String(val);
}

/**
 * Evaluate a single prose node given wired argument values (`Record<paramName, unknown>`).
 */
export function evaluateProseNode(
    node: SlateNode,
    args: Record<string, unknown>,
    citations: ReadonlyMap<string, ProseCitationEntry>,
): string {
    const parsed = parseProseNode(node);

    // If this is a citation node with no input params, emit `[@key]` token when wired into a passage/operator
    if (parsed.kind === 'citation' || parsed.signature.returns === 'citation') {
        const entry = parseCitationNode(node);
        if (entry && parsed.signature.params.length === 0) {
            // If bodyText explicitly contains `[@...]` or `\cite{...}`, preserve it; otherwise emit `[@key]`.
            if (extractCitations(parsed.bodyText).length > 0) {
                return parsed.bodyText;
            }
            return `[@${entry.key}]`;
        }
    }

    let template = parsed.bodyText;

    // Built-in section / passage combinator behavior when template is empty or uses standard placeholders
    if (!template) {
        if (parsed.signature.params.length > 0) {
            const parts: string[] = [];
            for (const p of parsed.signature.params) {
                const v = args[p.name] ?? (p.default ? coerceProseValue(p.default) : '');
                const str = coerceProseValue(v).trim();
                if (str) parts.push(str);
            }
            const joined = parts.join('\n\n');
            if (parsed.kind === 'section' || parsed.signature.returns === 'section') {
                const heading = typeof node.extra?.heading === 'string'
                    ? node.extra.heading
                    : typeof args.title === 'string' && args.title.trim()
                        ? args.title.trim()
                        : null;
                if (heading && !joined.startsWith('#')) {
                    const bodyParts = parsed.signature.params
                        .filter(p => p.name !== 'title')
                        .map(p => coerceProseValue(args[p.name] ?? p.default ?? '').trim())
                        .filter(Boolean);
                    return `## ${heading}\n\n${bodyParts.join('\n\n')}`.trim();
                }
            }
            return joined;
        }
        return node.intent ? node.intent.trim() : '';
    }

    // Substitute `{param}` and `{{param}}` placeholders in template
    template = template.replace(/\{\{\s*([A-Za-z_][A-Za-z0-9_]*)\s*\}\}|\{\s*([A-Za-z_][A-Za-z0-9_]*)\s*\}/g, (full, doubleKey, singleKey) => {
        const key = (doubleKey ?? singleKey) as string;
        if (key in args && args[key] !== undefined && args[key] !== null) {
            const paramDef = parsed.signature.params.find(p => p.name === key);
            const rawVal = coerceProseValue(args[key]);
            if (paramDef?.annotation === 'citation') {
                const normKey = normalizeCitationKey(rawVal);
                if (citations.has(normKey) && !rawVal.includes('@') && !rawVal.includes('\\cite')) {
                    return `[@${normKey}]`;
                }
            }
            return rawVal;
        }
        const paramDef = parsed.signature.params.find(p => p.name === key);
        if (paramDef && paramDef.default !== null) {
            return coerceProseValue(paramDef.default);
        }
        return full;
    });

    // If any wired arguments were NOT referenced as `{param}` placeholders in the template,
    // and the template has no placeholders at all, append or combine them deterministically.
    const hadPlaceholders = /\{\{?\s*([A-Za-z_][A-Za-z0-9_]*)\s*\}?\}/.test(parsed.bodyText);
    if (!hadPlaceholders && parsed.signature.params.length > 0) {
        const argParts = parsed.signature.params
            .map(p => {
                const val = args[p.name] ?? p.default;
                if (val === undefined || val === null) return '';
                const str = coerceProseValue(val).trim();
                if (p.annotation === 'citation' && str && !str.includes('@') && !str.includes('\\cite')) {
                    return `[@${normalizeCitationKey(str)}]`;
                }
                return str;
            })
            .filter(Boolean);
        if (argParts.length > 0) {
            template = `${template}\n\n${argParts.join('\n\n')}`.trim();
        }
    }

    return template.trim();
}

function isTruthyCondition(val: unknown): boolean {
    if (typeof val === 'boolean') return val;
    if (typeof val === 'number') return val !== 0;
    if (typeof val === 'string') {
        const lower = val.trim().toLowerCase();
        if (!lower || lower === 'false' || lower === '0' || lower === 'null' || lower === 'none' || lower === 'no') {
            return false;
        }
        return true;
    }
    return Boolean(val);
}

function parseCollectionItems(val: unknown): unknown[] {
    if (Array.isArray(val)) return val;
    if (typeof val === 'string') {
        const trimmed = val.trim();
        if (trimmed.startsWith('[') && trimmed.endsWith(']')) {
            try {
                const parsed = JSON.parse(trimmed);
                if (Array.isArray(parsed)) return parsed;
            } catch {
                // Fall through
            }
        }
        return trimmed
            .split(/\r?\n\r?\n|\r?\n|;/)
            .map(s => s.trim())
            .filter(Boolean);
    }
    if (val === undefined || val === null) return [];
    return [val];
}

/**
 * Deterministically evaluate a `SlateFlow` in prose mode.
 */
export function evaluateProseFlow(
    flowId: string,
    flow: SlateFlow,
    nodes: ReadonlyMap<string, SlateNode>,
    flows: ReadonlyMap<string, SlateFlow>,
    citations: Map<string, ProseCitationEntry>,
    flowInputs: Record<string, unknown>,
    proseDiagnostics: ProseDiagnostic[],
    callStack: Set<string> = new Set(),
): { outputs: Record<string, unknown>; assembledText: string } {
    if (callStack.has(flowId)) {
        proseDiagnostics.push({
            code: 'prose-flow-cycle',
            severity: 'error',
            message: `Recursive prose flow cycle detected involving "${flowId}".`,
            flowId,
        });
        return { outputs: {}, assembledText: '' };
    }
    const nextStack = new Set(callStack);
    nextStack.add(flowId);

    const regions = flow.regions ?? [];
    const allStepIds = [
        ...flow.instances.map(i => i.id),
        ...regions.map(r => r.id),
    ];
    const instanceMap = new Map(flow.instances.map(i => [i.id, i]));
    const regionMap = new Map(regions.map(r => [r.id, r]));
    const boundaries = new Map<string, RegionPorts>();
    const targets = new Map<string, { node?: SlateNode; flow?: SlateFlow; id: string }>();
    const error = (message: string) => proseDiagnostics.push({
        code: 'prose-wire-error', severity: 'error', message: `flows/${flowId}: ${message}.`, flowId,
    });
    for (const input of flow.inputs) {
        if (!Object.prototype.hasOwnProperty.call(flowInputs, input.name) || flowInputs[input.name] === undefined) {
            error(`required input ${input.name} has no value`);
        }
    }
    const singleOutput = [{ id: 'out', name: 'out', annotation: null }];
    for (const step of flow.instances) {
        if (step.kind === 'value' || step.kind === 'viewer') {
            boundaries.set(step.id, {
                inputs: step.kind === 'viewer' ? [{ id: 'in:in', name: 'in', annotation: null }] : [],
                outputs: step.kind === 'viewer' ? [] : singleOutput,
            });
            continue;
        }
        const id = step.node ?? '';
        const node = nodes.get(id);
        const childId = id.startsWith('flow:') ? id.slice('flow:'.length) : id;
        const child = node ? undefined : flows.get(childId);
        targets.set(step.id, { node, flow: child, id: node ? id : childId });
        if (node) {
            const parsed = parseProseNode(node, id);
            boundaries.set(step.id, parsed);
        } else if (child) {
            boundaries.set(step.id, {
                inputs: child.inputs.map(port => ({ ...port, id: 'in:' + port.name })),
                outputs: child.outputs.map(port => ({ ...port, id: child.outputs.length === 1 ? 'out' : 'out:' + port.name })),
            });
        } else {
            error(`instance ${step.id} calls ${id}, which does not exist`);
        }
    }
    for (const region of regions) {
        try {
            const ports = regionPorts(region, id => flows.get(id));
            if (region.kind === 'branch' && region.elseFlow &&
                !branchOutputsMatch(flows.get(region.thenFlow)!, flows.get(region.elseFlow)!)) {
                error(`region ${region.id} branches must expose compatible outputs by name`);
            }
            if (region.kind === 'repeat') {
                const body = flows.get(region.bodyFlow)!;
                if (region.statePorts?.some(name => !body.inputs.some(port => port.name === name) ||
                    !body.outputs.some(port => port.name === name))) {
                    error(`region ${region.id} state ports must be both inputs and outputs`);
                }
                if (region.conditionPort && !body.outputs.some(port => port.name === region.conditionPort)) {
                    error(`region ${region.id} condition port must be a body output`);
                }
            }
            boundaries.set(region.id, ports);
        } catch (problem) {
            error(`region ${region.id}: ${(problem as Error).message}`);
        }
    }
    const findOutput = (ports: Port[], id: string) => ports.find(port => port.id === id ||
        (ports.length === 1 && id === 'out:' + port.name));

    // Build incoming wire map (`toEndpoint -> fromEndpoint`) and validate endpoints
    const incoming = new Map<string, string>();
    for (const wire of flow.wires) {
        const from = parseEndpoint(wire.from);
        const to = parseEndpoint(wire.to);

        const fromValid = from.instance === null
            ? from.port.startsWith('input:') && flow.inputs.some(inp => `input:${inp.name}` === from.port)
            : findOutput(boundaries.get(from.instance)?.outputs ?? [], from.port);
        const toValid = to.instance === null
            ? to.port.startsWith('output:') && flow.outputs.some(out => `output:${out.name}` === to.port)
            : boundaries.get(to.instance)?.inputs.find(port => port.id === to.port ||
                (instanceMap.get(to.instance!)?.kind === 'viewer' && to.port === 'in'));

        if (!fromValid || !toValid) {
            proseDiagnostics.push({
                code: 'prose-wire-error',
                severity: 'error',
                message: `flows/${flowId}: wire ${wire.from} -> ${wire.to} has an unknown endpoint.`,
                flowId,
            });
            continue;
        }
        const sink = typeof toValid === 'object' ? to.instance + '.' + toValid.id : wire.to;
        if (incoming.has(sink)) {
            proseDiagnostics.push({
                code: 'prose-wire-error',
                severity: 'error',
                message: `flows/${flowId}: ${wire.to} has more than one incoming wire.`,
                flowId,
            });
            continue;
        }
        incoming.set(sink, wire.from);
    }

    // Topological sort via Kahn's algorithm
    const order: string[] = [];
    const pending = new Set(allStepIds);
    while (pending.size > 0) {
        const ready = [...pending].find(id =>
            [...incoming].every(([to, from]) => {
                const toEp = parseEndpoint(to);
                const fromEp = parseEndpoint(from);
                return toEp.instance !== id || fromEp.instance === null || !pending.has(fromEp.instance);
            }),
        );
        if (!ready) {
            proseDiagnostics.push({
                code: 'prose-flow-cycle',
                severity: 'error',
                message: `flows/${flowId}: instances ${[...pending].join(', ')} form a cycle.`,
                flowId,
            });
            break;
        }
        order.push(ready);
        pending.delete(ready);
    }

    const stepOutputs = new Map<string, Record<string, unknown>>();
    const terminalText = new Map<string, string>();
    const resolveEndpointValue = (endpoint: string): unknown => {
        const { instance, port } = parseEndpoint(endpoint);
        if (instance === null) {
            const inputName = port.slice('input:'.length);
            return flowInputs[inputName];
        }
        const outRec = stepOutputs.get(instance);
        if (!outRec) return undefined;
        const output = findOutput(boundaries.get(instance)?.outputs ?? [], port);
        return output && Object.prototype.hasOwnProperty.call(outRec, output.name) ? outRec[output.name] : undefined;
    };
    const required = (step: string, port: string) => {
        const source = incoming.get(step + '.in:' + port);
        const value = source ? resolveEndpointValue(source) : undefined;
        if (value === undefined) error(step + '.in:' + port + ' has no value');
        return value;
    };

    for (const stepId of order) {
        const instance = instanceMap.get(stepId);
        if (instance) {
            if (instance.kind === 'value') {
                const val = coerceProseValue(instance.value);
                stepOutputs.set(stepId, { out: val });
                terminalText.set(stepId, val);
                continue;
            }
            if (instance.kind === 'viewer') {
                const src = incoming.get(`${stepId}.in`) ?? incoming.get(`${stepId}.in:in`);
                const val = src ? resolveEndpointValue(src) : '';
                stepOutputs.set(stepId, { out: val });
                continue;
            }
            const { id: target, node: targetNode, flow: targetFlow } = targets.get(stepId)!;
            if (!targetNode && !targetFlow) continue;

            if (targetFlow) {
                const childArgs: Record<string, unknown> = {};
                for (const inp of targetFlow.inputs) {
                    const src = incoming.get(`${stepId}.in:${inp.name}`);
                    if (src) {
                        childArgs[inp.name] = resolveEndpointValue(src);
                    } else {
                        proseDiagnostics.push({
                            code: 'prose-wire-error',
                            severity: 'error',
                            message: `flows/${flowId}: ${stepId}.in:${inp.name} is not wired.`,
                            flowId,
                        });
                    }
                }
                const childRes = evaluateProseFlow(
                    target,
                    targetFlow,
                    nodes,
                    flows,
                    citations,
                    childArgs,
                    proseDiagnostics,
                    nextStack,
                );
                stepOutputs.set(stepId, childRes.outputs);
                terminalText.set(stepId, childRes.assembledText);
                continue;
            }

            // Evaluate atomic prose node
            const parsedNode = parseProseNode(targetNode!, target);
            const args: Record<string, unknown> = {};
            for (const param of parsedNode.signature.params) {
                const src = incoming.get(`${stepId}.in:${param.name}`);
                if (!src) {
                    if (param.default === null) {
                        proseDiagnostics.push({
                            code: 'prose-wire-error',
                            severity: 'error',
                            message: `flows/${flowId}: ${stepId}.in:${param.name} is not wired and has no default.`,
                            flowId,
                            nodeId: target,
                        });
                    } else {
                        args[param.name] = coerceProseValue(param.default);
                    }
                } else {
                    args[param.name] = required(stepId, param.name);
                }
            }

            const rendered = evaluateProseNode(targetNode!, args, citations);
            for (const key of extractCitations(rendered).filter(key => !citations.has(key))) {
                proseDiagnostics.push({ code: 'prose-missing-citation', severity: 'warning', flowId, nodeId: target,
                    message: `flows/${flowId}: citation "[@${key}]" has no matching bibliography entry.` });
            }
            // Verify node output against node's own contract
            const nodeVerification = verifyProseNode(targetNode!, {
                nodeId: target,
                candidateText: rendered,
            });
            for (const d of nodeVerification.diagnostics) {
                proseDiagnostics.push(d);
            }

            stepOutputs.set(stepId, { out: rendered });
            terminalText.set(stepId, rendered);
            continue;
        }

        const region = regionMap.get(stepId);
        if (region && boundaries.has(stepId)) {
            if (region.kind === 'branch') {
                const branchReg = region as FlowBranchRegion;
                const condPort = branchReg.conditionPort ?? 'condition';
                const condVal = required(stepId, condPort);
                if (condVal === undefined) continue;
                const chosenFlowId = isTruthyCondition(condVal) ? branchReg.thenFlow : branchReg.elseFlow;
                if (!chosenFlowId) {
                    stepOutputs.set(stepId, Object.fromEntries(boundaries.get(stepId)!.outputs.map(port => [port.name, ''])));
                    continue;
                }
                const chosenFlow = flows.get(chosenFlowId);
                if (!chosenFlow) {
                    proseDiagnostics.push({
                        code: 'prose-wire-error',
                        severity: 'error',
                        message: `flows/${flowId}: branch region ${stepId} references missing flow "${chosenFlowId}".`,
                        flowId,
                    });
                    stepOutputs.set(stepId, { out: '' });
                    continue;
                }
                const branchArgs: Record<string, unknown> = {};
                for (const inp of chosenFlow.inputs) {
                    const src = incoming.get(`${stepId}.in:${inp.name}`);
                    if (src) branchArgs[inp.name] = resolveEndpointValue(src);
                }
                const branchRes = evaluateProseFlow(
                    chosenFlowId,
                    chosenFlow,
                    nodes,
                    flows,
                    citations,
                    branchArgs,
                    proseDiagnostics,
                    nextStack,
                );
                stepOutputs.set(stepId, branchRes.outputs);
                terminalText.set(stepId, branchRes.assembledText);
                continue;
            }

            if (region.kind === 'foreach') {
                const foreachReg = region as FlowForeachRegion;
                const bodyFlow = flows.get(foreachReg.bodyFlow);
                if (!bodyFlow) {
                    proseDiagnostics.push({
                        code: 'prose-wire-error',
                        severity: 'error',
                        message: `flows/${flowId}: foreach region ${stepId} references missing bodyFlow "${foreachReg.bodyFlow}".`,
                        flowId,
                    });
                    stepOutputs.set(stepId, { out: '' });
                    continue;
                }
                const collPort = foreachReg.collectionPort ?? 'items';
                const itemPort = foreachReg.itemPort ?? 'item';
                const indexPort = foreachReg.indexPort ?? 'index';
                const collection = required(stepId, collPort);
                if (collection === undefined) continue;
                const items = parseCollectionItems(collection);
                const broadcasts = Object.fromEntries(bodyFlow.inputs.filter(input => ![itemPort, indexPort].includes(input.name))
                    .map(input => [input.name, required(stepId, input.name)]));
                const limit = foreachReg.maxIterations ? Math.min(items.length, foreachReg.maxIterations) : items.length;

                const collectedByOutput = new Map<string, string[]>();
                for (const outPort of bodyFlow.outputs) {
                    collectedByOutput.set(outPort.name, []);
                }
                const assembledItems: string[] = [];

                for (let idx = 0; idx < limit; idx++) {
                    const iterArgs = { ...broadcasts, [itemPort]: items[idx], [indexPort]: idx };
                    const iterRes = evaluateProseFlow(
                        foreachReg.bodyFlow,
                        bodyFlow,
                        nodes,
                        flows,
                        citations,
                        iterArgs,
                        proseDiagnostics,
                        nextStack,
                    );
                    assembledItems.push(iterRes.assembledText);
                    for (const outPort of bodyFlow.outputs) {
                        const v = coerceProseValue(iterRes.outputs[outPort.name]);
                        collectedByOutput.get(outPort.name)!.push(v);
                    }
                }

                stepOutputs.set(stepId, Object.fromEntries([...collectedByOutput]
                    .map(([name, values]) => [name, values.filter(Boolean).join('\n\n')])));
                terminalText.set(stepId, assembledItems.filter(Boolean).join('\n\n'));
                continue;
            }

            if (region.kind === 'repeat') {
                const repeatReg = region as FlowRepeatRegion;
                const bodyFlow = flows.get(repeatReg.bodyFlow);
                if (!bodyFlow) {
                    proseDiagnostics.push({
                        code: 'prose-wire-error',
                        severity: 'error',
                        message: `flows/${flowId}: repeat region ${stepId} references missing bodyFlow "${repeatReg.bodyFlow}".`,
                        flowId,
                    });
                    stepOutputs.set(stepId, { out: '' });
                    continue;
                }
                const statePorts = boundaries.get(stepId)!.outputs;
                const state = Object.fromEntries(bodyFlow.inputs.map(input => [input.name, required(stepId, input.name)]));
                for (let iter = 0; iter < repeatReg.maxIterations; iter++) {
                    const iterRes = evaluateProseFlow(
                        repeatReg.bodyFlow,
                        bodyFlow,
                        nodes,
                        flows,
                        citations,
                        { ...state },
                        proseDiagnostics,
                        nextStack,
                    );
                    for (const port of statePorts) state[port.name] = iterRes.outputs[port.name];
                    if (repeatReg.conditionPort && repeatReg.conditionPort in iterRes.outputs) {
                        if (!isTruthyCondition(iterRes.outputs[repeatReg.conditionPort])) break;
                    }
                }
                stepOutputs.set(stepId, Object.fromEntries(statePorts.map(port => [port.name, state[port.name]])));
                terminalText.set(stepId, statePorts.map(port => coerceProseValue(state[port.name])).filter(Boolean).join('\n\n'));
            }
        }
    }

    const outputs: Record<string, unknown> = {};
    const outputTexts: string[] = [];

    const collectTerminalOutputs = () => {
        const consumedSteps = new Set<string>();
        for (const wire of flow.wires) {
            const fromEp = parseEndpoint(wire.from);
            const toEp = parseEndpoint(wire.to);
            if (fromEp.instance) {
                const toInst = instanceMap.get(toEp.instance ?? '');
                if (toInst?.kind !== 'viewer') {
                    consumedSteps.add(fromEp.instance);
                }
            }
        }
        for (const stepId of order) {
            const inst = instanceMap.get(stepId);
            if (inst?.kind === 'viewer') continue;
            if (inst?.node) {
                const tNode = nodes.get(inst.node);
                if (tNode) {
                    const pNode = parseProseNode(tNode, inst.node);
                    if (pNode.kind === 'citation' || pNode.signature.returns === 'citation') continue;
                }
            }
            if (!consumedSteps.has(stepId)) {
                const textVal = terminalText.get(stepId)?.trim();
                if (textVal) outputTexts.push(textVal);
            }
        }
    };

    if (flow.outputs.length > 0) {
        for (const outPort of flow.outputs) {
            const src = incoming.get(`output:${outPort.name}`);
            if (!src) {
                proseDiagnostics.push({
                    code: 'prose-wire-error',
                    severity: 'error',
                    message: `flows/${flowId}: output ${outPort.name} is not wired.`,
                    flowId,
                });
                outputs[outPort.name] = '';
            } else {
                const val = resolveEndpointValue(src);
                if (val === undefined) error('output ' + outPort.name + ' has no value');
                const textVal = coerceProseValue(val).trim();
                outputs[outPort.name] = textVal;
                if (textVal) outputTexts.push(textVal);
            }
        }
    } else {
        // For a root flow (e.g. `main`) with no explicit output ports, collect terminal sink steps in topological order
        collectTerminalOutputs();
    }

    const assembledText = outputTexts.join('\n\n').trim();

    // Verify flow-level prose contract if present
    const flowContract = parseProseContract(
        typeof flow.extra?.contract === 'string' ? flow.extra.contract : '',
        flow.extra,
    );
    const hasFlowContract =
        flowContract.minWords !== undefined ||
        flowContract.maxWords !== undefined ||
        flowContract.minChars !== undefined ||
        flowContract.maxChars !== undefined ||
        (flowContract.requiredCitations && flowContract.requiredCitations.length > 0) ||
        (flowContract.forbiddenTerms && flowContract.forbiddenTerms.length > 0) ||
        (flowContract.requiredSections && flowContract.requiredSections.length > 0) ||
        (flowContract.rubricCriteria && flowContract.rubricCriteria.length > 0);

    if (hasFlowContract) {
        const flowVerification = verifyProseText(assembledText, flowContract, { flowId });
        for (const d of flowVerification.diagnostics) {
            proseDiagnostics.push(d);
        }
    }

    return { outputs, assembledText };
}

/**
 * Format inline citations (`[@key]` or `\cite{key}`) into Markdown inline citations `(Author, Year)`
 * and append a formatted `## References` section.
 */
export function renderProseMarkdown(
    title: string,
    rawBody: string,
    citations: ReadonlyMap<string, ProseCitationEntry>,
    referencedKeys: string[],
): string {
    // Convert any \cite{key1, key2} or [@key1; @key2] into Markdown inline citation format `(Author, Year)`
    const formatKeyInline = (key: string): string => {
        const entry = citations.get(key);
        if (!entry) return `[@${key}]`;
        return `${entry.author}, ${entry.year}`;
    };

    let mdBody = rawBody.replace(/\[([^\[\]]*@[A-Za-z0-9_:-]+[^\[\]]*)\]/g, (full, inner: string) => {
        const keys = [...inner.matchAll(/@([A-Za-z0-9_:-]+)/g)].map(m => m[1]);
        if (keys.length === 0) return full;
        return `(${keys.map(formatKeyInline).join('; ')})`;
    });

    mdBody = mdBody.replace(/\\cite[a-zA-Z]*\{([^}]+)\}/g, (_full, inner: string) => {
        const keys = inner.split(',').map(k => k.trim()).filter(Boolean);
        return `(${keys.map(formatKeyInline).join('; ')})`;
    });

    const lines: string[] = [
        PROSE_GENERATED_MD_HEADER,
        '',
    ];

    if (!mdBody.trimStart().startsWith('# ')) {
        lines.push(`# ${title}`, '');
    }
    if (mdBody.trim()) {
        lines.push(mdBody.trim(), '');
    }

    if (referencedKeys.length > 0) {
        lines.push('## References', '');
        for (const key of referencedKeys) {
            const entry = citations.get(key);
            if (entry) {
                const venuePart = entry.venue ? ` *${entry.venue}*.` : '';
                const doiPart = entry.doi ? ` DOI: ${entry.doi}.` : '';
                const urlPart = entry.url ? ` ${entry.url}` : '';
                lines.push(`- **[${entry.key}]** ${entry.author} (${entry.year}). "${entry.title}."${venuePart}${doiPart}${urlPart}`);
            } else {
                lines.push(`- **[${key}]** Unresolved citation key \`${key}\`.`);
            }
        }
        lines.push('');
    }

    return `${lines.join('\n').trimEnd()}\n`;
}

const LATEX_ESCAPES: Record<string, string> = {
    '\\': '\\textbackslash{}', '{': '\\{', '}': '\\}', '$': '\\$', '&': '\\&',
    '#': '\\#', '%': '\\%', '_': '\\_', '^': '\\textasciicircum{}', '~': '\\textasciitilde{}',
};

function escapeLatex(text: string): string {
    return text.replace(/[\\{}$&#%_^~]/g, char => LATEX_ESCAPES[char]);
}

function markdownBodyToLatex(text: string): string {
    const inline = (value: string) => {
        const tokens = /\[[^\[\]]*@[A-Za-z0-9_:-]+[^\[\]]*\]|\\cite\{[A-Za-z0-9_:-]+(?:\s*,\s*[A-Za-z0-9_:-]+)*\}|\*\*[^*]+\*\*|\*[^*]+\*/g;
        let result = '';
        let start = 0;
        for (const match of value.matchAll(tokens)) {
            const token = match[0];
            result += escapeLatex(value.slice(start, match.index));
            if (token.startsWith('\\cite{')) result += token;
            else if (token.startsWith('[')) {
                const keys = [...token.matchAll(/@([A-Za-z0-9_:-]+)/g)].map(key => key[1]);
                result += '\\cite{' + keys.join(',') + '}';
            } else if (token.startsWith('**')) result += '\\textbf{' + inline(token.slice(2, -2)) + '}';
            else result += '\\textit{' + inline(token.slice(1, -1)) + '}';
            start = match.index + token.length;
        }
        return result + escapeLatex(value.slice(start));
    };

    const outLines: string[] = [];
    for (const line of text.split(/\r?\n/)) {
        const h1 = line.match(/^\s*#\s+(.+?)\s*$/);
        if (h1) {
            outLines.push(`\\section{${inline(h1[1].trim())}}`);
            continue;
        }
        const h2 = line.match(/^\s*##\s+(.+?)\s*$/);
        if (h2) {
            outLines.push(`\\section{${inline(h2[1].trim())}}`);
            continue;
        }
        const h3 = line.match(/^\s*###\s+(.+?)\s*$/);
        if (h3) {
            outLines.push(`\\subsection{${inline(h3[1].trim())}}`);
            continue;
        }
        const h4 = line.match(/^\s*#{4,6}\s+(.+?)\s*$/);
        if (h4) {
            outLines.push(`\\subsubsection{${inline(h4[1].trim())}}`);
            continue;
        }
        outLines.push(inline(line));
    }
    return outLines.join('\n').trim();
}

/**
 * Render compiled prose body and bibliography into a complete LaTeX document (`<name>.tex`).
 */
export function renderProseLatex(
    title: string,
    rawBody: string,
    citations: ReadonlyMap<string, ProseCitationEntry>,
    referencedKeys: string[],
): string {
    const texBody = markdownBodyToLatex(rawBody);
    const lines: string[] = [
        PROSE_GENERATED_TEX_HEADER,
        '\\documentclass[11pt]{article}',
        '\\usepackage[utf8]{inputenc}',
        '\\usepackage{hyperref}',
        `\\title{${escapeLatex(title)}}`,
        '\\date{}',
        '\\begin{document}',
        '\\maketitle',
        '',
    ];

    if (texBody) {
        lines.push(texBody, '');
    }

    if (referencedKeys.length > 0) {
        lines.push(`\\begin{thebibliography}{${Math.max(9, referencedKeys.length)}}`);
        for (const key of referencedKeys) {
            const entry = citations.get(key);
            if (entry) {
                const venuePart = entry.venue ? ` \\textit{${escapeLatex(entry.venue)}}.` : '';
                const doiPart = entry.doi ? ` DOI: ${escapeLatex(entry.doi)}.` : '';
                lines.push(`\\bibitem{${entry.key}} ${escapeLatex(entry.author)} (${escapeLatex(entry.year)}). ${escapeLatex(entry.title)}.${venuePart}${doiPart}`);
            } else {
                lines.push(`\\bibitem{${key}} Unresolved citation ${key}.`);
            }
        }
        lines.push('\\end{thebibliography}', '');
    }

    lines.push('\\end{document}', '');
    return lines.join('\n');
}

/**
 * Deterministically compile a Prose project (`language: "prose"`) into Markdown (`.md`)
 * and LaTeX (`.tex`) artifacts, resolving inline citations (`[@key]` and `\cite{key}`),
 * generating the Bibliography / References section, and verifying all node and flow
 * prose contracts (word/character budgets, required citations, forbidden terms, rubrics).
 */
export function compileProse(
    sourceNodes: ReadonlyMap<string, SlateNode>,
    config: SlateConfig,
    flows: ReadonlyMap<string, SlateFlow> = new Map(),
    explicitCitations?: ReadonlyMap<string, ProseCitationEntry> | ProseCitationEntry[],
    options?: { contractOverride?: Partial<ProseContractSpec> },
): ProseCompileResult {
    const proseDiagnostics: ProseDiagnostic[] = [];
    const citations = new Map<string, ProseCitationEntry>();

    if (explicitCitations) {
        if (Array.isArray(explicitCitations)) {
            for (const c of explicitCitations) {
                citations.set(normalizeCitationKey(c.key), { ...c, key: normalizeCitationKey(c.key) });
            }
        } else {
            for (const [k, c] of explicitCitations.entries()) {
                const norm = normalizeCitationKey(k);
                citations.set(norm, { ...c, key: norm });
            }
        }
    }

    // Index all prose nodes and extract any citation nodes into the citation registry
    const proseNodes = new Map<string, SlateNode>();
    for (const [nodeId, node] of [...sourceNodes.entries()].sort(([a], [b]) => a.localeCompare(b))) {
        const lang = node.language ?? config.language;
        if (lang !== 'prose') {
            proseDiagnostics.push({
                code: 'prose-syntax',
                severity: 'error',
                message: `${nodeId}: expected language "prose", got "${lang}".`,
                nodeId,
            });
            continue;
        }
        proseNodes.set(nodeId, node);
        const parsed = parseProseNode(node, nodeId);
        for (const d of parsed.diagnostics) {
            proseDiagnostics.push(d);
        }
        const citEntry = parseCitationNode(node);
        if (citEntry && (parsed.kind === 'citation' || parsed.signature.returns === 'citation')) {
            citations.set(citEntry.key, citEntry);
        }
    }

    const files = new Map<string, string>();
    const assembledFlows = new Map<string, string>();
    const allReferencedCitations = new Set<string>();

    // Inspect every component before selecting roots, including cycles with no root.
    const calls = new Map([...flows].map(([id, flow]) => [id, [
        ...flow.instances.flatMap(instance => {
            if (!instance.node || proseNodes.has(instance.node)) return [];
            return [instance.node.replace(/^flow:/, '')];
        }),
        ...(flow.regions ?? []).flatMap(region => region.kind === 'branch'
            ? [region.thenFlow, ...(region.elseFlow ? [region.elseFlow] : [])] : [region.bodyFlow]),
    ].filter(target => flows.has(target))]));
    const calledSubflows = new Set([...calls.values()].flat());
    const active = new Set<string>();
    const visited = new Set<string>();
    const visit = (id: string) => {
        if (active.has(id)) {
            proseDiagnostics.push({
                code: 'prose-flow-cycle', severity: 'error', flowId: id,
                message: `Recursive prose flow cycle: ${[...active, id].join(' → ')}.`,
            });
            return;
        }
        if (visited.has(id)) return;
        active.add(id);
        for (const target of calls.get(id) ?? []) visit(target);
        active.delete(id);
        visited.add(id);
    };
    for (const id of flows.keys()) visit(id);

    const sortedFlows = [...flows.entries()].sort(([a], [b]) => a.localeCompare(b));
    const executableTopFlows = sortedFlows.filter(([flowId, flow]) => {
        if (flowId === MAIN_FLOW && !flow.inputs.length && !flow.outputs.length &&
            !flow.instances.length && !flow.regions?.length) {
            return false;
        }
        return !calledSubflows.has(flowId);
    });

    if (proseDiagnostics.some(item => item.code === 'prose-flow-cycle')) {
        return { files, proseDiagnostics, diagnostics: proseDiagnostics, assembledFlows, referencedCitations: [] };
    }
    if (executableTopFlows.length > 0) {
        for (const [flowId, flow] of executableTopFlows) {
            if (proseNodes.has(flowId)) {
                proseDiagnostics.push({
                    code: 'prose-wire-error',
                    severity: 'error',
                    message: `flows/${flowId} has the same id as a prose node.`,
                    flowId,
                });
                continue;
            }

            // Provide default values for top-level flow inputs if any are declared
            const defaultInputs: Record<string, unknown> = {};
            const extraDefaults = (flow.extra?.defaultInputs && typeof flow.extra.defaultInputs === 'object')
                ? (flow.extra.defaultInputs as Record<string, unknown>)
                : {};
            for (const inp of flow.inputs) {
                if (inp.name in extraDefaults) {
                    defaultInputs[inp.name] = extraDefaults[inp.name];
                }
            }

            const evalRes = evaluateProseFlow(
                flowId,
                flow,
                proseNodes,
                flows,
                citations,
                defaultInputs,
                proseDiagnostics,
            );

            const body = evalRes.assembledText;
            assembledFlows.set(flowId, body);

            if (options?.contractOverride) {
                const overrideCheck = verifyProseText(body, options.contractOverride, { flowId });
                proseDiagnostics.push(...overrideCheck.diagnostics);
            }

            const citedInFlow = extractCitations(body);
            for (const cKey of citedInFlow) {
                allReferencedCitations.add(cKey);
                if (!citations.has(cKey)) {
                    proseDiagnostics.push({
                        code: 'prose-missing-citation',
                        severity: 'warning',
                        message: `flows/${flowId}: citation "[@${cKey}]" is referenced in text but has no matching citation node or bibliography entry.`,
                        flowId,
                    });
                }
            }

            const slug = flowId === MAIN_FLOW ? proseDocumentSlug(config.name) : proseDocumentSlug(flow.name || flowId);
            const docTitle = typeof flow.extra?.title === 'string'
                ? flow.extra.title
                : flowId === MAIN_FLOW
                    ? config.name
                    : flow.name;

            files.set(`${slug}.md`, renderProseMarkdown(docTitle, body, citations, citedInFlow));
            files.set(`${slug}.tex`, renderProseLatex(docTitle, body, citations, citedInFlow));
        }
    } else if (proseNodes.size > 0) {
        // Fallback when no flows are wired: assemble standalone leaf prose nodes in order
        const sections: string[] = [];
        const sortedNodeEntries = [...proseNodes.entries()].sort(([, a], [, b]) =>
            (a.order ?? Number.MAX_SAFE_INTEGER) - (b.order ?? Number.MAX_SAFE_INTEGER) || a.name.localeCompare(b.name),
        );
        for (const [nodeId, node] of sortedNodeEntries) {
            const parsed = parseProseNode(node, nodeId);
            if (parsed.kind === 'citation' || parsed.signature.returns === 'citation') continue;
            const rendered = evaluateProseNode(node, {}, citations);
            const verifyRes = verifyProseNode(node, { nodeId, candidateText: rendered });
            proseDiagnostics.push(...verifyRes.diagnostics);
            if (rendered) sections.push(rendered);
        }
        const combined = sections.join('\n\n').trim();
        const slug = proseDocumentSlug(config.name);
        assembledFlows.set(MAIN_FLOW, combined);

        if (options?.contractOverride) {
            const overrideCheck = verifyProseText(combined, options.contractOverride, { flowId: MAIN_FLOW });
            proseDiagnostics.push(...overrideCheck.diagnostics);
        }

        const cited = extractCitations(combined);
        for (const cKey of cited) {
            allReferencedCitations.add(cKey);
        }
        files.set(`${slug}.md`, renderProseMarkdown(config.name, combined, citations, cited));
        files.set(`${slug}.tex`, renderProseLatex(config.name, combined, citations, cited));
    }

    const diagnostics: CompileDiagnostic[] = proseDiagnostics.map(d => ({ severity: d.severity, message: d.message }));
    if (proseDiagnostics.some(item => item.code === 'prose-wire-error' && item.severity === 'error')) files.clear();

    return {
        files: new Map([...files.entries()].sort(([a], [b]) => a.localeCompare(b))),
        diagnostics,
        proseDiagnostics,
        assembledFlows,
        referencedCitations: [...allReferencedCitations],
    };
}
